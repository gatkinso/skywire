// The JSON and XML text forms of generated C messages (wiregen
// --generate_json, --generate_xml); docs/text-formats.md defines them. Every
// byte written, and every input accepted or refused, is the same as the C++
// runtime's (lang/cpp/text.h); the fuzz target fuzz_c_cpp_text checks that.
//
// Header-only, C99 standard library only, and independent of the C locale.
// Reading streams through the input once, without building a tree; the
// generated _FromJson and _FromXml read into a copy and change the message
// only on success, so a failure, wherever it is found, leaves it as it was.
// A number held in a string of more than about 100 bytes is copied to the
// heap while it is read.

