// Parses a whole BSON document: its length must be exactly bytes' length.
// The Document's names and string/binary values are views into bytes, so
// bytes must outlive it.
inline bool parse(std::string_view bytes, Document& doc)
{
    detail::Parser parser(bytes);
    size_t pos = 0;
    return parser.document(pos, bytes.size(), doc, 1) && pos == bytes.size();
}

// Reads a number member (a bitfield of bits bits, when not 0). An integer
// member takes an int32, int64, Decimal128 or double that is a whole number
// in its range; a float or double takes a double (rounded to the type, too
// large for it an error), int32 or int64.
template <typename T>
bool read(const Element& e, T& out, unsigned bits = 0)
{
    static_assert(std::is_arithmetic<T>::value, "read needs a number member");

    if constexpr (std::is_floating_point<T>::value)
    {
        if (e.type == type_int32 || e.type == type_int64)
        {
            out = static_cast<T>(e.integer);
            return true;
        }
        if (e.type != type_double)
            return false;
        if constexpr (std::is_same<T, float>::value)
        {
            // Halfway from the largest float to 2^128 and beyond round to
            // infinity: too large.
            if (std::isfinite(e.number) && std::fabs(e.number) >= 0x1.ffffffp+127)
                return false;
        }
        out = static_cast<T>(e.number);
        return true;
    }
    else
    {
        bool negative = false;
        uint64_t magnitude = 0;
        if (e.type == type_int32 || e.type == type_int64)
        {
            negative = e.integer < 0;
            magnitude = negative ? ~static_cast<uint64_t>(e.integer) + 1 : static_cast<uint64_t>(e.integer);
        }
        else if (e.type == type_decimal128)
        {
            if (false == detail::decimal_integer(e.decimal_high, e.decimal_low, negative, magnitude))
                return false;
        }
        else if (e.type == type_double)
        {
            const double d = e.number;
            if (false == std::isfinite(d) || std::trunc(d) != d)
                return false;
            negative = d < 0;
            const double m = std::fabs(d);
            if (m >= 18446744073709551616.0)
                return false;
            magnitude = static_cast<uint64_t>(m);
        }
        else
        {
            return false;
        }
        return detail::fit(negative, magnitude, out, bits);
    }
}

// Reads a string member of len bytes from a string or binary (subtype 0) of
// at most len bytes, zero-filling the rest.
inline bool read_bytes(const Element& e, char* dst, size_t len)
{
    if (e.type != type_string && (e.type != type_binary || e.subtype != 0))
        return false;
    if (e.bytes.size() > len)
        return false;
    std::memcpy(dst, e.bytes.data(), e.bytes.size());
    std::memset(dst + e.bytes.size(), 0, len - e.bytes.size());
    return true;
}

// Reads a nested message member from an embedded document.
template <typename Message>
bool read_document(const Element& e, Message& member)
{
    return e.type == type_document && member.from_bson(e.document);
}

