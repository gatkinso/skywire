// A subset of XML 1.0 that is enough for messages: elements, attributes,
// character data, CDATA, comments, processing instructions, the predefined
// entities and character references. A document type declaration (and so
// any other entity) is rejected.
class XmlParser
{
public:
    explicit XmlParser(std::string_view s) : s_(s) {}

    bool document(XmlNode& root)
    {
        // Every character must be UTF-8 and allowed in XML 1.0.
        for (size_t i = 0; i < s_.size();)
        {
            uint32_t cp;
            if (false == next_utf8(s_, i, cp))
                return false;
            if (cp < 0x20 && cp != 0x09 && cp != 0x0A && cp != 0x0D)
                return false;
            if (cp == 0xFFFE || cp == 0xFFFF)
                return false;
        }

        if (starts("<?xml") && i_ + 5 < s_.size() && is_space(s_[i_ + 5]))
        {
            if (false == skip_past("?>"))
                return false;
        }
        if (false == misc())
            return false;
        if (i_ >= s_.size() || s_[i_] != '<')
            return false;
        if (false == element(root, 0))
            return false;
        if (false == misc())
            return false;
        return i_ == s_.size();
    }

private:
    std::string_view s_;
    size_t i_ = 0;

    static bool is_space(char c) { return c == ' ' || c == '\t' || c == '\n' || c == '\r'; }

    static bool name_start(char c)
    {
        const unsigned char u = static_cast<unsigned char>(c);
        return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_' || c == ':' || u >= 0x80;
    }

    static bool name_char(char c) { return name_start(c) || is_digit(c) || c == '-' || c == '.'; }

    bool starts(std::string_view word) const { return s_.substr(i_, word.size()) == word; }

    void space()
    {
        while (i_ < s_.size() && is_space(s_[i_]))
            i_++;
    }

    bool skip_past(std::string_view end)
    {
        const size_t at = s_.find(end, i_);
        if (at == std::string_view::npos)
            return false;
        i_ = at + end.size();
        return true;
    }

    // Whitespace, comments and processing instructions outside the root.
    bool misc()
    {
        for (;;)
        {
            space();
            if (starts("<!--"))
            {
                i_ += 4;
                if (false == skip_past("-->"))
                    return false;
            }
            else if (starts("<?"))
            {
                i_ += 2;
                if (false == skip_past("?>"))
                    return false;
            }
            else if (starts("<!"))
            {
                return false;   // <!DOCTYPE and anything else
            }
            else
            {
                return true;
            }
        }
    }

    bool name(std::string& out)
    {
        if (i_ >= s_.size() || false == name_start(s_[i_]))
            return false;
        const size_t start = i_;
        while (i_ < s_.size() && name_char(s_[i_]))
            i_++;
        out.assign(s_.substr(start, i_ - start));
        return true;
    }

    // Decodes the reference at s_[i_] (just past '&') into out.
    bool reference(std::string& out)
    {
        const size_t semi = s_.find(';', i_);
        if (semi == std::string_view::npos)
            return false;
        const std::string_view ref = s_.substr(i_, semi - i_);
        i_ = semi + 1;

        if (ref == "lt")
            out += '<';
        else if (ref == "gt")
            out += '>';
        else if (ref == "amp")
            out += '&';
        else if (ref == "quot")
            out += '"';
        else if (ref == "apos")
            out += '\'';
        else if (ref.size() > 1 && ref[0] == '#')
        {
            const bool hex = ref[1] == 'x';
            const std::string_view digits = ref.substr(hex ? 2 : 1);
            if (digits.empty() || digits.size() > 8)
                return false;
            uint32_t cp = 0;
            auto result = std::from_chars(digits.data(), digits.data() + digits.size(), cp, hex ? 16 : 10);
            if (result.ec != std::errc() || result.ptr != digits.data() + digits.size())
                return false;
            const bool allowed = cp == 0x9 || cp == 0xA || cp == 0xD || (cp >= 0x20 && cp <= 0xD7FF) ||
                                 (cp >= 0xE000 && cp <= 0xFFFD) || (cp >= 0x10000 && cp <= 0x10FFFF);
            if (false == allowed)
                return false;
            append_utf8(out, cp);
        }
        else
        {
            return false;
        }
        return true;
    }

    // Character data up to the next '<' (or, in an attribute, the quote).
    bool chars(std::string& out, char stop, bool attribute)
    {
        while (i_ < s_.size() && s_[i_] != stop)
        {
            const char c = s_[i_];
            if (c == '<')
                return false;   // only possible in an attribute
            if (c == '&')
            {
                i_++;
                if (false == reference(out))
                    return false;
                continue;
            }
            if (c == '\r')
            {
                // CR LF and a lone CR are both a line end.
                i_++;
                if (i_ < s_.size() && s_[i_] == '\n')
                    i_++;
                out += attribute ? ' ' : '\n';
                continue;
            }
            out += (attribute && (c == '\n' || c == '\t')) ? ' ' : c;
            i_++;
        }
        return true;
    }

    bool element(XmlNode& node, unsigned depth)
    {
        if (++depth > max_depth)
            return false;
        i_++;   // '<'
        if (false == name(node.name))
            return false;

        for (;;)
        {
            const size_t before = i_;
            space();
            if (i_ >= s_.size())
                return false;
            if (starts("/>"))
            {
                i_ += 2;
                return true;
            }
            if (s_[i_] == '>')
            {
                i_++;
                break;
            }
            if (i_ == before)
                return false;   // attributes are separated by whitespace
            XmlAttribute attribute;
            if (false == name(attribute.name))
                return false;
            space();
            if (i_ >= s_.size() || s_[i_] != '=')
                return false;
            i_++;
            space();
            if (i_ >= s_.size() || (s_[i_] != '"' && s_[i_] != '\''))
                return false;
            const char quote = s_[i_++];
            if (false == chars(attribute.value, quote, true) || i_ >= s_.size())
                return false;
            i_++;
            if (node.attribute(attribute.name) != nullptr)
                return false;
            node.attributes.push_back(std::move(attribute));
        }

        for (;;)
        {
            if (i_ >= s_.size())
                return false;
            if (starts("</"))
            {
                i_ += 2;
                std::string end;
                if (false == name(end) || end != node.name)
                    return false;
                space();
                if (i_ >= s_.size() || s_[i_] != '>')
                    return false;
                i_++;
                return true;
            }
            if (starts("<!--"))
            {
                i_ += 4;
                if (false == skip_past("-->"))
                    return false;
            }
            else if (starts("<![CDATA["))
            {
                i_ += 9;
                const size_t end = s_.find("]]>", i_);
                if (end == std::string_view::npos)
                    return false;
                for (size_t k = i_; k < end; k++)
                {
                    if (s_[k] == '\r')
                    {
                        if (k + 1 < end && s_[k + 1] == '\n')
                            k++;
                        node.text += '\n';
                    }
                    else
                    {
                        node.text += s_[k];
                    }
                }
                i_ = end + 3;
            }
            else if (starts("<?"))
            {
                i_ += 2;
                if (false == skip_past("?>"))
                    return false;
            }
            else if (starts("<!"))
            {
                return false;
            }
            else if (s_[i_] == '<')
            {
                node.children.emplace_back();
                if (false == element(node.children.back(), depth))
                    return false;
            }
            else if (false == chars(node.text, '<', false))
            {
                return false;
            }
        }
    }
};

inline std::string_view trim(std::string_view s)
{
    while (false == s.empty() && (s.front() == ' ' || s.front() == '\t' || s.front() == '\n' || s.front() == '\r'))
        s.remove_prefix(1);
    while (false == s.empty() && (s.back() == ' ' || s.back() == '\t' || s.back() == '\n' || s.back() == '\r'))
        s.remove_suffix(1);
    return s;
}

