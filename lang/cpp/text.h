inline bool is_digit(char c) { return c >= '0' && c <= '9'; }

// A JSON number: -?(0|[1-9][0-9]*)(\.[0-9]+)?([eE][+-]?[0-9]+)?
inline bool is_json_number(std::string_view s)
{
    size_t i = 0;
    const size_t n = s.size();
    if (i < n && s[i] == '-')
        i++;
    if (i >= n)
        return false;
    if (s[i] == '0')
        i++;
    else if (is_digit(s[i]))
        while (i < n && is_digit(s[i]))
            i++;
    else
        return false;
    if (i < n && s[i] == '.')
    {
        i++;
        if (i >= n || false == is_digit(s[i]))
            return false;
        while (i < n && is_digit(s[i]))
            i++;
    }
    if (i < n && (s[i] == 'e' || s[i] == 'E'))
    {
        i++;
        if (i < n && (s[i] == '+' || s[i] == '-'))
            i++;
        if (i >= n || false == is_digit(s[i]))
            return false;
        while (i < n && is_digit(s[i]))
            i++;
    }
    return i == n;
}

// The exact integer a JSON number stands for ("12", "1.2e1", "120e-1"), as a
// sign and magnitude. False if it is not a whole number or needs more than
// 64 bits of magnitude.
inline bool integer_value(std::string_view s, bool& negative, uint64_t& magnitude)
{
    if (false == is_json_number(s))
        return false;

    size_t i = 0;
    negative = false;
    if (s[i] == '-')
    {
        negative = true;
        i++;
    }

    std::string digits;
    long long exponent = 0;
    while (i < s.size() && is_digit(s[i]))
        digits += s[i++];
    if (i < s.size() && s[i] == '.')
    {
        i++;
        while (i < s.size() && is_digit(s[i]))
        {
            digits += s[i++];
            exponent--;
        }
    }
    if (i < s.size())
    {
        i++;   // 'e' or 'E'
        bool exponent_negative = false;
        if (s[i] == '+' || s[i] == '-')
            exponent_negative = s[i++] == '-';
        long long e = 0;
        while (i < s.size())
        {
            e = e * 10 + (s[i++] - '0');
            if (e > 100000)
                e = 100000;   // far beyond any 64-bit value either way
        }
        exponent += exponent_negative ? -e : e;
    }

    const size_t first = digits.find_first_not_of('0');
    if (first == std::string::npos)
    {
        magnitude = 0;
        return true;
    }
    digits.erase(0, first);
    while (exponent < 0 && digits.back() == '0')
    {
        digits.pop_back();
        exponent++;
    }
    if (exponent < 0 || static_cast<long long>(digits.size()) + exponent > 20)
        return false;
    digits.append(static_cast<size_t>(exponent), '0');

    auto result = std::from_chars(digits.data(), digits.data() + digits.size(), magnitude);
    return result.ec == std::errc() && result.ptr == digits.data() + digits.size();
}

// The range a member of type T holds; bits, when not 0, makes it a bitfield
// of that width. A char takes -128 to 255, whatever its signedness here.
template <typename T>
void integer_range(unsigned bits, int64_t& lo, uint64_t& hi)
{
    if (std::is_same<T, char>::value)
    {
        lo = -128;
        hi = 255;
        return;
    }
    const unsigned width = bits ? bits : static_cast<unsigned>(sizeof(T) * 8);
    if (std::is_signed<T>::value)
    {
        lo = width == 64 ? std::numeric_limits<int64_t>::min() : -(int64_t(1) << (width - 1));
        hi = width == 64 ? uint64_t(std::numeric_limits<int64_t>::max()) : (uint64_t(1) << (width - 1)) - 1;
    }
    else
    {
        lo = 0;
        hi = width == 64 ? std::numeric_limits<uint64_t>::max() : (uint64_t(1) << width) - 1;
    }
}

template <typename T>
bool to_integer(std::string_view s, T& out, unsigned bits)
{
    bool negative;
    uint64_t magnitude;
    if (false == integer_value(s, negative, magnitude))
        return false;

    int64_t lo;
    uint64_t hi;
    integer_range<T>(bits, lo, hi);

    if (negative && magnitude != 0)
    {
        if (lo >= 0 || magnitude - 1 > static_cast<uint64_t>(-(lo + 1)))
            return false;
        out = static_cast<T>(-static_cast<int64_t>(magnitude - 1) - 1);
        return true;
    }
    if (magnitude > hi)
        return false;
    out = static_cast<T>(magnitude);
    return true;
}

template <typename T>
bool to_float(std::string_view s, T& out)
{
    if (s == "NaN")
    {
        out = std::numeric_limits<T>::quiet_NaN();
        return true;
    }
    if (s == "Infinity" || s == "-Infinity")
    {
        out = s[0] == '-' ? -std::numeric_limits<T>::infinity() : std::numeric_limits<T>::infinity();
        return true;
    }
    if (false == is_json_number(s))
        return false;

    const std::string copy(s);
    char* end = nullptr;
    T value;
    if (std::is_same<T, float>::value)
        value = static_cast<T>(strtof_c(copy.c_str(), &end));
    else
        value = static_cast<T>(strtod_c(copy.c_str(), &end));

    // Too large for the type is an error; too small rounds, as it should.
    if (end != copy.c_str() + copy.size() || std::isinf(value))
        return false;
    out = value;
    return true;
}

// Whether the decimal digits.e-exp (digits[0] before the point) reads back as v.
template <typename T>
bool reads_back(const std::string& digits, int exponent, T v)
{
    std::string s;
    if (v < 0)
        s += '-';
    s += digits[0];
    if (digits.size() > 1)
    {
        s += '.';
        s.append(digits, 1, std::string::npos);
    }
    s += 'e';
    s += std::to_string(exponent);

    char* end = nullptr;
    if (std::is_same<T, float>::value)
        return strtof_c(s.c_str(), &end) == static_cast<float>(v);
    return strtod_c(s.c_str(), &end) == static_cast<double>(v);
}

// Adds delta (+1 or -1) to the last digit, carrying; exponent follows a
// change in the number of digits. False if the result would be zero.
inline bool step(std::string& digits, int& exponent, int delta)
{
    size_t i = digits.size();
    while (i > 0)
    {
        i--;
        if (delta > 0)
        {
            if (digits[i] != '9')
            {
                digits[i]++;
                return true;
            }
            digits[i] = '0';
        }
        else
        {
            if (digits[i] != '0')
            {
                digits[i]--;
                break;
            }
            digits[i] = '9';
        }
    }
    if (delta > 0)
    {
        // All nines: 99 becomes 100, one place up.
        digits.insert(digits.begin(), '1');
        digits.pop_back();
        exponent++;
        return true;
    }
    if (digits[0] == '0')
    {
        // 10 becomes 99, one place down.
        digits.erase(0, 1);
        digits += '9';
        exponent--;
    }
    return false == digits.empty() && digits.find_first_not_of('0') != std::string::npos;
}

// A finite, nonzero v as the fewest significant digits that read back as v
// (for v's own type), and the power of ten of the first one.
template <typename T>
void shortest(T v, std::string& digits, int& exponent)
{
    const int max_digits = std::is_same<T, float>::value ? 9 : 17;
    char buf[64];

    for (int precision = 1; precision <= max_digits; precision++)
    {
        // %e gives the correctly rounded digits; only the decimal point
        // depends on the locale, and it is skipped.
        std::snprintf(buf, sizeof(buf), "%.*e", precision - 1, static_cast<double>(v));
        std::string d;
        const char* p = buf;
        while (*p != 'e' && *p != 'E' && *p != '\0')
        {
            if (is_digit(*p))
                d += *p;
            p++;
        }
        int e = (*p != '\0') ? std::atoi(p + 1) : 0;

        if (reads_back(d, e, v))
        {
            digits = d;
            exponent = e;
            break;
        }

        // Next to a power of two the nearest decimal can miss while a
        // neighbour of it reads back.
        bool found = false;
        for (int delta : { 1, -1 })
        {
            std::string nd = d;
            int ne = e;
            if (step(nd, ne, delta) && nd.size() == d.size() && reads_back(nd, ne, v))
            {
                digits = nd;
                exponent = ne;
                found = true;
                break;
            }
        }
        if (found)
            break;
        digits = d;
        exponent = e;
    }

    while (digits.size() > 1 && digits.back() == '0')
        digits.pop_back();
}

inline void append_utf8(std::string& out, uint32_t cp)
{
    if (cp < 0x80)
    {
        out += static_cast<char>(cp);
    }
    else if (cp < 0x800)
    {
        out += static_cast<char>(0xC0 | (cp >> 6));
        out += static_cast<char>(0x80 | (cp & 0x3F));
    }
    else if (cp < 0x10000)
    {
        out += static_cast<char>(0xE0 | (cp >> 12));
        out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
        out += static_cast<char>(0x80 | (cp & 0x3F));
    }
    else
    {
        out += static_cast<char>(0xF0 | (cp >> 18));
        out += static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
        out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
        out += static_cast<char>(0x80 | (cp & 0x3F));
    }
}

// Decodes one UTF-8 character at s[i], advancing i; false if it is not
// well formed (overlong, a surrogate, beyond U+10FFFF, cut short).
inline bool next_utf8(std::string_view s, size_t& i, uint32_t& cp)
{
    const unsigned char c = static_cast<unsigned char>(s[i]);
    unsigned extra;
    uint32_t min;
    if (c < 0x80)
    {
        cp = c;
        i++;
        return true;
    }
    if ((c & 0xE0) == 0xC0)
    {
        cp = c & 0x1F;
        extra = 1;
        min = 0x80;
    }
    else if ((c & 0xF0) == 0xE0)
    {
        cp = c & 0x0F;
        extra = 2;
        min = 0x800;
    }
    else if ((c & 0xF8) == 0xF0)
    {
        cp = c & 0x07;
        extra = 3;
        min = 0x10000;
    }
    else
    {
        return false;
    }
    if (i + extra >= s.size())
        return false;
    for (unsigned k = 1; k <= extra; k++)
    {
        const unsigned char cc = static_cast<unsigned char>(s[i + k]);
        if ((cc & 0xC0) != 0x80)
            return false;
        cp = (cp << 6) | (cc & 0x3F);
    }
    if (cp < min || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF))
        return false;
    i += extra + 1;
    return true;
}

// Text (UTF-8) as bytes, one per character; false if a character is above
// U+00FF or there are more than len. The rest of dst is zero-filled.
inline bool text_to_bytes(std::string_view s, char* dst, size_t len)
{
    std::string bytes;
    size_t i = 0;
    while (i < s.size())
    {
        uint32_t cp;
        if (false == next_utf8(s, i, cp) || cp > 0xFF)
            return false;
        bytes += static_cast<char>(cp);
    }
    if (bytes.size() > len)
        return false;
    std::memcpy(dst, bytes.data(), bytes.size());
    std::memset(dst + bytes.size(), 0, len - bytes.size());
    return true;
}

// The bytes of a string member, without its trailing NULs.
inline size_t used_length(const char* p, size_t len)
{
    while (len > 0 && p[len - 1] == '\0')
        len--;
    return len;
}

