// A member's value as text: integers in decimal (a char as signed), floats
// in the shortest form that reads back exactly, laid out as JavaScript's
// Number#toString does, but keeping -0; NaN, Infinity and -Infinity by name.
template <typename T>
std::string number_text(T v)
{
    static_assert(std::is_arithmetic<T>::value, "number_text needs a number");

    if constexpr (std::is_floating_point<T>::value)
    {
        if (std::isnan(v))
            return "NaN";
        if (std::isinf(v))
            return v < 0 ? "-Infinity" : "Infinity";
        if (v == 0)
            return std::signbit(v) ? "-0" : "0";

        std::string digits;
        int e = 0;
        detail::shortest(v, digits, e);

        const int k = static_cast<int>(digits.size());
        const int n = e + 1;
        std::string out = v < 0 ? "-" : "";
        if (k <= n && n <= 21)
        {
            out += digits;
            out.append(static_cast<size_t>(n - k), '0');
        }
        else if (0 < n && n <= 21)
        {
            out.append(digits, 0, static_cast<size_t>(n));
            out += '.';
            out.append(digits, static_cast<size_t>(n), std::string::npos);
        }
        else if (-6 < n && n <= 0)
        {
            out += "0.";
            out.append(static_cast<size_t>(-n), '0');
            out += digits;
        }
        else
        {
            out += digits[0];
            if (k > 1)
            {
                out += '.';
                out.append(digits, 1, std::string::npos);
            }
            out += e < 0 ? "e-" : "e+";
            out += std::to_string(e < 0 ? -e : e);
        }
        return out;
    }
    else if constexpr (std::is_same<T, char>::value)
    {
        return std::to_string(static_cast<int>(static_cast<signed char>(v)));
    }
    else
    {
        return std::to_string(v);
    }
}

