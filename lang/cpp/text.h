// Parses a whole XML document into its root element. False if it is not
// well-formed (in the subset XmlParser takes), is not UTF-8, has a document
// type declaration, or nests deeper than max_depth.
inline bool parse_xml(std::string_view text, XmlNode& root)
{
    root = XmlNode();
    return detail::XmlParser(text).document(root);
}

// Whether an element holding a message has only whitespace between its
// member elements.
inline bool is_blank(const XmlNode& node)
{
    return detail::trim(node.text).empty();
}

// Reads a number member from an element holding only its text (surrounding
// whitespace allowed), under the same rules as the JSON read.
template <typename T>
bool read(const XmlNode& node, T& out, unsigned bits = 0)
{
    static_assert(std::is_arithmetic<T>::value, "read needs a number member");
    if (false == node.children.empty())
        return false;
    const std::string_view s = detail::trim(node.text);
    if constexpr (std::is_floating_point<T>::value)
        return detail::to_float(s, out);
    else
        return detail::to_integer(s, out, bits);
}

// Reads a string member of len bytes: the element's text, each character one
// byte (U+0000 to U+00FF), or with encoding="hex" the bytes in hexadecimal.
inline bool read_bytes(const XmlNode& node, char* dst, size_t len)
{
    if (false == node.children.empty())
        return false;
    const XmlAttribute* encoding = node.attribute("encoding");
    if (encoding == nullptr)
        return detail::text_to_bytes(node.text, dst, len);
    if (encoding->value != "hex")
        return false;

    const std::string_view hex = detail::trim(node.text);
    if (hex.size() % 2 != 0 || hex.size() / 2 > len)
        return false;
    std::string bytes;
    for (size_t i = 0; i < hex.size(); i += 2)
    {
        uint8_t b = 0;
        auto result = std::from_chars(hex.data() + i, hex.data() + i + 2, b, 16);
        if (result.ec != std::errc() || result.ptr != hex.data() + i + 2)
            return false;
        bytes += static_cast<char>(b);
    }
    std::memcpy(dst, bytes.data(), bytes.size());
    std::memset(dst + bytes.size(), 0, len - bytes.size());
    return true;
}

// Writes the canonical XML form: no declaration, no whitespace between
// elements, one element per member.
class XmlWriter
{
public:
    void open(std::string_view name)
    {
        out_ += '<';
        out_ += name;
        out_ += '>';
    }

    void close(std::string_view name)
    {
        out_ += "</";
        out_ += name;
        out_ += '>';
    }

    template <typename T>
    void element(std::string_view name, T v)
    {
        open(name);
        out_ += number_text(v);
        close(name);
    }

    // A string member: its bytes up to the trailing NULs, escaped, or, if
    // any byte is not printable ASCII (XML cannot hold control characters),
    // in hexadecimal with encoding="hex".
    void bytes_element(std::string_view name, const char* p, size_t len)
    {
        static const char hex[] = "0123456789abcdef";
        len = detail::used_length(p, len);

        bool printable = true;
        for (size_t i = 0; i < len; i++)
        {
            const unsigned char c = static_cast<unsigned char>(p[i]);
            if (c < 0x20 || c > 0x7E)
                printable = false;
        }

        if (false == printable)
        {
            out_ += '<';
            out_ += name;
            out_ += " encoding=\"hex\">";
            for (size_t i = 0; i < len; i++)
            {
                const unsigned char c = static_cast<unsigned char>(p[i]);
                out_ += hex[c >> 4];
                out_ += hex[c & 0x0F];
            }
            close(name);
            return;
        }

        open(name);
        for (size_t i = 0; i < len; i++)
        {
            switch (p[i])
            {
            case '<': out_ += "&lt;"; break;
            case '>': out_ += "&gt;"; break;
            case '&': out_ += "&amp;"; break;
            case '"': out_ += "&quot;"; break;
            case '\'': out_ += "&apos;"; break;
            default: out_ += p[i]; break;
            }
        }
        close(name);
    }

    const std::string& str() const { return out_; }
    std::string take() { return std::move(out_); }

private:
    std::string out_;
};

