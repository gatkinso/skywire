struct XmlAttribute
{
    std::string name;
    std::string value;
};

// A parsed element: its attributes, child elements and character data
// (text and CDATA, entities decoded, line ends normalized), all in UTF-8.
struct XmlNode
{
    std::string name;
    std::vector<XmlAttribute> attributes;
    std::string text;
    std::vector<XmlNode> children;

    const XmlAttribute* attribute(std::string_view n) const
    {
        for (const auto& a : attributes)
            if (a.name == n)
                return &a;
        return nullptr;
    }
};

