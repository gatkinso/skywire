struct JsonMember;

// A parsed JSON value. A number keeps its text, so no precision is lost
// before it is read into a member; a string is its decoded UTF-8.
struct JsonValue
{
    enum Kind { Null, Bool, Number, String, Array, Object };
    Kind kind = Null;
    bool boolean = false;
    std::string text;
    std::vector<JsonValue> items;
    std::vector<JsonMember> members;
};

struct JsonMember
{
    std::string name;
    JsonValue value;
};

namespace detail
{

class JsonParser
{
public:
    explicit JsonParser(std::string_view s) : s_(s) {}

    bool document(JsonValue& out)
    {
        space();
        if (false == value(out, 0))
            return false;
        space();
        return i_ == s_.size();
    }

private:
    std::string_view s_;
    size_t i_ = 0;

    void space()
    {
        while (i_ < s_.size() && (s_[i_] == ' ' || s_[i_] == '\t' || s_[i_] == '\n' || s_[i_] == '\r'))
            i_++;
    }

    bool literal(std::string_view word)
    {
        if (s_.substr(i_, word.size()) != word)
            return false;
        i_ += word.size();
        return true;
    }

    bool hex4(uint32_t& v)
    {
        if (i_ + 4 > s_.size())
            return false;
        v = 0;
        for (int k = 0; k < 4; k++)
        {
            const char c = s_[i_++];
            v <<= 4;
            if (c >= '0' && c <= '9')
                v |= static_cast<uint32_t>(c - '0');
            else if (c >= 'a' && c <= 'f')
                v |= static_cast<uint32_t>(c - 'a' + 10);
            else if (c >= 'A' && c <= 'F')
                v |= static_cast<uint32_t>(c - 'A' + 10);
            else
                return false;
        }
        return true;
    }

    bool string(std::string& out)
    {
        if (i_ >= s_.size() || s_[i_] != '"')
            return false;
        i_++;
        while (i_ < s_.size())
        {
            const unsigned char c = static_cast<unsigned char>(s_[i_]);
            if (c == '"')
            {
                i_++;
                return true;
            }
            if (c < 0x20)
                return false;
            if (c >= 0x80)
            {
                const size_t start = i_;
                uint32_t cp;
                if (false == next_utf8(s_, i_, cp))
                    return false;
                out.append(s_.substr(start, i_ - start));
                continue;
            }
            i_++;
            if (c != '\\')
            {
                out += static_cast<char>(c);
                continue;
            }
            if (i_ >= s_.size())
                return false;
            const char e = s_[i_++];
            switch (e)
            {
            case '"': out += '"'; break;
            case '\\': out += '\\'; break;
            case '/': out += '/'; break;
            case 'b': out += '\b'; break;
            case 'f': out += '\f'; break;
            case 'n': out += '\n'; break;
            case 'r': out += '\r'; break;
            case 't': out += '\t'; break;
            case 'u':
            {
                uint32_t cp;
                if (false == hex4(cp))
                    return false;
                if (cp >= 0xDC00 && cp <= 0xDFFF)
                    return false;
                if (cp >= 0xD800 && cp <= 0xDBFF)
                {
                    uint32_t low;
                    if (false == literal("\\u") || false == hex4(low) || low < 0xDC00 || low > 0xDFFF)
                        return false;
                    cp = 0x10000 + ((cp - 0xD800) << 10) + (low - 0xDC00);
                }
                append_utf8(out, cp);
                break;
            }
            default:
                return false;
            }
        }
        return false;
    }

    bool number(std::string& out)
    {
        const size_t start = i_;
        while (i_ < s_.size())
        {
            const char c = s_[i_];
            if (is_digit(c) || c == '-' || c == '+' || c == '.' || c == 'e' || c == 'E')
                i_++;
            else
                break;
        }
        out.assign(s_.substr(start, i_ - start));
        return is_json_number(out);
    }

    bool value(JsonValue& out, unsigned depth)
    {
        if (i_ >= s_.size())
            return false;
        const char c = s_[i_];
        if (c == '{')
        {
            if (++depth > max_depth)
                return false;
            out.kind = JsonValue::Object;
            i_++;
            space();
            if (i_ < s_.size() && s_[i_] == '}')
            {
                i_++;
                return true;
            }
            for (;;)
            {
                JsonMember member;
                space();
                if (false == string(member.name))
                    return false;
                space();
                if (i_ >= s_.size() || s_[i_] != ':')
                    return false;
                i_++;
                space();
                if (false == value(member.value, depth))
                    return false;
                out.members.push_back(std::move(member));
                space();
                if (i_ >= s_.size())
                    return false;
                if (s_[i_] == ',')
                {
                    i_++;
                    continue;
                }
                if (s_[i_] == '}')
                {
                    i_++;
                    return true;
                }
                return false;
            }
        }
        if (c == '[')
        {
            if (++depth > max_depth)
                return false;
            out.kind = JsonValue::Array;
            i_++;
            space();
            if (i_ < s_.size() && s_[i_] == ']')
            {
                i_++;
                return true;
            }
            for (;;)
            {
                JsonValue item;
                space();
                if (false == value(item, depth))
                    return false;
                out.items.push_back(std::move(item));
                space();
                if (i_ >= s_.size())
                    return false;
                if (s_[i_] == ',')
                {
                    i_++;
                    continue;
                }
                if (s_[i_] == ']')
                {
                    i_++;
                    return true;
                }
                return false;
            }
        }
        if (c == '"')
        {
            out.kind = JsonValue::String;
            return string(out.text);
        }
        if (c == 't' || c == 'f')
        {
            out.kind = JsonValue::Bool;
            out.boolean = c == 't';
            return literal(c == 't' ? "true" : "false");
        }
        if (c == 'n')
        {
            out.kind = JsonValue::Null;
            return literal("null");
        }
        out.kind = JsonValue::Number;
        return number(out.text);
    }
};

}

// Parses a whole JSON document (surrounding whitespace allowed). False if it
// is not well-formed JSON, is not UTF-8, or nests deeper than max_depth.
inline bool parse_json(std::string_view text, JsonValue& out)
{
    out = JsonValue();
    return detail::JsonParser(text).document(out);
}

// Reads a number member: a JSON number, or a string holding one (as 64-bit
// integers are written); floats also take "NaN", "Infinity" and "-Infinity".
// An integer must be whole and in range: of the type, or, when bits is not 0,
// of a bitfield that wide.
template <typename T>
bool read(const JsonValue& v, T& out, unsigned bits = 0)
{
    static_assert(std::is_arithmetic<T>::value, "read needs a number member");
    if (v.kind != JsonValue::Number && v.kind != JsonValue::String)
        return false;
    if constexpr (std::is_floating_point<T>::value)
    {
        return detail::to_float(v.text, out);
    }
    else
    {
        return detail::to_integer(v.text, out, bits);
    }
}

// Reads a string member of len bytes: each character is one byte, so it must
// be U+0000 to U+00FF; a shorter value is zero-padded.
inline bool read_bytes(const JsonValue& v, char* dst, size_t len)
{
    return v.kind == JsonValue::String && detail::text_to_bytes(v.text, dst, len);
}

// Writes the canonical JSON form: no whitespace, members in the order written.
class JsonWriter
{
public:
    void begin_object()
    {
        out_ += '{';
        first_ = true;
    }

    void end_object()
    {
        out_ += '}';
        first_ = false;
    }

    // A member name; names are identifiers, so need no escaping.
    void key(std::string_view name)
    {
        if (false == first_)
            out_ += ',';
        first_ = false;
        out_ += '"';
        out_ += name;
        out_ += "\":";
    }

    // 64-bit integers, NaN and the infinities are written as strings.
    template <typename T>
    void value(T v)
    {
        const std::string s = number_text(v);
        const bool quoted = (std::is_integral<T>::value && sizeof(T) == 8) ||
                            (std::is_floating_point<T>::value && false == detail::is_json_number(s));
        if (quoted)
            out_ += '"';
        out_ += s;
        if (quoted)
            out_ += '"';
    }

    // A string member: its bytes up to the trailing NULs, printable ASCII as
    // is (but " and \ escaped), every other byte as \u00xx.
    void bytes(const char* p, size_t len)
    {
        static const char hex[] = "0123456789abcdef";
        len = detail::used_length(p, len);
        out_ += '"';
        for (size_t i = 0; i < len; i++)
        {
            const unsigned char c = static_cast<unsigned char>(p[i]);
            if (c == '"' || c == '\\')
            {
                out_ += '\\';
                out_ += static_cast<char>(c);
            }
            else if (c >= 0x20 && c <= 0x7E)
            {
                out_ += static_cast<char>(c);
            }
            else
            {
                out_ += "\\u00";
                out_ += hex[c >> 4];
                out_ += hex[c & 0x0F];
            }
        }
        out_ += '"';
    }

    const std::string& str() const { return out_; }
    std::string take() { return std::move(out_); }

private:
    std::string out_;
    bool first_ = true;
};

