"""The JSON, XML and BSON forms of messages generated by wiregen.

wiregen writes this module next to the generated code when it is asked for
--generate_json, --generate_xml or --generate_bson; docs/text-formats.md
defines the forms. Every byte written, and every input accepted or refused,
is the same as the C and C++ runtimes' (lang/cpp/text.h, lang/cpp/bson.h).
Standard library only.
"""

import math
import re
import struct
from fractions import Fraction

# Nesting deeper than this (objects, arrays, elements, documents) is
# rejected, so hostile input cannot exhaust the stack.
MAX_DEPTH = 128


class Invalid(Exception):
    """Input that is not the form asked for, or a value a member cannot hold."""


# ------------------------------------------------------------------ numbers

_INTEGERS = {
    "char": (True, 8),
    "unsigned char": (False, 8),
    "uint8_t": (False, 8),
    "int8_t": (True, 8),
    "uint16_t": (False, 16),
    "int16_t": (True, 16),
    "uint32_t": (False, 32),
    "int32_t": (True, 32),
    "uint64_t": (False, 64),
    "int64_t": (True, 64),
}

_NUMBER = re.compile(r"-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?\Z")
_SPACE = " \t\n\r"


def _is_number(text):
    return _NUMBER.match(text) is not None


def _range(type_, bits):
    """The values a member of type_ (a bitfield bits wide, if bits) holds; a
    char takes -128 to 255, as in the C and C++ runtimes."""
    if type_ == "char":
        return -128, 255
    signed, width = _INTEGERS[type_]
    if bits:
        width = bits
    if signed:
        return -(1 << (width - 1)), (1 << (width - 1)) - 1
    return 0, (1 << width) - 1


def _integer_value(text):
    """The exact integer a JSON number stands for ("12", "1.2e1", "120e-1"),
    or None if it is not a whole number or needs more than 64 bits."""
    if not _is_number(text):
        return None
    negative = text.startswith("-")
    body = text[1:] if negative else text
    mantissa, _, exponent_text = body.replace("E", "e").partition("e")
    whole, _, fraction = mantissa.partition(".")
    exponent = -len(fraction)
    if exponent_text:
        sign = -1 if exponent_text.startswith("-") else 1
        digits = exponent_text.lstrip("+-").lstrip("0") or "0"
        # Beyond 100000 either way is beyond any 64-bit value.
        e = 100000 if len(digits) > 6 else min(int(digits), 100000)
        exponent += sign * e
    digits = (whole + fraction).lstrip("0")
    if not digits:
        return 0
    significant = digits.rstrip("0")
    places = len(digits) - len(significant) + exponent
    if places < 0 or len(significant) + places > 20:
        return None
    magnitude = int(significant) * 10 ** places
    if magnitude > 0xFFFFFFFFFFFFFFFF:
        return None
    return -magnitude if negative else magnitude


def _fit_integer(value, type_, bits):
    lo, hi = _range(type_, bits)
    if value is None or value < lo or value > hi:
        raise Invalid("%r is not a %s" % (value, type_))
    if type_ == "char" and value > 127:
        return value - 256  # stored as the signed char C and C++ hold
    return value


def _round_f32(value):
    """A Fraction rounded to the nearest float (ties to even), as a Python
    float; infinity if it rounds beyond the largest float."""
    if value == 0:
        return 0.0
    negative = value < 0
    value = -value if negative else value
    n, d = value.numerator, value.denominator
    e = n.bit_length() - d.bit_length()
    if (n < (d << e)) if e >= 0 else ((n << -e) < d):
        e -= 1
    if e >= 128:
        return -math.inf if negative else math.inf
    q = max(e, -126) - 23  # the weight of the last of 24 bits
    if q >= 0:
        units, rest = divmod(n, d << q)
        whole = d << q
    else:
        units, rest = divmod(n << -q, d)
        whole = d
    if 2 * rest > whole or (2 * rest == whole and units & 1):
        units += 1
    result = math.inf if units * 2.0 ** q >= 2.0 ** 128 else math.ldexp(units, q)
    return -result if negative else result


def _decimal_to_f32(text):
    """A JSON number rounded straight to the nearest float, not through a
    double, which could round twice."""
    mantissa, _, exponent_text = text.replace("E", "e").partition("e")
    negative = mantissa.startswith("-")
    digits = mantissa.lstrip("-").replace(".", "")
    if digits.strip("0") == "":
        return -0.0 if negative else 0.0
    exponent_digits = exponent_text.lstrip("+-").lstrip("0") or "0"
    limit = len(text) + 60
    if len(exponent_digits) > 6 or int(exponent_digits) > limit:
        # Far beyond a float's range either way.
        result = 0.0 if exponent_text.startswith("-") else math.inf
        return -result if negative else result
    return _round_f32(Fraction(text))


def _to_real(text, is_float):
    """A float or double member's value: "NaN", "Infinity" and "-Infinity" by
    name, otherwise a JSON number rounded to the type; too large is Invalid."""
    if text == "NaN":
        return math.nan
    if text in ("Infinity", "-Infinity"):
        return -math.inf if text[0] == "-" else math.inf
    if not _is_number(text):
        raise Invalid("%r is not a number" % text)
    value = _decimal_to_f32(text) if is_float else float(text)
    if math.isinf(value):
        raise Invalid("%r is too large" % text)
    return value


def _to_number(text, type_, bits):
    if type_ in ("float", "double"):
        return _to_real(text, type_ == "float")
    return _fit_integer(_integer_value(text), type_, bits)


def _as_f32(value):
    """A float member's value as the float it is on the wire."""
    return struct.unpack("<f", struct.pack("<f", value))[0]


def _reads_back(digits, exponent, value, is_float):
    """Whether the decimal digits * 10^(exponent - len(digits) + 1) reads back
    as value."""
    text = ("-" if value < 0 else "") + digits + "e" + str(exponent - (len(digits) - 1))
    if is_float:
        return _decimal_to_f32(text) == value
    return float(text) == value


def _step(digits, exponent, delta):
    """Adds delta (+1 or -1) to the last digit, carrying: the digits, the
    exponent and False if the result is zero."""
    d = list(digits)
    i = len(d)
    while i > 0:
        i -= 1
        if delta > 0:
            if d[i] != "9":
                d[i] = chr(ord(d[i]) + 1)
                return "".join(d), exponent, True
            d[i] = "0"
        else:
            if d[i] != "0":
                d[i] = chr(ord(d[i]) - 1)
                break
            d[i] = "9"
    if delta > 0:
        # All nines: 99 becomes 100, one place up.
        return "1" + "".join(d[:-1]), exponent + 1, True
    if d[0] == "0":
        # 10 becomes 99, one place down.
        d = d[1:] + ["9"]
        exponent -= 1
    text = "".join(d)
    return text, exponent, text.strip("0") != ""


def _shortest(value, is_float):
    """A finite, nonzero value as the fewest significant digits that read back
    as it, and the power of ten of the first one."""
    digits, exponent = "", 0
    for precision in range(1, (9 if is_float else 17) + 1):
        mantissa, _, e = ("%.*e" % (precision - 1, value)).partition("e")
        d = "".join(c for c in mantissa if c.isdigit())
        e = int(e)
        if _reads_back(d, e, value, is_float):
            digits, exponent = d, e
            break
        # Next to a power of two the nearest decimal can miss while a
        # neighbour of it reads back.
        found = False
        for delta in (1, -1):
            nd, ne, nonzero = _step(d, e, delta)
            if nonzero and len(nd) == len(d) and _reads_back(nd, ne, value, is_float):
                digits, exponent, found = nd, ne, True
                break
        if found:
            break
        digits, exponent = d, e
    while len(digits) > 1 and digits.endswith("0"):
        digits = digits[:-1]
    return digits, exponent


def real_text(value, is_float):
    """A float or double as text: the shortest form that reads back exactly,
    laid out as JavaScript's Number#toString does, but keeping -0; NaN,
    Infinity and -Infinity by name."""
    if math.isnan(value):
        return "NaN"
    if math.isinf(value):
        return "-Infinity" if value < 0 else "Infinity"
    if value == 0:
        return "-0" if math.copysign(1.0, value) < 0 else "0"
    digits, e = _shortest(value, is_float)
    k, n = len(digits), e + 1
    sign = "-" if value < 0 else ""
    if k <= n <= 21:
        return sign + digits + "0" * (n - k)
    if 0 < n <= 21:
        return sign + digits[:n] + "." + digits[n:]
    if -6 < n <= 0:
        return sign + "0." + "0" * -n + digits
    out = digits[0] + ("." + digits[1:] if k > 1 else "")
    return sign + out + ("e-" if e < 0 else "e+") + str(abs(e))


def _number_text(type_, value):
    """A member's value as text: integers in decimal (a char as signed)."""
    if type_ == "float":
        return real_text(_as_f32(value), True)
    if type_ == "double":
        return real_text(float(value), False)
    lo, hi = _range(type_, 0)
    if value < lo or value > hi:
        raise ValueError("%r is not a %s" % (value, type_))
    if type_ == "char" and value > 127:
        value -= 256
    return str(value)


def _used(data):
    """A string member's bytes, without its trailing NULs."""
    return bytes(data).rstrip(b"\x00")


def _text_to_bytes(text, length):
    """Text, each character one byte (U+0000 to U+00FF), at most length of
    them, zero-padded to length."""
    if len(text) > length or any(ord(c) > 0xFF for c in text):
        raise Invalid("not %d bytes" % length)
    return text.encode("latin-1").ljust(length, b"\x00")


def _decode(text):
    """Input as a str of characters: UTF-8 bytes decoded, or a str that is
    valid Unicode (no lone surrogates)."""
    try:
        if isinstance(text, str):
            text.encode("utf-8")
            return text
        return bytes(text).decode("utf-8")
    except (UnicodeError, TypeError) as e:
        raise Invalid("not UTF-8") from e


# ------------------------------------------------------------------ JSON

# A parsed JSON value is a pair: ("object", [(name, value), ...]),
# ("array", [value, ...]), ("string", str), ("number", its text),
# ("bool", bool) or ("null", None).


class _JsonParser:
    def __init__(self, s):
        self.s = s
        self.i = 0

    def space(self):
        s, i = self.s, self.i
        while i < len(s) and s[i] in _SPACE:
            i += 1
        self.i = i

    def expect(self, c):
        if self.i >= len(self.s) or self.s[self.i] != c:
            raise Invalid("expected %r" % c)
        self.i += 1

    def literal(self, word):
        if not self.s.startswith(word, self.i):
            raise Invalid("expected %r" % word)
        self.i += len(word)

    def hex4(self):
        h = self.s[self.i:self.i + 4]
        if len(h) != 4 or any(c not in "0123456789abcdefABCDEF" for c in h):
            raise Invalid("bad \\u escape")
        self.i += 4
        return int(h, 16)

    def string(self):
        self.expect('"')
        out = []
        s = self.s
        while self.i < len(s):
            c = s[self.i]
            self.i += 1
            if c == '"':
                return "".join(out)
            if ord(c) < 0x20:
                raise Invalid("control character in a string")
            if c != "\\":
                out.append(c)
                continue
            if self.i >= len(s):
                break
            e = s[self.i]
            self.i += 1
            simple = {'"': '"', "\\": "\\", "/": "/", "b": "\b", "f": "\f", "n": "\n", "r": "\r", "t": "\t"}
            if e in simple:
                out.append(simple[e])
            elif e == "u":
                cp = self.hex4()
                if 0xDC00 <= cp <= 0xDFFF:
                    raise Invalid("lone low surrogate")
                if 0xD800 <= cp <= 0xDBFF:
                    self.literal("\\u")
                    low = self.hex4()
                    if not 0xDC00 <= low <= 0xDFFF:
                        raise Invalid("lone high surrogate")
                    cp = 0x10000 + ((cp - 0xD800) << 10) + (low - 0xDC00)
                out.append(chr(cp))
            else:
                raise Invalid("bad escape")
        raise Invalid("unterminated string")

    def number(self):
        start = self.i
        s = self.s
        while self.i < len(s) and s[self.i] in "0123456789+-.eE":
            self.i += 1
        text = s[start:self.i]
        if not _is_number(text):
            raise Invalid("bad number")
        return text

    def value(self, depth):
        if self.i >= len(self.s):
            raise Invalid("expected a value")
        c = self.s[self.i]
        if c == "{" or c == "[":
            depth += 1
            if depth > MAX_DEPTH:
                raise Invalid("nested too deeply")
            close = "}" if c == "{" else "]"
            items = []
            self.i += 1
            self.space()
            if self.i < len(self.s) and self.s[self.i] == close:
                self.i += 1
                return ("object" if c == "{" else "array", items)
            while True:
                self.space()
                if c == "{":
                    name = self.string()
                    self.space()
                    self.expect(":")
                    self.space()
                    items.append((name, self.value(depth)))
                else:
                    items.append(self.value(depth))
                self.space()
                if self.i < len(self.s) and self.s[self.i] == ",":
                    self.i += 1
                    continue
                self.expect(close)
                return ("object" if c == "{" else "array", items)
        if c == '"':
            return ("string", self.string())
        if c in "tf":
            self.literal("true" if c == "t" else "false")
            return ("bool", c == "t")
        if c == "n":
            self.literal("null")
            return ("null", None)
        return ("number", self.number())


def parse_json(text):
    """A whole JSON document (str, or UTF-8 bytes), surrounding whitespace
    allowed. Invalid if it is not well-formed JSON or nests too deeply."""
    p = _JsonParser(_decode(text))
    p.space()
    value = p.value(0)
    p.space()
    if p.i != len(p.s):
        raise Invalid("text after the value")
    return value


def json_members(value):
    """The members of an object, in order, repeats and all."""
    if value[0] != "object":
        raise Invalid("not an object")
    return value[1]


def json_number(value, type_, bits=0):
    """A number member: a JSON number, or a string holding one (as 64-bit
    integers, NaN and the infinities are written). An integer must be whole
    and in range, of the type or of a bitfield bits wide."""
    if value[0] not in ("number", "string"):
        raise Invalid("not a number")
    return _to_number(value[1], type_, bits)


def json_bytes(value, length):
    """A string member of length bytes: each character one byte."""
    if value[0] != "string":
        raise Invalid("not a string")
    return _text_to_bytes(value[1], length)


class JsonWriter:
    """Writes the canonical JSON form: no whitespace, members in order."""

    def __init__(self):
        self._out = []
        self._first = True

    def begin_object(self):
        self._out.append("{")
        self._first = True

    def end_object(self):
        self._out.append("}")
        self._first = False

    def key(self, name):
        if not self._first:
            self._out.append(",")
        self._first = False
        self._out.append('"%s":' % name)

    def number(self, name, type_, value):
        """64-bit integers, NaN and the infinities are written as strings."""
        self.key(name)
        text = _number_text(type_, value)
        quoted = type_ in ("uint64_t", "int64_t") or not _is_number(text)
        self._out.append('"%s"' % text if quoted else text)

    def bytes(self, name, data):
        """A string member: its bytes up to the trailing NULs, printable ASCII
        as is (but " and \\ escaped), every other byte as \\u00xx."""
        self.key(name)
        out = ['"']
        for b in _used(data):
            if b in (0x22, 0x5C):
                out.append("\\" + chr(b))
            elif 0x20 <= b <= 0x7E:
                out.append(chr(b))
            else:
                out.append("\\u%04x" % b)
        out.append('"')
        self._out.append("".join(out))

    def text(self):
        return "".join(self._out)


# ------------------------------------------------------------------ XML


class XmlNode:
    """A parsed element: its attributes, child elements and character data
    (text and CDATA, entities decoded, line ends normalized)."""

    def __init__(self, name):
        self.name = name
        self.attributes = []
        self.text = []
        self.children = []

    def attribute(self, name):
        for n, v in self.attributes:
            if n == name:
                return v
        return None


def _name_start(c):
    return ("a" <= c <= "z") or ("A" <= c <= "Z") or c in "_:" or ord(c) >= 0x80


def _name_char(c):
    return _name_start(c) or ("0" <= c <= "9") or c in "-."


class _XmlParser:
    """A subset of XML 1.0 that is enough for messages: elements, attributes,
    character data, CDATA, comments, processing instructions, the predefined
    entities and character references. A document type declaration, and so
    any other entity, is rejected."""

    def __init__(self, s):
        self.s = s
        self.i = 0

    def starts(self, word):
        return self.s.startswith(word, self.i)

    def space(self):
        s, i = self.s, self.i
        while i < len(s) and s[i] in _SPACE:
            i += 1
        self.i = i

    def skip_past(self, end):
        at = self.s.find(end, self.i)
        if at < 0:
            raise Invalid("unterminated")
        self.i = at + len(end)

    def misc(self):
        while True:
            self.space()
            if self.starts("<!--"):
                self.i += 4
                self.skip_past("-->")
            elif self.starts("<?"):
                self.i += 2
                self.skip_past("?>")
            elif self.starts("<!"):
                raise Invalid("a document type declaration")
            else:
                return

    def name(self):
        s = self.s
        if self.i >= len(s) or not _name_start(s[self.i]):
            raise Invalid("expected a name")
        start = self.i
        while self.i < len(s) and _name_char(s[self.i]):
            self.i += 1
        return s[start:self.i]

    def reference(self, out):
        semi = self.s.find(";", self.i)
        if semi < 0:
            raise Invalid("unterminated reference")
        ref = self.s[self.i:semi]
        self.i = semi + 1
        named = {"lt": "<", "gt": ">", "amp": "&", "quot": '"', "apos": "'"}
        if ref in named:
            out.append(named[ref])
            return
        if len(ref) > 1 and ref[0] == "#":
            hexadecimal = ref[1] == "x"
            digits = ref[2:] if hexadecimal else ref[1:]
            allowed = "0123456789abcdefABCDEF" if hexadecimal else "0123456789"
            if not 0 < len(digits) <= 8 or any(c not in allowed for c in digits):
                raise Invalid("bad character reference")
            cp = int(digits, 16 if hexadecimal else 10)
            if not (cp in (0x9, 0xA, 0xD) or 0x20 <= cp <= 0xD7FF or 0xE000 <= cp <= 0xFFFD or 0x10000 <= cp <= 0x10FFFF):
                raise Invalid("character not allowed")
            out.append(chr(cp))
            return
        raise Invalid("unknown entity")

    def chars(self, out, stop, attribute):
        """Character data up to stop (not consumed)."""
        s = self.s
        while self.i < len(s) and s[self.i] != stop:
            c = s[self.i]
            if c == "<":
                raise Invalid("< in an attribute")
            if c == "&":
                self.i += 1
                self.reference(out)
                continue
            if c == "\r":
                # CR LF and a lone CR are both a line end.
                self.i += 1
                if self.i < len(s) and s[self.i] == "\n":
                    self.i += 1
                out.append(" " if attribute else "\n")
                continue
            out.append(" " if attribute and c in "\n\t" else c)
            self.i += 1

    def element(self, depth):
        depth += 1
        if depth > MAX_DEPTH:
            raise Invalid("nested too deeply")
        self.i += 1  # '<'
        node = XmlNode(self.name())
        s = self.s
        while True:
            before = self.i
            self.space()
            if self.i >= len(s):
                raise Invalid("unterminated start tag")
            if self.starts("/>"):
                self.i += 2
                return node
            if s[self.i] == ">":
                self.i += 1
                break
            if self.i == before:
                raise Invalid("attributes must be separated by whitespace")
            name = self.name()
            self.space()
            if self.i >= len(s) or s[self.i] != "=":
                raise Invalid("expected =")
            self.i += 1
            self.space()
            if self.i >= len(s) or s[self.i] not in "\"'":
                raise Invalid("expected a quote")
            quote = s[self.i]
            self.i += 1
            value = []
            self.chars(value, quote, True)
            if self.i >= len(s):
                raise Invalid("unterminated attribute")
            self.i += 1
            if node.attribute(name) is not None:
                raise Invalid("repeated attribute")
            node.attributes.append((name, "".join(value)))

        while True:
            if self.i >= len(s):
                raise Invalid("unterminated element")
            if self.starts("</"):
                self.i += 2
                if self.name() != node.name:
                    raise Invalid("mismatched end tag")
                self.space()
                if self.i >= len(s) or s[self.i] != ">":
                    raise Invalid("bad end tag")
                self.i += 1
                return node
            if self.starts("<!--"):
                self.i += 4
                self.skip_past("-->")
            elif self.starts("<![CDATA["):
                self.i += 9
                end = s.find("]]>", self.i)
                if end < 0:
                    raise Invalid("unterminated CDATA")
                node.text.append(s[self.i:end].replace("\r\n", "\n").replace("\r", "\n"))
                self.i = end + 3
            elif self.starts("<?"):
                self.i += 2
                self.skip_past("?>")
            elif self.starts("<!"):
                raise Invalid("a declaration in content")
            elif s[self.i] == "<":
                node.children.append(self.element(depth))
            else:
                self.chars(node.text, "<", False)


def _check_xml_chars(s):
    for c in s:
        cp = ord(c)
        if (cp < 0x20 and cp not in (0x9, 0xA, 0xD)) or cp in (0xFFFE, 0xFFFF):
            raise Invalid("character not allowed in XML")


def parse_xml(text, root):
    """A whole XML document (str, or UTF-8 bytes) whose root element is root.
    Invalid if it is not well-formed in the subset _XmlParser takes."""
    s = _decode(text)
    _check_xml_chars(s)
    p = _XmlParser(s)
    if p.starts("<?xml") and len(s) > 5 and s[5] in _SPACE:
        p.skip_past("?>")
    p.misc()
    if p.i >= len(s) or s[p.i] != "<":
        raise Invalid("no root element")
    node = p.element(0)
    p.misc()
    if p.i != len(s):
        raise Invalid("text after the root element")
    if node.name != root:
        raise Invalid("root element is not %s" % root)
    return node


def _trim(text):
    return text.strip(_SPACE)


def xml_members(node):
    """The member elements of an element holding a message, which must have
    only whitespace between them: (name, element) pairs."""
    if _trim("".join(node.text)) != "":
        raise Invalid("text in a message element")
    return [(child.name, child) for child in node.children]


def xml_number(node, type_, bits=0):
    """A number member: an element holding only its text (surrounding
    whitespace allowed), read as in JSON."""
    if node.children:
        raise Invalid("an element in a number")
    return _to_number(_trim("".join(node.text)), type_, bits)


def xml_bytes(node, length):
    """A string member of length bytes: the element's text, each character
    one byte, or with encoding="hex" the bytes in hexadecimal."""
    if node.children:
        raise Invalid("an element in a string")
    encoding = node.attribute("encoding")
    text = "".join(node.text)
    if encoding is None:
        return _text_to_bytes(text, length)
    if encoding != "hex":
        raise Invalid("unknown encoding")
    digits = _trim(text)
    if len(digits) % 2 or len(digits) // 2 > length or any(c not in "0123456789abcdefABCDEF" for c in digits):
        raise Invalid("bad hex")
    return bytes.fromhex(digits).ljust(length, b"\x00")


class XmlWriter:
    """Writes the canonical XML form: no declaration, no whitespace between
    elements, one element per member."""

    def __init__(self):
        self._out = []

    def open(self, name):
        self._out.append("<%s>" % name)

    def close(self, name):
        self._out.append("</%s>" % name)

    def number(self, name, type_, value):
        self._out.append("<%s>%s</%s>" % (name, _number_text(type_, value), name))

    def bytes(self, name, data):
        """A string member: its bytes up to the trailing NULs, escaped, or, if
        any byte is not printable ASCII, in hexadecimal with encoding="hex"."""
        used = _used(data)
        if any(b < 0x20 or b > 0x7E for b in used):
            self._out.append('<%s encoding="hex">%s</%s>' % (name, used.hex(), name))
            return
        escapes = {"<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;", "'": "&apos;"}
        text = "".join(escapes.get(c, c) for c in used.decode("ascii"))
        self._out.append("<%s>%s</%s>" % (name, text, name))

    def text(self):
        return "".join(self._out)


# ------------------------------------------------------------------ BSON

DOUBLE, STRING, DOCUMENT, ARRAY, BINARY = 0x01, 0x02, 0x03, 0x04, 0x05
UNDEFINED, OBJECT_ID, BOOL, DATETIME, NULL = 0x06, 0x07, 0x08, 0x09, 0x0A
REGEX, DB_POINTER, JAVASCRIPT, SYMBOL, CODE_WITH_SCOPE = 0x0B, 0x0C, 0x0D, 0x0E, 0x0F
INT32, TIMESTAMP, INT64, DECIMAL128 = 0x10, 0x11, 0x12, 0x13
MIN_KEY, MAX_KEY = 0xFF, 0x7F

# The high word of a Decimal128 holding an integer: exponent 0 (6176
# biased), positive.
_DECIMAL128_INTEGER_HIGH = 6176 << 49
# The quiet NaN every NaN is written as.
_CANONICAL_NAN = b"\x00\x00\x00\x00\x00\x00\xf8\x7f"


class BsonElement:
    """One element. Which fields hold its value depends on its type: data for
    a string (without its NUL) or binary (with subtype); integer for int32
    and int64; number for double; decimal for Decimal128 (low, high);
    document for an embedded document or array."""

    __slots__ = ("name", "type", "data", "subtype", "integer", "number", "decimal", "document")

    def __init__(self, type_):
        self.type = type_
        self.name = ""
        self.data = b""
        self.subtype = 0
        self.integer = 0
        self.number = 0.0
        self.decimal = (0, 0)
        self.document = None


def _is_utf8(data):
    try:
        data.decode("utf-8")
        return True
    except UnicodeDecodeError:
        return False


class _BsonParser:
    """Reads a document or an element's value between pos and end, checking
    every length against the bytes there are."""

    def __init__(self, data):
        self.s = data

    def int32(self, at):
        return struct.unpack_from("<i", self.s, at)[0]

    def document(self, pos, end, depth):
        if depth > MAX_DEPTH or end - pos < 5:
            raise Invalid("bad document")
        length = self.int32(pos)
        if length < 5 or length > end - pos:
            raise Invalid("bad document length")
        last = pos + length - 1
        if self.s[last] != 0:
            raise Invalid("no document terminator")
        elements = []
        p = pos + 4
        while p < last:
            e, p = self.element(p, last, depth)
            elements.append(e)
        return elements, last + 1

    def cstring(self, p, end):
        nul = self.s.find(b"\x00", p, end)
        if nul < 0:
            raise Invalid("unterminated cstring")
        text = bytes(self.s[p:nul])
        if not _is_utf8(text):
            raise Invalid("not UTF-8")
        return text, nul + 1

    def string(self, p, end):
        if end - p < 4:
            raise Invalid("bad string")
        length = self.int32(p)
        if length < 1 or length > end - p - 4:
            raise Invalid("bad string length")
        nul = p + 4 + length - 1
        if self.s[nul] != 0:
            raise Invalid("unterminated string")
        text = bytes(self.s[p + 4:nul])
        if not _is_utf8(text):
            raise Invalid("not UTF-8")
        return text, nul + 1

    def fixed(self, p, end, width):
        if end - p < width:
            raise Invalid("cut short")
        return p + width

    def element(self, p, end, depth):
        e = BsonElement(self.s[p])
        name, p = self.cstring(p + 1, end)
        e.name = name.decode("utf-8")
        at = p
        t = e.type
        if t == DOUBLE:
            p = self.fixed(p, end, 8)
            e.number = struct.unpack_from("<d", self.s, at)[0]
        elif t in (STRING, JAVASCRIPT, SYMBOL):
            e.data, p = self.string(p, end)
        elif t in (DOCUMENT, ARRAY):
            e.document, p = self.document(p, end, depth + 1)
        elif t == BINARY:
            if end - p < 5:
                raise Invalid("bad binary")
            length = self.int32(p)
            if length < 0 or length > end - p - 5:
                raise Invalid("bad binary length")
            e.subtype = self.s[p + 4]
            e.data = bytes(self.s[p + 5:p + 5 + length])
            p += 5 + length
        elif t in (UNDEFINED, NULL, MIN_KEY, MAX_KEY):
            pass
        elif t == OBJECT_ID:
            p = self.fixed(p, end, 12)
        elif t == BOOL:
            p = self.fixed(p, end, 1)
            if self.s[at] > 1:
                raise Invalid("bad bool")
        elif t in (DATETIME, TIMESTAMP):
            p = self.fixed(p, end, 8)
        elif t == INT32:
            p = self.fixed(p, end, 4)
            e.integer = self.int32(at)
        elif t == INT64:
            p = self.fixed(p, end, 8)
            e.integer = struct.unpack_from("<q", self.s, at)[0]
        elif t == DECIMAL128:
            p = self.fixed(p, end, 16)
            e.decimal = struct.unpack_from("<QQ", self.s, at)
        elif t == REGEX:
            _, p = self.cstring(p, end)
            _, p = self.cstring(p, end)
        elif t == DB_POINTER:
            _, p = self.string(p, end)
            p = self.fixed(p, end, 12)
        elif t == CODE_WITH_SCOPE:
            # int32 total length, then a string and a document filling it.
            if end - p < 4:
                raise Invalid("bad code with scope")
            length = self.int32(p)
            if length < 4 or length > end - p:
                raise Invalid("bad code with scope length")
            stop = p + length
            _, p = self.string(p + 4, stop)
            _, p = self.document(p, stop, depth + 1)
            if p != stop:
                raise Invalid("bad code with scope length")
        else:
            # An unknown type: its length is unknown, so nothing after it
            # can be read.
            raise Invalid("unknown element type")
        return e, p


def parse_bson(data):
    """A whole BSON document (bytes): its length must be exactly the bytes'.
    Its elements, in order, repeats and all."""
    try:
        data = bytes(data)
    except TypeError as e:
        raise Invalid("not bytes") from e
    elements, pos = _BsonParser(data).document(0, len(data), 1)
    if pos != len(data):
        raise Invalid("bytes after the document")
    return elements


def bson_members(elements):
    """(name, element) pairs."""
    return [(e.name, e) for e in elements]


def _decimal_integer(low, high):
    """A Decimal128 (BID) as a whole number of at most 64 bits, or None if it
    is infinite, NaN, not canonical, not whole, or larger."""
    negative = high >> 63
    if (high >> 61) & 3 == 3:
        return None
    exponent = ((high >> 49) & 0x3FFF) - 6176
    coefficient = ((high & 0x1FFFFFFFFFFFF) << 64) | low
    if coefficient > 10 ** 34 - 1:
        return None
    if coefficient == 0:
        return 0
    if exponent < 0:
        divisor = 10 ** -exponent
        if coefficient % divisor:
            return None
        coefficient //= divisor
    elif exponent > 0:
        if exponent > 20:
            return None
        coefficient *= 10 ** exponent
    if coefficient > 0xFFFFFFFFFFFFFFFF:
        return None
    return -coefficient if negative else coefficient


def bson_number(e, type_, bits=0):
    """A number member. An integer takes an int32, int64, Decimal128 or
    double that is a whole number in its range; a float or double takes a
    double (rounded to the type, too large for it Invalid), int32 or int64."""
    if type_ in ("float", "double"):
        if e.type in (INT32, INT64):
            return _round_f32(Fraction(e.integer)) if type_ == "float" else float(e.integer)
        if e.type != DOUBLE:
            raise Invalid("not a number")
        if type_ == "double":
            return e.number
        # Halfway from the largest float to 2^128 and beyond round to
        # infinity: too large.
        if math.isfinite(e.number) and abs(e.number) >= math.ldexp(0x1FFFFFF, 103):
            raise Invalid("too large for a float")
        return e.number if math.isnan(e.number) else _as_f32(e.number)
    if e.type in (INT32, INT64):
        value = e.integer
    elif e.type == DECIMAL128:
        value = _decimal_integer(*e.decimal)
    elif e.type == DOUBLE:
        d = e.number
        if not math.isfinite(d) or d != math.trunc(d) or abs(d) >= 18446744073709551616.0:
            raise Invalid("not a whole number")
        value = int(d)
    else:
        raise Invalid("not a number")
    return _fit_integer(value, type_, bits)


def bson_bytes(e, length):
    """A string member of length bytes from a string or binary (subtype 0) of
    at most length bytes, zero-filled."""
    if e.type != STRING and (e.type != BINARY or e.subtype != 0):
        raise Invalid("not a string")
    if len(e.data) > length:
        raise Invalid("too long")
    return e.data.ljust(length, b"\x00")


def bson_document(e):
    """A nested message member's elements."""
    if e.type != DOCUMENT:
        raise Invalid("not a document")
    return e.document


class BsonWriter:
    """Builds a BSON document: each, the outermost included, is
    begin_document() ... end_document(); an embedded one is named first with
    document(name)."""

    def __init__(self):
        self._out = bytearray()
        self._starts = []

    def begin_document(self):
        self._starts.append(len(self._out))
        self._out += b"\x00\x00\x00\x00"

    def end_document(self):
        self._out.append(0)
        start = self._starts.pop()
        struct.pack_into("<i", self._out, start, len(self._out) - start)

    def _head(self, type_, name):
        self._out.append(type_)
        self._out += name.encode("utf-8") + b"\x00"

    def document(self, name):
        self._head(DOCUMENT, name)

    def number(self, name, type_, value):
        """int32 for types up to 32 bits that int32 holds (a char as signed),
        int64 for uint32_t and int64_t, and for uint64_t int64 or, above
        2^63-1, a Decimal128; double for float and double."""
        if type_ in ("float", "double"):
            d = _as_f32(value) if type_ == "float" else float(value)
            self._head(DOUBLE, name)
            self._out += _CANONICAL_NAN if math.isnan(d) else struct.pack("<d", d)
            return
        lo, hi = _range(type_, 0)
        if value < lo or value > hi:
            raise ValueError("%r is not a %s" % (value, type_))
        if type_ == "char" and value > 127:
            value -= 256
        if type_ in ("uint32_t", "int64_t") or (type_ == "uint64_t" and value <= 0x7FFFFFFFFFFFFFFF):
            self._head(INT64, name)
            self._out += struct.pack("<q", value)
        elif type_ == "uint64_t":
            self._head(DECIMAL128, name)
            self._out += struct.pack("<QQ", value, _DECIMAL128_INTEGER_HIGH)
        else:
            self._head(INT32, name)
            self._out += struct.pack("<i", value)

    def bytes(self, name, data):
        """A string member: its bytes up to the trailing NULs, as a string if
        they are UTF-8 holding no NUL, otherwise as binary (subtype 0)."""
        used = _used(data)
        if b"\x00" not in used and _is_utf8(used):
            self._head(STRING, name)
            self._out += struct.pack("<i", len(used) + 1) + used + b"\x00"
        else:
            self._head(BINARY, name)
            self._out += struct.pack("<i", len(used)) + b"\x00" + used

    def data(self):
        return bytes(self._out)
