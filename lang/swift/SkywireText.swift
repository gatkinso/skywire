    static let bsonMaxKey: UInt8 = 0x7F

    /// The high word of a Decimal128 holding an integer: exponent 0 (6176
    /// biased), positive.
    static let decimal128IntegerHigh: UInt64 = 6176 << 49
    /// The quiet NaN every NaN is written as.
    static let canonicalNaN: UInt64 = 0x7FF8_0000_0000_0000
    /// Halfway from the largest float to 2^128: this and beyond round to
    /// infinity.
    static let floatLimit = Double(bitPattern: 0x47EF_FFFF_F000_0000)
    /// 10^34, the bound on a Decimal128 coefficient, as two words.
    static let tenToThe34: (UInt64, UInt64) = (0x0001_ED09_BEAD_87C0, 0x378D_8E64_0000_0000)

    /// One element. Which fields hold its value depends on its type: data for
    /// a string (without its NUL) or binary (with subtype); integer for
    /// int32 and int64; number for double; low and high for Decimal128;
    /// elements for an embedded document or array.
    public final class BsonElement {
        /// The element's name if it is ASCII, otherwise empty (see key).
        public let name: String
        let kind: UInt8
        var data: [UInt8] = []
        var subtype: UInt8 = 0
        var integerValue: Int64 = 0
        var number: Double = 0
        var low: UInt64 = 0
        var high: UInt64 = 0
        var elements: [BsonElement] = []

        init(_ name: String, _ kind: UInt8) {
            self.name = name
            self.kind = kind
        }

        /// An integer member, from an int32, int64, Decimal128 or double that
        /// is a whole number in its range, as the bits of a UInt64.
        public func integer(_ ctype: String, _ bits: Int) throws -> UInt64 {
            var value: (Bool, UInt64)?
            switch kind {
            case bsonInt32, bsonInt64:
                value = (integerValue < 0, integerValue.magnitude)
            case bsonDecimal128:
                value = decimalInteger(low, high)
            case bsonDouble:
                let d = number
                if !d.isFinite || d != d.rounded(.towardZero) || d.magnitude >= 18_446_744_073_709_551_616.0 {
                    throw Invalid("not a whole number")
                }
                value = (d < 0, UInt64(d.magnitude))
            default:
                throw Invalid("not a number")
            }
            guard let (negative, magnitude) = value else {
                throw Invalid("not a whole number of at most 64 bits")
            }
            return try fitInteger(negative, magnitude, ctype, bits)
        }

        /// A float or double member, from a double (rounded to the type, too
        /// large for it invalid), int32 or int64.
        public func real(_ ctype: String) throws -> Double {
            let isFloat = ctype == "float"
            switch kind {
            case bsonInt32, bsonInt64:
                return isFloat ? Double(Float(integerValue)) : Double(integerValue)
            case bsonDouble:
                break
            default:
                throw Invalid("not a number")
            }
            let d = number
            if !isFloat || d.isNaN {
                return d
            }
            if !d.isInfinite && d.magnitude >= floatLimit {
                throw Invalid("too large for a float")
            }
            return Double(Float(d))
        }

        /// A string member, into dst, from a string or binary (subtype 0) of
        /// at most dst.count bytes, zero-filled.
        public func bytes(_ dst: inout [UInt8]) throws {
            if kind != bsonString && (kind != bsonBinary || subtype != 0) {
                throw Invalid("not a string")
            }
            if data.count > dst.count {
                throw Invalid("string too long")
            }
            for i in 0..<dst.count {
                dst[i] = i < data.count ? data[i] : 0
            }
        }

        /// A nested message member's elements.
        public func document() throws -> [BsonElement] {
            if kind != bsonDocument {
                throw Invalid("not a document")
            }
            return elements
        }
    }

    /// A Decimal128 (BID) as a whole number of at most 64 bits, as its sign
    /// and magnitude; nil if it is infinite, NaN, not canonical, not whole,
    /// or larger.
    static func decimalInteger(_ low: UInt64, _ high: UInt64) -> (Bool, UInt64)? {
        let negative = high >> 63 != 0
        if (high >> 61) & 3 == 3 {
            return nil
        }
        let exponent = Int((high >> 49) & 0x3FFF) - 6176
        var hi = high & 0x1_FFFF_FFFF_FFFF
        var lo = low
        if hi > tenToThe34.0 || (hi == tenToThe34.0 && lo >= tenToThe34.1) {
            return nil
        }
        if hi == 0 && lo == 0 {
            return (false, 0)
        }
        if exponent < 0 {
            // The coefficient is not zero, so this ends within 34 places.
            for _ in 0 ..< -exponent {
                let (qhi, rhi) = hi.quotientAndRemainder(dividingBy: 10)
                let (qlo, r) = UInt64(10).dividingFullWidth((rhi, lo))
                if r != 0 {
                    return nil
                }
                (hi, lo) = (qhi, qlo)
            }
        } else if exponent > 0 {
            if exponent > 20 || hi != 0 {
                return nil
            }
            for _ in 0..<exponent {
                let (times, overflow) = lo.multipliedReportingOverflow(by: 10)
                if overflow {
                    return nil
                }
                lo = times
            }
        }
        if hi != 0 {
            return nil
        }
        return (negative, lo)
    }

    /// Reads a document or an element's value between a position and an end,
    /// checking every length against the bytes there are.
    struct BsonParser {
        let s: [UInt8]

        func int32(_ at: Int) -> Int64 {
            let v = UInt32(s[at]) | UInt32(s[at + 1]) << 8 | UInt32(s[at + 2]) << 16 | UInt32(s[at + 3]) << 24
            return Int64(Int32(bitPattern: v))
        }

        func uint64(_ at: Int) -> UInt64 {
            var v: UInt64 = 0
            for k in 0..<8 {
                v |= UInt64(s[at + k]) << UInt64(8 * k)
            }
            return v
        }

        func document(_ pos: Int, _ end: Int, _ depth: Int) throws -> ([BsonElement], Int) {
            if depth > maxDepth || end - pos < 5 {
                throw Invalid("bad document")
            }
            let length = int32(pos)
            if length < 5 || length > Int64(end - pos) {
                throw Invalid("bad document length")
            }
            let last = pos + Int(length) - 1
            if s[last] != 0 {
                throw Invalid("no document terminator")
            }
            var elements: [BsonElement] = []
            var at = pos + 4
            while at < last {
                let (e, next) = try element(at, last, depth)
                elements.append(e)
                at = next
            }
            return (elements, last + 1)
        }

        func cstring(_ at: Int, _ end: Int) throws -> (String, Int) {
            var nul = at
            while nul < end && s[nul] != 0 {
                nul += 1
            }
            if nul >= end {
                throw Invalid("unterminated cstring")
            }
            guard let text = utf8(s, at, nul) else {
                throw Invalid("not UTF-8")
            }
            return (key(text), nul + 1)
        }

        func string(_ at: Int, _ end: Int) throws -> ([UInt8], Int) {
            if end - at < 4 {
                throw Invalid("bad string")
            }
            let length = int32(at)
            if length < 1 || length > Int64(end - at - 4) {
                throw Invalid("bad string length")
            }
            let nul = at + 4 + Int(length) - 1
            if s[nul] != 0 {
                throw Invalid("unterminated string")
            }
            if utf8(s, at + 4, nul) == nil {
                throw Invalid("not UTF-8")
            }
            return (Array(s[(at + 4)..<nul]), nul + 1)
        }

        func fixed(_ at: Int, _ end: Int, _ width: Int) throws -> Int {
            if end - at < width {
                throw Invalid("cut short")
            }
            return at + width
        }

        func element(_ at: Int, _ end: Int, _ depth: Int) throws -> (BsonElement, Int) {
            let kind = s[at]
            let (name, start) = try cstring(at + 1, end)
            let e = BsonElement(name, kind)
            var next = start
            switch kind {
            case bsonDouble:
                next = try fixed(start, end, 8)
                e.number = Double(bitPattern: uint64(start))
            case bsonString, bsonJavascript, bsonSymbol:
                (e.data, next) = try string(start, end)
            case bsonDocument, bsonArray:
                (e.elements, next) = try document(start, end, depth + 1)
            case bsonBinary:
                if end - start < 5 {
                    throw Invalid("bad binary")
                }
                let length = int32(start)
                if length < 0 || length > Int64(end - start - 5) {
                    throw Invalid("bad binary length")
                }
                e.subtype = s[start + 4]
                e.data = Array(s[(start + 5)..<(start + 5 + Int(length))])
                next = start + 5 + Int(length)
            case bsonUndefined, bsonNull, bsonMinKey, bsonMaxKey:
                next = start
            case bsonObjectId:
                next = try fixed(start, end, 12)
            case bsonBool:
                next = try fixed(start, end, 1)
                if s[start] > 1 {
                    throw Invalid("bad bool")
                }
            case bsonDatetime, bsonTimestamp:
                next = try fixed(start, end, 8)
            case bsonInt32:
                next = try fixed(start, end, 4)
                e.integerValue = int32(start)
            case bsonInt64:
                next = try fixed(start, end, 8)
                e.integerValue = Int64(bitPattern: uint64(start))
            case bsonDecimal128:
                next = try fixed(start, end, 16)
                e.low = uint64(start)
                e.high = uint64(start + 8)
            case bsonRegex:
                let (_, after) = try cstring(start, end)
                next = try cstring(after, end).1
            case bsonDbPointer:
                let (_, after) = try string(start, end)
                next = try fixed(after, end, 12)
            case bsonCodeWithScope:
                // int32 total length, then a string and a document filling it.
                if end - start < 4 {
                    throw Invalid("bad code with scope")
                }
                let length = int32(start)
                if length < 4 || length > Int64(end - start) {
                    throw Invalid("bad code with scope length")
                }
                let stop = start + Int(length)
                let (_, after) = try string(start + 4, stop)
                let (_, done) = try document(after, stop, depth + 1)
                if done != stop {
                    throw Invalid("bad code with scope length")
                }
                next = done
            default:
                // An unknown type: its length is unknown, so nothing after it
                // can be read.
                throw Invalid("unknown element type")
            }
            return (e, next)
        }
    }

    /// Parses a whole BSON document: its length must be exactly the input's.
    /// Its elements, in order, repeats and all.
    public static func parseBson(_ input: [UInt8]) throws -> [BsonElement] {
        let (elements, end) = try BsonParser(s: input).document(0, input.count, 1)
        if end != input.count {
            throw Invalid("bytes after the document")
        }
        return elements
    }

    /// Builds a BSON document: each, the outermost included, is
    /// beginDocument() ... endDocument(); an embedded one is named first with
    /// document(name).
    public final class BsonWriter {
        var out: [UInt8] = []
        var starts: [Int] = []

        public init() {}

        /// The bytes written.
        public func finish() -> [UInt8] {
            return out
        }

        func putInt32(_ v: UInt32) {
            for k in 0..<4 {
                out.append(UInt8(truncatingIfNeeded: v >> UInt32(8 * k)))
            }
        }

        func putInt64(_ v: UInt64) {
            for k in 0..<8 {
                out.append(UInt8(truncatingIfNeeded: v >> UInt64(8 * k)))
            }
        }

        public func beginDocument() {
            starts.append(out.count)
            putInt32(0)
        }

        public func endDocument() {
            out.append(0)
            let start = starts.removeLast()
            let length = UInt32(out.count - start)
            for k in 0..<4 {
                out[start + k] = UInt8(truncatingIfNeeded: length >> UInt32(8 * k))
            }
        }

        func head(_ kind: UInt8, _ name: String) {
            out.append(kind)
            out.append(contentsOf: Array(name.utf8))
            out.append(0)
        }

        public func document(_ name: String) {
            head(bsonDocument, name)
        }

        /// Types up to 32 bits but uint32_t are int32 (a char as signed).
        public func i32(_ name: String, _ v: Int32) {
            head(bsonInt32, name)
            putInt32(UInt32(bitPattern: v))
        }

        public func u32(_ name: String, _ v: UInt32) {
            i64(name, Int64(v))
        }

        public func i64(_ name: String, _ v: Int64) {
            head(bsonInt64, name)
            putInt64(UInt64(bitPattern: v))
        }

        /// A uint64_t above 2^63-1 is a Decimal128, so no tool sees it
        /// negative.
        public func u64(_ name: String, _ v: UInt64) {
            if v <= UInt64(Int64.max) {
                i64(name, Int64(v))
                return
            }
            head(bsonDecimal128, name)
            putInt64(v)
            putInt64(decimal128IntegerHigh)
        }

        public func f32(_ name: String, _ v: Float) {
            f64(name, Double(v))
        }

        public func f64(_ name: String, _ v: Double) {
            head(bsonDouble, name)
            putInt64(v.isNaN ? canonicalNaN : v.bitPattern)
        }

        /// A string member: its bytes up to the trailing NULs, as a string if
        /// they are UTF-8 holding no NUL, otherwise as binary (subtype 0).
        public func bytes(_ name: String, _ data: [UInt8]) {
            let used = SkywireText.used(data)
            let bytes = Array(data[0..<used])
            if !bytes.contains(0) && utf8(bytes, 0, used) != nil {
                head(bsonString, name)
                putInt32(UInt32(used + 1))
                out.append(contentsOf: bytes)
                out.append(0)
                return
            }
            head(bsonBinary, name)
            putInt32(UInt32(used))
            out.append(0)
            out.append(contentsOf: bytes)
        }
    }
