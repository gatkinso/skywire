    static let bsonDouble: UInt8 = 0x01
    static let bsonString: UInt8 = 0x02
    static let bsonDocument: UInt8 = 0x03
    static let bsonArray: UInt8 = 0x04
    static let bsonBinary: UInt8 = 0x05
    static let bsonUndefined: UInt8 = 0x06
    static let bsonObjectId: UInt8 = 0x07
    static let bsonBool: UInt8 = 0x08
    static let bsonDatetime: UInt8 = 0x09
    static let bsonNull: UInt8 = 0x0A
    static let bsonRegex: UInt8 = 0x0B
    static let bsonDbPointer: UInt8 = 0x0C
    static let bsonJavascript: UInt8 = 0x0D
    static let bsonSymbol: UInt8 = 0x0E
    static let bsonCodeWithScope: UInt8 = 0x0F
    static let bsonInt32: UInt8 = 0x10
    static let bsonTimestamp: UInt8 = 0x11
    static let bsonInt64: UInt8 = 0x12
