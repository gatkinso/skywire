            element(name, realText(Double(v), true))
        }

        public func f64(_ name: String, _ v: Double) {
            element(name, realText(v, false))
        }

        /// A string member: its bytes up to the trailing NULs, escaped, or,
        /// if any byte is not printable ASCII, in hexadecimal with
        /// encoding="hex".
        public func bytes(_ name: String, _ data: [UInt8]) {
            let used = data[0..<SkywireText.used(data)]
            if used.contains(where: { $0 < 0x20 || $0 > 0x7E }) {
                append(&out, "<" + name + " encoding=\"hex\">")
                for b in used {
                    appendHex(&out, b)
                }
                close(name)
                return
            }
            open(name)
            for b in used {
                switch b {
                case UInt8(ascii: "<"): append(&out, "&lt;")
                case UInt8(ascii: ">"): append(&out, "&gt;")
                case UInt8(ascii: "&"): append(&out, "&amp;")
                case UInt8(ascii: "\""): append(&out, "&quot;")
                case UInt8(ascii: "'"): append(&out, "&apos;")
                default: out.append(b)
                }
            }
            close(name)
        }
    }

