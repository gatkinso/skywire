    /// Nesting deeper than this (objects, arrays, elements, documents) is
    /// rejected, so hostile input cannot exhaust the stack.
    static let maxDepth = 128

    // MARK: - numbers

    static func isDigit(_ c: UInt32) -> Bool {
        return c >= 0x30 && c <= 0x39
    }

    /// The value of an ASCII hexadecimal digit, or nil.
    static func hexValue(_ c: UInt32) -> UInt32? {
        switch c {
        case 0x30...0x39: return c - 0x30
        case 0x61...0x66: return c - 0x61 + 10
        case 0x41...0x46: return c - 0x41 + 10
        default: return nil
        }
    }

    static func skipDigits(_ b: [UInt8], _ start: Int) -> Int {
        var i = start
        while i < b.count && isDigit(UInt32(b[i])) {
            i += 1
        }
        return i
    }

    /// Reports whether b (ASCII) is a JSON number.
    static func isNumber(_ b: [UInt8]) -> Bool {
        var i = 0
        if i < b.count && b[i] == UInt8(ascii: "-") {
            i += 1
        }
        if i >= b.count {
            return false
        }
        if b[i] == UInt8(ascii: "0") {
            i += 1
        } else if isDigit(UInt32(b[i])) {
            i = skipDigits(b, i)
        } else {
            return false
        }
        if i < b.count && b[i] == UInt8(ascii: ".") {
            let start = i + 1
            i = skipDigits(b, start)
            if i == start {
                return false
            }
        }
        if i < b.count && (b[i] == UInt8(ascii: "e") || b[i] == UInt8(ascii: "E")) {
            i += 1
            if i < b.count && (b[i] == UInt8(ascii: "+") || b[i] == UInt8(ascii: "-")) {
                i += 1
            }
            let start = i
            i = skipDigits(b, start)
            if i == start {
                return false
            }
        }
        return i == b.count
    }

    /// The values a member of type ctype (a bitfield bits wide, if bits)
    /// holds, as the magnitude of the lowest and the highest; a char takes
    /// -128 to 255, as in the C and C++ runtimes.
    static func range(_ ctype: String, _ bits: Int) -> (UInt64, UInt64) {
        var signed = true
        var width = 64
        switch ctype {
        case "char": return (128, 255)
        case "unsigned char", "uint8_t": (signed, width) = (false, 8)
        case "int8_t": (signed, width) = (true, 8)
        case "uint16_t": (signed, width) = (false, 16)
        case "int16_t": (signed, width) = (true, 16)
        case "uint32_t": (signed, width) = (false, 32)
        case "int32_t": (signed, width) = (true, 32)
        case "uint64_t": (signed, width) = (false, 64)
        default: break
        }
        if bits > 0 {
            width = bits
        }
        if signed {
            let half: UInt64 = 1 << UInt64(width - 1)
            return (half, half - 1)
        }
        if width == 64 {
            return (0, UInt64.max)
        }
        return (0, (1 << UInt64(width)) - 1)
    }

    static func dropLeading(_ b: ArraySlice<UInt8>, _ set: [UInt8]) -> ArraySlice<UInt8> {
        var s = b
        while let first = s.first, set.contains(first) {
            s = s.dropFirst()
        }
        return s
    }

    /// The exact integer a JSON number stands for ("12", "1.2e1", "120e-1")
    /// as its sign and magnitude; nil if it is not a whole number or needs
    /// more than 64 bits.
    static func integerValue(_ text: [UInt8]) -> (Bool, UInt64)? {
        if !isNumber(text) {
            return nil
        }
        let negative = text.first == UInt8(ascii: "-")
        let body = Array(dropLeading(text[...], [UInt8(ascii: "-")]).map { $0 == UInt8(ascii: "E") ? UInt8(ascii: "e") : $0 })
        var mantissa = body[...]
        var exponentText: ArraySlice<UInt8>? = nil
        if let e = body.firstIndex(of: UInt8(ascii: "e")) {
            mantissa = body[..<e]
            exponentText = body[(e + 1)...]
        }
        var whole = mantissa
        var fraction: ArraySlice<UInt8> = []
        if let point = mantissa.firstIndex(of: UInt8(ascii: ".")) {
            whole = mantissa[..<point]
            fraction = mantissa[(point + 1)...]
        }
        var exponent = -fraction.count
        if let e = exponentText {
            let sign = e.first == UInt8(ascii: "-") ? -1 : 1
            let digits = dropLeading(dropLeading(e, [UInt8(ascii: "+"), UInt8(ascii: "-")]), [UInt8(ascii: "0")])
            // Beyond 100000 either way is beyond any 64-bit value.
            var value = 100_000
            if digits.count <= 6 {
                value = 0
                for d in digits {
                    value = value * 10 + Int(d - UInt8(ascii: "0"))
                }
                value = min(value, 100_000)
            }
            exponent += sign * value
        }
        let digits = dropLeading(whole + fraction, [UInt8(ascii: "0")])
        if digits.isEmpty {
            return (false, 0)
        }
        var significant = digits
        while significant.last == UInt8(ascii: "0") {
            significant = significant.dropLast()
        }
        let places = (digits.count - significant.count) + exponent
        if places < 0 || significant.count + places > 20 {
            return nil
        }
        var magnitude: UInt64 = 0
        for c in Array(significant) + [UInt8](repeating: UInt8(ascii: "0"), count: places) {
            let (times, o1) = magnitude.multipliedReportingOverflow(by: 10)
            let (plus, o2) = times.addingReportingOverflow(UInt64(c - UInt8(ascii: "0")))
            if o1 || o2 {
                return nil
            }
            magnitude = plus
        }
        return (negative, magnitude)
    }

    /// The value, as the bits of a two's complement UInt64 that the member's
    /// type converts to, if it is in range for ctype (a bitfield bits wide, if
    /// bits). A char above 127 converts to the signed char C and C++ hold.
    static func fitInteger(_ negative: Bool, _ magnitude: UInt64, _ ctype: String, _ bits: Int) throws -> UInt64 {
        let (lo, hi) = range(ctype, bits)
        if (negative && magnitude > lo) || (!negative && magnitude > hi) {
            throw Invalid("out of range for " + ctype)
        }
        return negative ? 0 &- magnitude : magnitude
    }

    static func toInteger(_ text: [UInt8], _ ctype: String, _ bits: Int) throws -> UInt64 {
        guard let (negative, magnitude) = integerValue(text) else {
            throw Invalid("not a whole number of at most 64 bits")
        }
        return try fitInteger(negative, magnitude, ctype, bits)
    }

    /// A JSON number rounded straight to the type: a float directly, not
    /// through a double, which could round twice. Too large gives an
    /// infinity.
    static func parseReal(_ text: [UInt8], _ isFloat: Bool) -> Double {
        let s = String(decoding: text, as: UTF8.self)
        if isFloat {
            return Double(Float(s) ?? .nan)
        }
        return Double(s) ?? .nan
    }

    static let nanText = Array("NaN".utf8)
    static let infinityText = Array("Infinity".utf8)
    static let minusInfinityText = Array("-Infinity".utf8)

    /// A float or double member's value: "NaN", "Infinity" and "-Infinity"
    /// by name, otherwise a JSON number rounded to the type; too large is
    /// invalid.
    static func toReal(_ text: [UInt8], _ ctype: String) throws -> Double {
        if text == nanText {
            return .nan
        }
        if text == infinityText {
            return .infinity
        }
        if text == minusInfinityText {
            return -.infinity
        }
        if !isNumber(text) {
            throw Invalid("not a number")
        }
        let value = parseReal(text, ctype == "float")
        if value.isInfinite {
            throw Invalid("too large for " + ctype)
        }
        return value
    }

    // Unsigned integers of any size, little-endian 32-bit limbs, for a
    // double's exact decimal value.

    static func multiply(_ n: inout [UInt32], _ k: UInt32) {
        var carry: UInt64 = 0
        for i in 0..<n.count {
            let t = UInt64(n[i]) * UInt64(k) + carry
            n[i] = UInt32(truncatingIfNeeded: t)
            carry = t >> 32
        }
        if carry != 0 {
            n.append(UInt32(carry))
        }
    }

    /// Divides n by d, returning the remainder.
    static func divide(_ n: inout [UInt32], _ d: UInt32) -> UInt32 {
        var rem: UInt64 = 0
        for i in stride(from: n.count - 1, through: 0, by: -1) {
            let t = (rem << 32) | UInt64(n[i])
            n[i] = UInt32(t / UInt64(d))
            rem = t % UInt64(d)
        }
        while n.last == 0 {
            n.removeLast()
        }
        return UInt32(rem)
    }

    /// n's decimal digits (each 0 to 9), most significant first.
    static func decimal(_ value: [UInt32]) -> [UInt8] {
        var n = value
        while n.last == 0 {
            n.removeLast()
        }
        var groups: [UInt32] = []
        while !n.isEmpty {
            groups.append(divide(&n, 1_000_000_000))
        }
        var digits: [UInt8] = []
        for (index, group) in groups.reversed().enumerated() {
            var g = group
            var nine = [UInt8](repeating: 0, count: 9)
            for k in stride(from: 8, through: 0, by: -1) {
                nine[k] = UInt8(g % 10)
                g /= 10
            }
            if index == 0 {
                digits.append(contentsOf: nine.drop(while: { $0 == 0 }))
            } else {
                digits.append(contentsOf: nine)
            }
        }
        return digits
    }

    /// The exact decimal digits (each 0 to 9) of a finite, nonzero value,
    /// without trailing zeros, and the power of ten of the first: the value
    /// is m * 2^e, so m * 2^e or (m * 5^-e) / 10^-e.
    static func exactDigits(_ value: Double) -> ([UInt8], Int) {
        let bits = value.magnitude.bitPattern
        let biased = Int((bits >> 52) & 0x7FF)
        var m = bits & ((1 << 52) - 1)
        var e2 = -1074
        if biased != 0 {
            m |= 1 << 52
            e2 = biased - 1075
        }
        var n: [UInt32] = [UInt32(truncatingIfNeeded: m), UInt32(truncatingIfNeeded: m >> 32)]
        var scale = 0
        if e2 >= 0 {
            var left = e2
            while left > 0 {
                let s = min(left, 31)
                multiply(&n, 1 << UInt32(s))
                left -= s
            }
        } else {
            var left = -e2
            scale = left
            while left > 0 {
                let s = min(left, 13)
                var p: UInt32 = 1
                for _ in 0..<s {
                    p *= 5
                }
                multiply(&n, p)
                left -= s
            }
        }
        var digits = decimal(n)
        let exponent = digits.count - 1 - scale
        while digits.count > 1 && digits.last == 0 {
            digits.removeLast()
        }
        return (digits, exponent)
    }

    /// The exact digits rounded to precision digits, ties to even, as
    /// printf's %.*e does, and the power of ten of the first.
    static func rounded(_ exact: [UInt8], _ exponent: Int, _ precision: Int) -> ([UInt8], Int) {
        var digits = Array(exact.prefix(precision))
        if exact.count <= precision {
            digits += [UInt8](repeating: 0, count: precision - digits.count)
            return (digits, exponent)
        }
        let next = exact[precision]
        // exact has no trailing zeros, so a digit after next is not zero.
        let up = next > 5 || (next == 5 && (exact.count > precision + 1 || digits[precision - 1] % 2 == 1))
        if up {
            for i in stride(from: precision - 1, through: 0, by: -1) {
                if digits[i] != 9 {
                    digits[i] += 1
                    return (digits, exponent)
                }
                digits[i] = 0
            }
            // All nines: 99 becomes 100, one place up.
            digits[0] = 1
            return (digits, exponent + 1)
        }
        return (digits, exponent)
    }

    /// Reports whether digits * 10^(exponent - digits.count + 1) reads back
    /// as value.
    static func readsBack(_ digits: [UInt8], _ exponent: Int, _ value: Double, _ isFloat: Bool) -> Bool {
        var text: [UInt8] = []
        if value < 0 {
            text.append(UInt8(ascii: "-"))
        }
        text.append(contentsOf: digits.map { $0 + UInt8(ascii: "0") })
        text.append(UInt8(ascii: "e"))
        text.append(contentsOf: Array(String(exponent - (digits.count - 1)).utf8))
        return parseReal(text, isFloat) == value
    }

    /// Adds one to (up) or takes one from the last digit, carrying: the
    /// digits and the exponent, or nil if the result is zero.
    static func step(_ digits: [UInt8], _ exponent: Int, _ up: Bool) -> ([UInt8], Int)? {
        var d = digits
        var e = exponent
        for i in stride(from: d.count - 1, through: 0, by: -1) {
            if up {
                if d[i] != 9 {
                    d[i] += 1
                    return (d, e)
                }
                d[i] = 0
            } else {
                if d[i] != 0 {
                    d[i] -= 1
                    break
                }
                d[i] = 9
            }
        }
        if up {
            // All nines: 99 becomes 100, one place up.
            d[0] = 1
            return (d, e + 1)
        }
        if d[0] == 0 {
            // 10 becomes 99, one place down.
            d.removeFirst()
            d.append(9)
            e -= 1
        }
        return d.contains(where: { $0 != 0 }) ? (d, e) : nil
    }

    /// A finite, nonzero value as the fewest significant digits that read
    /// back as it, and the power of ten of the first one.
    static func shortest(_ value: Double, _ isFloat: Bool) -> ([UInt8], Int) {
        let most = isFloat ? 9 : 17
        let (exact, exactExponent) = exactDigits(value)
        var digits: [UInt8] = []
        var exponent = 0
        for precision in 1...most {
            let (d, e) = rounded(exact, exactExponent, precision)
            if readsBack(d, e, value, isFloat) {
                (digits, exponent) = (d, e)
                break
            }
            // Next to a power of two the nearest decimal can miss while a
            // neighbour of it reads back.
            var found: ([UInt8], Int)? = nil
            for up in [true, false] {
                if let (nd, ne) = step(d, e, up), readsBack(nd, ne, value, isFloat) {
                    found = (nd, ne)
                    break
                }
            }
            if let (nd, ne) = found {
                (digits, exponent) = (nd, ne)
                break
            }
            (digits, exponent) = (d, e)
        }
        while digits.count > 1 && digits.last == 0 {
            digits.removeLast()
        }
        return (digits, exponent)
    }

    static func zeros(_ n: Int) -> String {
        return String(repeating: "0", count: n)
    }

    /// A float or double as text: the shortest form that reads back exactly,
    /// laid out as JavaScript's Number#toString does, but keeping -0; NaN,
    /// Infinity and -Infinity by name.
    static func realText(_ value: Double, _ isFloat: Bool) -> String {
        if value.isNaN {
            return "NaN"
        }
        if value.isInfinite {
            return value > 0 ? "Infinity" : "-Infinity"
        }
        if value == 0 {
            return value.sign == .minus ? "-0" : "0"
        }
        let (digits, e) = shortest(value, isFloat)
        let text = String(decoding: digits.map { $0 + UInt8(ascii: "0") }, as: UTF8.self)
        let k = digits.count
        let n = e + 1
        let sign = value < 0 ? "-" : ""
        if n >= k && n <= 21 {
            return sign + text + zeros(n - k)
        }
        if n >= 1 && n <= 21 {
            return sign + String(text.prefix(n)) + "." + String(text.dropFirst(n))
        }
        if n >= -5 && n <= 0 {
            return sign + "0." + zeros(-n) + text
        }
        let rest = String(text.dropFirst())
        let point = rest.isEmpty ? "" : "."
        return sign + String(text.prefix(1)) + point + rest + (e < 0 ? "e-" + String(-e) : "e+" + String(e))
    }

    /// The number of a string member's bytes before its trailing NULs.
    static func used(_ data: [UInt8]) -> Int {
        var n = data.count
        while n > 0 && data[n - 1] == 0 {
            n -= 1
        }
        return n
    }

    /// Fills dst with text, each character one byte (U+0000 to U+00FF),
    /// zero-padded; invalid if there are more than dst.count.
    static func textToBytes(_ text: [UInt32], _ dst: inout [UInt8]) throws {
        if text.count > dst.count {
            throw Invalid("string too long")
        }
        if text.contains(where: { $0 > 0xFF }) {
            throw Invalid("a character that is not one byte")
        }
        for i in 0..<dst.count {
            dst[i] = i < text.count ? UInt8(text[i]) : 0
        }
    }

    /// The code points of the UTF-8 bytes in b[begin..<end]; nil if they are
    /// not UTF-8 (overlong forms, surrogates and values above U+10FFFF
    /// included).
    static func utf8(_ b: [UInt8], _ begin: Int, _ end: Int) -> [UInt32]? {
        var out: [UInt32] = []
        out.reserveCapacity(end - begin)
        var i = begin
        while i < end {
            let c0 = b[i]
            if c0 < 0x80 {
                out.append(UInt32(c0))
                i += 1
                continue
            }
            var more = 0
            var cp: UInt32 = 0
            var low: UInt8 = 0x80
            var high: UInt8 = 0xBF
            switch c0 {
            case 0xC2...0xDF:
                more = 1
                cp = UInt32(c0 & 0x1F)
            case 0xE0...0xEF:
                more = 2
                cp = UInt32(c0 & 0x0F)
                if c0 == 0xE0 {
                    low = 0xA0
                } else if c0 == 0xED {
                    high = 0x9F
                }
            case 0xF0...0xF4:
                more = 3
                cp = UInt32(c0 & 0x07)
                if c0 == 0xF0 {
                    low = 0x90
                } else if c0 == 0xF4 {
                    high = 0x8F
                }
            default:
                return nil
            }
            if end - i - 1 < more {
                return nil
            }
            for k in 1...more {
                let c = b[i + k]
                if c < low || c > high {
                    return nil
                }
                low = 0x80
                high = 0xBF
                cp = (cp << 6) | UInt32(c & 0x3F)
            }
            out.append(cp)
            i += more + 1
        }
        return out
    }

    /// input as code points; invalid if it is not UTF-8.
    static func decode(_ input: [UInt8]) throws -> [UInt32] {
        guard let s = utf8(input, 0, input.count) else {
            throw Invalid("not UTF-8")
        }
        return s
    }

    /// input as code points (a String is always valid Unicode).
    static func decode(_ input: String) -> [UInt32] {
        return input.unicodeScalars.map { $0.value }
    }

    /// text as ASCII bytes for the number functions; a character that is not
    /// ASCII becomes 0xFF, which nothing takes.
    static func ascii(_ text: ArraySlice<UInt32>) -> [UInt8] {
        return text.map { $0 < 0x80 ? UInt8($0) : 0xFF }
    }

    /// A name to match a member by: the name itself if it is ASCII,
    /// otherwise empty, which no member's name is. (Swift's String equality
    /// would take a name that is only canonically equivalent, such as
    /// "\u{212A}" for "K", which the other languages refuse.)
    static func key(_ name: [UInt32]) -> String {
        if name.contains(where: { $0 >= 0x80 }) {
            return ""
        }
        return String(decoding: name.map { UInt8($0) }, as: UTF8.self)
    }

    static func isSpace(_ c: UInt32) -> Bool {
        return c == 0x20 || c == 0x09 || c == 0x0A || c == 0x0D
    }

    static func hasPrefix(_ s: [UInt32], _ i: Int, _ word: [UInt32]) -> Bool {
        if i + word.count > s.count {
            return false
        }
        for k in 0..<word.count where s[i + k] != word[k] {
            return false
        }
        return true
    }

    static func scalars(_ s: String) -> [UInt32] {
        return s.unicodeScalars.map { $0.value }
    }

    /// text without surrounding whitespace (space, tab, CR, LF).
    static func trim(_ text: [UInt32]) -> ArraySlice<UInt32> {
        var s = text[...]
        while let c = s.first, isSpace(c) {
            s = s.dropFirst()
        }
        while let c = s.last, isSpace(c) {
            s = s.dropLast()
        }
        return s
    }

    static let hexDigits = Array("0123456789abcdef".utf8)

    static func appendHex(_ out: inout [UInt8], _ b: UInt8) {
        out.append(hexDigits[Int(b >> 4)])
        out.append(hexDigits[Int(b & 15)])
    }

    static func append(_ out: inout [UInt8], _ s: String) {
        out.append(contentsOf: Array(s.utf8))
    }

    // MARK: - JSON

    /// A parsed JSON value.
    public final class Json {
        enum Kind {
            case object, array, string, number, bool, null
        }

        let kind: Kind
        var objectMembers: [JsonMember] = []
        /// A string's code points.
        var chars: [UInt32] = []
        /// A number, as its text.
        var number: [UInt8] = []

        init(_ kind: Kind) {
            self.kind = kind
        }

        /// The members of an object, in order, repeats and all.
        public func members() throws -> [JsonMember] {
            if kind != .object {
                throw Invalid("not an object")
            }
            return objectMembers
        }

        /// A number member's text: a JSON number, or a string holding one
        /// (as 64-bit integers, NaN and the infinities are written).
        func text() throws -> [UInt8] {
            switch kind {
            case .number: return number
            case .string: return ascii(chars[...])
            default: throw Invalid("not a number")
            }
        }

        /// An integer member, which must be whole and in range, of ctype or
        /// of a bitfield bits wide, as the bits of a UInt64.
        public func integer(_ ctype: String, _ bits: Int) throws -> UInt64 {
            return try toInteger(text(), ctype, bits)
        }

        /// A float or double member.
        public func real(_ ctype: String) throws -> Double {
            return try toReal(text(), ctype)
        }

        /// A string member, into dst: each character one byte.
        public func bytes(_ dst: inout [UInt8]) throws {
            if kind != .string {
                throw Invalid("not a string")
            }
            try textToBytes(chars, &dst)
        }
    }

    /// One member of a JSON object.
    public struct JsonMember {
        /// The member's name if it is ASCII, otherwise empty (see key).
        public let name: String
        public let value: Json
    }

    struct JsonParser {
        let s: [UInt32]
        var i = 0

        init(_ s: [UInt32]) {
            self.s = s
        }

        func peek() -> UInt32? {
            return i < s.count ? s[i] : nil
        }

        mutating func space() {
            while i < s.count && isSpace(s[i]) {
                i += 1
            }
        }

        mutating func expect(_ c: Character) throws {
            if peek() != c.unicodeScalars.first!.value {
                throw Invalid("expected " + String(c))
            }
            i += 1
        }

        mutating func literal(_ word: String) throws {
            let w = scalars(word)
            if !hasPrefix(s, i, w) {
                throw Invalid("expected " + word)
            }
            i += w.count
        }

        mutating func hex4() throws -> UInt32 {
            if i + 4 > s.count {
                throw Invalid("bad \\u escape")
            }
            var cp: UInt32 = 0
            for k in 0..<4 {
                guard let v = hexValue(s[i + k]) else {
                    throw Invalid("bad \\u escape")
                }
                cp = cp * 16 + v
            }
            i += 4
            return cp
        }

        mutating func string() throws -> [UInt32] {
            try expect("\"")
            var out: [UInt32] = []
            while i < s.count {
                let c = s[i]
                i += 1
                if c == 0x22 {
                    return out
                }
                if c < 0x20 {
                    throw Invalid("control character in a string")
                }
                if c != 0x5C {
                    out.append(c)
                    continue
                }
                if i >= s.count {
                    break
                }
                let e = s[i]
                i += 1
                switch e {
                case 0x22, 0x5C, 0x2F: out.append(e)
                case 0x62: out.append(0x08)
                case 0x66: out.append(0x0C)
                case 0x6E: out.append(0x0A)
                case 0x72: out.append(0x0D)
                case 0x74: out.append(0x09)
                case 0x75:
                    var cp = try hex4()
                    if cp >= 0xDC00 && cp <= 0xDFFF {
                        throw Invalid("lone low surrogate")
                    }
                    if cp >= 0xD800 && cp <= 0xDBFF {
                        try literal("\\u")
                        let low = try hex4()
                        if low < 0xDC00 || low > 0xDFFF {
                            throw Invalid("lone high surrogate")
                        }
                        cp = 0x10000 + ((cp - 0xD800) << 10) + (low - 0xDC00)
                    }
                    out.append(cp)
                default:
                    throw Invalid("bad escape")
                }
            }
            throw Invalid("unterminated string")
        }

        static let numberChars = scalars("0123456789+-.eE")

        mutating func number() throws -> [UInt8] {
            let start = i
            while i < s.count && JsonParser.numberChars.contains(s[i]) {
                i += 1
            }
            let text = ascii(s[start..<i])
            if !isNumber(text) {
                throw Invalid("bad number")
            }
            return text
        }

        mutating func value(_ outer: Int) throws -> Json {
            guard let c = peek() else {
                throw Invalid("expected a value")
            }
            switch c {
            case 0x7B, 0x5B:
                let depth = outer + 1
                if depth > maxDepth {
                    throw Invalid("nested too deeply")
                }
                let object = c == 0x7B
                let end: UInt32 = object ? 0x7D : 0x5D
                let v = Json(object ? .object : .array)
                i += 1
                space()
                if peek() != end {
                    while true {
                        space()
                        if object {
                            let name = try string()
                            space()
                            try expect(":")
                            space()
                            v.objectMembers.append(JsonMember(name: key(name), value: try value(depth)))
                        } else {
                            _ = try value(depth)
                        }
                        space()
                        if peek() != 0x2C {
                            break
                        }
                        i += 1
                    }
                }
                try expect(object ? "}" : "]")
                return v
            case 0x22:
                let v = Json(.string)
                v.chars = try string()
                return v
            case 0x74:
                try literal("true")
                return Json(.bool)
            case 0x66:
                try literal("false")
                return Json(.bool)
            case 0x6E:
                try literal("null")
                return Json(.null)
            default:
                let v = Json(.number)
                v.number = try number()
                return v
            }
        }

        mutating func document() throws -> Json {
            space()
            let v = try value(0)
            space()
            if i != s.count {
                throw Invalid("text after the value")
            }
            return v
        }
    }

