    /// Writes the canonical JSON form: no whitespace, members in order.
    public final class JsonWriter {
        var out: [UInt8] = []
        var first = false

        public init() {}

        /// The text written.
        public func finish() -> String {
            return String(decoding: out, as: UTF8.self)
        }

        public func beginObject() {
            out.append(UInt8(ascii: "{"))
            first = true
        }

        public func endObject() {
            out.append(UInt8(ascii: "}"))
            first = false
        }

        public func key(_ name: String) {
            if !first {
                out.append(UInt8(ascii: ","))
            }
            first = false
            append(&out, "\"" + name + "\":")
        }

        /// Types up to 32 bits but uint32_t (a char as signed).
        public func i32(_ name: String, _ v: Int32) {
            key(name)
            append(&out, String(v))
        }

        public func u32(_ name: String, _ v: UInt32) {
            key(name)
            append(&out, String(v))
        }

        /// 64-bit integers are written as strings.
        public func i64(_ name: String, _ v: Int64) {
            key(name)
            append(&out, "\"" + String(v) + "\"")
        }

        public func u64(_ name: String, _ v: UInt64) {
            key(name)
            append(&out, "\"" + String(v) + "\"")
        }

        public func f32(_ name: String, _ v: Float) {
            real(name, realText(Double(v), true))
        }

        public func f64(_ name: String, _ v: Double) {
            real(name, realText(v, false))
        }

        /// NaN and the infinities are written as strings.
        func real(_ name: String, _ text: String) {
            key(name)
            if isNumber(Array(text.utf8)) {
                append(&out, text)
            } else {
                append(&out, "\"" + text + "\"")
            }
        }

        /// A string member: its bytes up to the trailing NULs, printable
        /// ASCII as is (but " and \ escaped), every other byte as \u00xx.
        public func bytes(_ name: String, _ data: [UInt8]) {
            key(name)
            out.append(UInt8(ascii: "\""))
            for b in data[0..<used(data)] {
                if b == UInt8(ascii: "\"") || b == UInt8(ascii: "\\") {
                    out.append(UInt8(ascii: "\\"))
                    out.append(b)
                } else if b >= 0x20 && b <= 0x7E {
                    out.append(b)
                } else {
                    append(&out, "\\u00")
                    appendHex(&out, b)
                }
            }
            out.append(UInt8(ascii: "\""))
        }
    }

