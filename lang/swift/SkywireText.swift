    /// A parsed element: its attributes, child elements and character data
    /// (text and CDATA, entities decoded, line ends normalized).
    public final class XmlNode {
        let tag: [UInt32]
        /// The element's name if it is ASCII, otherwise empty (see key).
        public let name: String
        var attributes: [([UInt32], [UInt32])] = []
        var text: [UInt32] = []
        var children: [XmlNode] = []

        init(_ tag: [UInt32]) {
            self.tag = tag
            name = key(tag)
        }

        func attribute(_ name: [UInt32]) -> [UInt32]? {
            return attributes.first(where: { $0.0 == name })?.1
        }

        /// The member elements of an element holding a message, which must
        /// have only whitespace between them.
        public func members() throws -> [XmlNode] {
            if !trim(text).isEmpty {
                throw Invalid("text in a message element")
            }
            return children
        }

        /// A number member's text: an element holding only its text,
        /// surrounding whitespace allowed.
        func numberText() throws -> [UInt8] {
            if !children.isEmpty {
                throw Invalid("an element in a number")
            }
            return ascii(trim(text))
        }

        /// An integer member, as in JSON.
        public func integer(_ ctype: String, _ bits: Int) throws -> UInt64 {
            return try toInteger(numberText(), ctype, bits)
        }

        /// A float or double member, as in JSON.
        public func real(_ ctype: String) throws -> Double {
            return try toReal(numberText(), ctype)
        }

        static let encodingName = scalars("encoding")
        static let hexName = scalars("hex")

        /// A string member, into dst: the element's text, each character one
        /// byte, or with encoding="hex" the bytes in hexadecimal.
        public func bytes(_ dst: inout [UInt8]) throws {
            if !children.isEmpty {
                throw Invalid("an element in a string")
            }
            guard let encoding = attribute(XmlNode.encodingName) else {
                try textToBytes(text, &dst)
                return
            }
            if encoding != XmlNode.hexName {
                throw Invalid("unknown encoding")
            }
            let digits = Array(trim(text))
            if digits.count % 2 == 1 || digits.count / 2 > dst.count || digits.contains(where: { hexValue($0) == nil }) {
                throw Invalid("bad hex")
            }
            for i in 0..<dst.count {
                dst[i] = i < digits.count / 2 ? UInt8(hexValue(digits[2 * i])! * 16 + hexValue(digits[2 * i + 1])!) : 0
            }
        }
    }

    static func isNameStart(_ c: UInt32) -> Bool {
        return (c >= 0x61 && c <= 0x7A) || (c >= 0x41 && c <= 0x5A) || c == 0x5F || c == 0x3A || c >= 0x80
    }

    static func isNameChar(_ c: UInt32) -> Bool {
        return isNameStart(c) || isDigit(c) || c == 0x2D || c == 0x2E
    }

    /// Reads a subset of XML 1.0 that is enough for messages: elements,
    /// attributes, character data, CDATA, comments, processing instructions,
    /// the predefined entities and character references. A document type
    /// declaration, and so any other entity, is rejected.
    struct XmlParser {
        let s: [UInt32]
        var i = 0

        init(_ s: [UInt32]) {
            self.s = s
        }

        func peek() -> UInt32? {
            return i < s.count ? s[i] : nil
        }

        func starts(_ word: [UInt32]) -> Bool {
            return hasPrefix(s, i, word)
        }

        mutating func space() {
            while i < s.count && isSpace(s[i]) {
                i += 1
            }
        }

        func find(_ word: [UInt32], _ from: Int) -> Int? {
            var at = from
            while at < s.count {
                if hasPrefix(s, at, word) {
                    return at
                }
                at += 1
            }
            return nil
        }

        mutating func skipPast(_ end: [UInt32]) throws {
            guard let at = find(end, i) else {
                throw Invalid("unterminated")
            }
            i = at + end.count
        }

        static let commentOpen = scalars("<!--")
        static let commentClose = scalars("-->")
        static let piOpen = scalars("<?")
        static let piClose = scalars("?>")
        static let declOpen = scalars("<!")
        static let cdataOpen = scalars("<![CDATA[")
        static let cdataClose = scalars("]]>")
        static let endOpen = scalars("</")
        static let emptyClose = scalars("/>")
        static let semicolon = scalars(";")
        static let xmlDecl = scalars("<?xml")

        mutating func misc() throws {
            while true {
                space()
                if starts(XmlParser.commentOpen) {
                    i += 4
                    try skipPast(XmlParser.commentClose)
                } else if starts(XmlParser.piOpen) {
                    i += 2
                    try skipPast(XmlParser.piClose)
                } else if starts(XmlParser.declOpen) {
                    throw Invalid("a document type declaration")
                } else {
                    return
                }
            }
        }

        mutating func name() throws -> [UInt32] {
            guard let c = peek(), isNameStart(c) else {
                throw Invalid("expected a name")
            }
            let start = i
            while i < s.count && isNameChar(s[i]) {
                i += 1
            }
            return Array(s[start..<i])
        }

        static let entities: [([UInt32], UInt32)] = [
            (scalars("lt"), 0x3C), (scalars("gt"), 0x3E), (scalars("amp"), 0x26),
            (scalars("quot"), 0x22), (scalars("apos"), 0x27),
        ]

        mutating func reference(_ out: inout [UInt32]) throws {
            guard let semi = find(XmlParser.semicolon, i) else {
                throw Invalid("unterminated reference")
            }
            let r = Array(s[i..<semi])
            i = semi + 1
            if let entity = XmlParser.entities.first(where: { $0.0 == r }) {
                out.append(entity.1)
                return
            }
            if r.count <= 1 || r[0] != 0x23 {
                throw Invalid("unknown entity")
            }
            let hexadecimal = r[1] == 0x78
            let digits = r[(hexadecimal ? 2 : 1)...]
            let radix: UInt64 = hexadecimal ? 16 : 10
            if digits.isEmpty || digits.count > 8 {
                throw Invalid("bad character reference")
            }
            var v: UInt64 = 0
            for c in digits {
                if !isDigit(c) && !(hexadecimal && hexValue(c) != nil) {
                    throw Invalid("bad character reference")
                }
                v = v * radix + UInt64(hexValue(c)!)
            }
            let allowed = v == 0x9 || v == 0xA || v == 0xD || (v >= 0x20 && v <= 0xD7FF) ||
                (v >= 0xE000 && v <= 0xFFFD) || (v >= 0x10000 && v <= 0x10FFFF)
            if !allowed {
                throw Invalid("character not allowed")
            }
            out.append(UInt32(v))
        }

        /// Character data up to stop (not consumed), into out.
        mutating func chars(_ out: inout [UInt32], _ stop: UInt32, _ attribute: Bool) throws {
            while i < s.count {
                let c = s[i]
                if c == stop {
                    break
                }
                if c == 0x3C {
                    throw Invalid("< in an attribute")
                }
                if c == 0x26 {
                    i += 1
                    try reference(&out)
                    continue
                }
                if c == 0x0D {
                    // CR LF and a lone CR are both a line end.
                    i += 1
                    if peek() == 0x0A {
                        i += 1
                    }
                    out.append(attribute ? 0x20 : 0x0A)
                    continue
                }
                out.append(attribute && (c == 0x0A || c == 0x09) ? 0x20 : c)
                i += 1
            }
        }

        mutating func element(_ outer: Int) throws -> XmlNode {
            let depth = outer + 1
            if depth > maxDepth {
                throw Invalid("nested too deeply")
            }
            i += 1 // "<"
            let node = XmlNode(try name())
            while true {
                let before = i
                space()
                if i >= s.count {
                    throw Invalid("unterminated start tag")
                }
                if starts(XmlParser.emptyClose) {
                    i += 2
                    return node
                }
                if peek() == 0x3E {
                    i += 1
                    break
                }
                if i == before {
                    throw Invalid("attributes must be separated by whitespace")
                }
                let attributeName = try name()
                space()
                if peek() != 0x3D {
                    throw Invalid("expected =")
                }
                i += 1
                space()
                guard let quote = peek(), quote == 0x22 || quote == 0x27 else {
                    throw Invalid("expected a quote")
                }
                i += 1
                var value: [UInt32] = []
                try chars(&value, quote, true)
                if i >= s.count {
                    throw Invalid("unterminated attribute")
                }
                i += 1
                if node.attribute(attributeName) != nil {
                    throw Invalid("repeated attribute")
                }
                node.attributes.append((attributeName, value))
            }

            while true {
                if i >= s.count {
                    throw Invalid("unterminated element")
                }
                if starts(XmlParser.endOpen) {
                    i += 2
                    if try name() != node.tag {
                        throw Invalid("mismatched end tag")
                    }
                    space()
                    if peek() != 0x3E {
                        throw Invalid("bad end tag")
                    }
                    i += 1
                    return node
                } else if starts(XmlParser.commentOpen) {
                    i += 4
                    try skipPast(XmlParser.commentClose)
                } else if starts(XmlParser.cdataOpen) {
                    i += 9
                    guard let end = find(XmlParser.cdataClose, i) else {
                        throw Invalid("unterminated CDATA")
                    }
                    var j = i
                    while j < end {
                        var c = s[j]
                        if c == 0x0D {
                            if j + 1 < end && s[j + 1] == 0x0A {
                                j += 1
                            }
                            c = 0x0A
                        }
                        node.text.append(c)
                        j += 1
                    }
                    i = end + 3
                } else if starts(XmlParser.piOpen) {
                    i += 2
                    try skipPast(XmlParser.piClose)
                } else if starts(XmlParser.declOpen) {
                    throw Invalid("a declaration in content")
                } else if peek() == 0x3C {
                    node.children.append(try element(depth))
                } else {
                    try chars(&node.text, 0x3C, false)
                }
            }
        }

        mutating func document(_ root: String) throws -> XmlNode {
            for c in s where (c < 0x20 && c != 0x9 && c != 0xA && c != 0xD) || c == 0xFFFE || c == 0xFFFF {
                throw Invalid("character not allowed in XML")
            }
            if starts(XmlParser.xmlDecl) && s.count > 5 && isSpace(s[5]) {
                try skipPast(XmlParser.piClose)
            }
            try misc()
            if peek() != 0x3C {
                throw Invalid("no root element")
            }
            let node = try element(0)
            try misc()
            if i != s.count {
                throw Invalid("text after the root element")
            }
            if node.tag != scalars(root) {
                throw Invalid("root element is not " + root)
            }
            return node
        }
    }

    /// Parses a whole XML document whose root element is root. Invalid if it
    /// is not well-formed in the subset XmlParser takes.
    public static func parseXml(_ input: String, _ root: String) throws -> XmlNode {
        var p = XmlParser(decode(input))
        return try p.document(root)
    }

