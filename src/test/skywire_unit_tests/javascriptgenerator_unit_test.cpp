TEST_F(JavaScriptGeneratorUnitTest, RejectsCollidingNames)
{
    // a's backing field is _a; s's text getter is sText.
    EXPECT_FALSE(generate(R"({"1":{"type":"uint8_t","name":"a"},"2":{"type":"uint8_t","name":"_a"}})"));
    EXPECT_NE(errorcode & SW_SPEC_INVALID, 0u);

    errorcode = SW_SUCCESS;
    EXPECT_FALSE(generate(R"({"1":{"type":"string","name":"s","length":4},"2":{"type":"uint8_t","name":"sText"}})"));
    EXPECT_NE(errorcode & SW_SPEC_INVALID, 0u);

    errorcode = SW_SUCCESS;
    EXPECT_TRUE(generate(R"({"1":{"type":"uint8_t","name":"s"},"2":{"type":"uint8_t","name":"sText"}})"));
}

TEST_F(JavaScriptGeneratorUnitTest, BitfieldsPackIntoNumberUnits)
{
    ASSERT_TRUE(generate(R"({
        "1":{"type":"uint16_t","name":"a","bits":5,"endian":0},
        "2":{"type":"int16_t","name":"b","bits":6,"endian":0},
        "3":{"type":"uint16_t","name":"c","bits":3,"endian":0}})"));

    // a and c share a unit; b's type differs, so it has its own.
    EXPECT_TRUE(has_line("    let unit_0 = 0;"));
    EXPECT_TRUE(has_line("    unit_0 |= (this._a & 0x1f);"));
    EXPECT_TRUE(has_line("    view.setUint16(offset, unit_0, true);"));
    EXPECT_TRUE(has_line("    unit_1 |= (this._b & 0x3f);"));
    EXPECT_TRUE(has_line("    const unit_0 = view.getUint16(offset, true);"));
    EXPECT_TRUE(has_line("    this._a = unit_0 & 0x1f;"));
    // Signed fields sign-extend through an int32.
    EXPECT_TRUE(has_line("    this._b = (unit_1 << 26) >> 26;"));

    EXPECT_TRUE(has_line("  set a(v) { this._a = v & 0x1f; }"));
    EXPECT_TRUE(has_line("  set b(v) { this._b = (v << 26) >> 26; }"));
    EXPECT_TRUE(has_line("Object.defineProperty(TestClass, \"SIZE\", { value: 6, enumerable: true });"));
}

TEST_F(JavaScriptGeneratorUnitTest, BitfieldShiftsAndFullWidth)
{
    ASSERT_TRUE(generate(R"({
        "1":{"type":"uint32_t","name":"lo","bits":4,"endian":1},
        "2":{"type":"uint32_t","name":"hi","bits":28,"endian":1},
        "3":{"type":"int32_t","name":"all","bits":32,"endian":1},
        "4":{"type":"uint32_t","name":"whole","bits":32,"endian":1}})"));

    EXPECT_TRUE(has_line("    unit_0 |= ((this._hi & 0xfffffff) << 4);"));
    EXPECT_TRUE(has_line("    this._hi = (unit_0 >>> 4) & 0xfffffff;"));
    EXPECT_TRUE(has_line("    this._all = unit_1 | 0;"));
    EXPECT_TRUE(has_line("    this._whole = unit_2 >>> 0;"));
    EXPECT_TRUE(has_line("  set whole(v) { this._whole = v >>> 0; }"));
}

TEST_F(JavaScriptGeneratorUnitTest, SixtyFourBitBitfieldsUseBigInt)
{
    ASSERT_TRUE(generate(R"({
        "1":{"type":"uint64_t","name":"a","bits":33,"endian":1},
        "2":{"type":"uint64_t","name":"b","bits":31,"endian":1},
        "3":{"type":"int64_t","name":"c","bits":40,"endian":1}})"));

    EXPECT_TRUE(has_line("    let unit_0 = 0n;"));
    EXPECT_TRUE(has_line("    unit_0 |= BigInt.asUintN(33, this._a);"));
    EXPECT_TRUE(has_line("    unit_0 |= (BigInt.asUintN(31, this._b) << 33n);"));
    EXPECT_TRUE(has_line("    view.setBigUint64(offset, unit_0, false);"));
    EXPECT_TRUE(has_line("    const unit_0 = view.getBigUint64(offset, false);"));
    EXPECT_TRUE(has_line("    this._b = BigInt.asUintN(31, (unit_0 >> 33n));"));
    EXPECT_TRUE(has_line("    this._c = BigInt.asIntN(40, unit_1);"));
    EXPECT_TRUE(has_line("  set a(v) { this._a = BigInt.asUintN(33, BigInt(v)); }"));
    EXPECT_TRUE(has_line("  set c(v) { this._c = BigInt.asIntN(40, BigInt(v)); }"));
}

TEST_F(JavaScriptGeneratorUnitTest, ImportsFollowTheLangFilePattern)
{
    // A CommonJS package renames the outputs to .mjs; nested imports follow.
    std::string lang = lang_spec_.get_value_string("outputimplfilename");
    ASSERT_EQ(lang, "{classname}.js");

    Specification mjs;
    ASSERT_TRUE(mjs.read_file(std::string(SKYWIRE_LANG_DIR) + "/javascript/lang.javascript.json"));
    (*mjs.get_proto_ref().mutable_string_values())["outputimplfilename"] = "{classname}.mjs";
    ASSERT_TRUE(msg_spec_.read_string(R"({"stringValues":{"classname":"TestClass"},"members":{"1":{"type":"Inner","name":"n"}}})"));

    JavaScriptGenerator unit(msg_spec_, mjs);
    ASSERT_TRUE(unit.generate(errorcode));
    js = unit.get_results()["implementation"];
    EXPECT_TRUE(has_line("import { Inner } from \"./Inner.mjs\";"));
}

class JavaScriptTestGeneratorUnitTest : public JavaScriptGeneratorUnitTest
{
protected:
    std::string test;

    bool generate_test(const std::string& members)
    {
        std::string json = R"({"stringValues":{"classname":"TestClass","outputimplfilename":"TestClass.js"},"members":)" + members + "}";
        EXPECT_TRUE(msg_spec_.read_string(json));

        JavaScriptTestGenerator unit(msg_spec_, lang_spec_);
        bool success = unit.generate(errorcode);
        test = unit.get_results()["unittest"];
        return success;
    }

    bool test_has(const std::string& text) const
    {
        return test.find(text) != std::string::npos;
    }
};

TEST_F(JavaScriptTestGeneratorUnitTest, NodeTestWithNoPackages)
{
    ASSERT_TRUE(generate_test(R"({"1":{"type":"uint8_t","name":"a"}})"));

    EXPECT_TRUE(test_has("import { test } from \"node:test\";\n"));
    EXPECT_TRUE(test_has("import assert from \"node:assert/strict\";\n"));
    EXPECT_TRUE(test_has("import { TestClass } from \"./TestClass.js\";\n"));
    for (const char* name : { "RoundTrip", "Fresh", "Equals", "ShortBuffer", "Offset", "Wire", "SetterWrap" })
    {
        EXPECT_TRUE(test_has(std::string("test(\"TestClass ") + name + "\"")) << name;
    }
    EXPECT_FALSE(test_has("BitfieldSetters"));
    EXPECT_FALSE(test_has("Strings"));
}

TEST_F(JavaScriptTestGeneratorUnitTest, LiteralsSuitTheType)
{
    ASSERT_TRUE(generate_test(R"({
        "1":{"type":"uint32_t","name":"a","endian":1},
        "2":{"type":"int64_t","name":"b","endian":1},
        "3":{"type":"float","name":"c","endian":1},
        "4":{"type":"string","name":"d","length":4},
        "5":{"type":"uint64_t","name":"e","bits":40,"endian":1}})"));

    EXPECT_TRUE(test_has("msg.a = 3000000000;"));
    EXPECT_TRUE(test_has("msg.b = -9000000000n;"));
    EXPECT_TRUE(test_has("msg.c = 3.5;"));
    EXPECT_TRUE(test_has("msg.d = \"skywire\";"));
    EXPECT_TRUE(test_has("msg.e = 0x"));
    EXPECT_TRUE(test_has("n;\n  assert.equal(msg.e, "));
    EXPECT_TRUE(test_has("test(\"TestClass Strings\""));
    EXPECT_TRUE(test_has("test(\"TestClass BitfieldSetters\""));
}

