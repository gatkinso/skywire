TEST_F(CSharpGeneratorUnitTest, RejectsKeywordTypeNames)
{
    ASSERT_FALSE(generate(R"({"1":{"type":"uint8_t","name":"a"}})", R"("classname":"object")"));
    ASSERT_NE(errorcode & SW_SPEC_INVALID, 0u);

    errorcode = SW_SUCCESS;
    ASSERT_FALSE(generate(R"({"1":{"type":"decimal","name":"a"}})"));
    ASSERT_NE(errorcode & SW_SPEC_INVALID, 0u);
}

TEST_F(CSharpGeneratorUnitTest, RejectsNamesTheClassUses)
{
    for (const char* name : { "Size", "Serialize", "Deserialize", "Equals", "GetHashCode", "ToString", "GetType", "PutLE16", "GetBE64", "PutNE32", "PutBytes", "TestClass" })
    {
        errorcode = SW_SUCCESS;
        ASSERT_FALSE(generate(std::string(R"({"1":{"type":"uint8_t","name":")") + name + R"("}})")) << name;
        ASSERT_NE(errorcode & SW_SPEC_INVALID, 0u) << name;
    }

    // C# is case-sensitive.
    errorcode = SW_SUCCESS;
    ASSERT_TRUE(generate(R"({"1":{"type":"uint8_t","name":"size"}})"));
}

TEST_F(CSharpGeneratorUnitTest, RejectsCollidingNames)
{
    // a's field is m_a.
    ASSERT_FALSE(generate(R"({"1":{"type":"uint8_t","name":"a"},"2":{"type":"uint8_t","name":"m_a"}})"));
    ASSERT_NE(errorcode & SW_SPEC_INVALID, 0u);

    errorcode = SW_SUCCESS;
    ASSERT_FALSE(generate(R"({"1":{"type":"string","name":"s","length":2},"2":{"type":"uint8_t","name":"Get_s"}})"));
    ASSERT_NE(errorcode & SW_SPEC_INVALID, 0u);

    // Only a string member has Get_/Set_ methods.
    errorcode = SW_SUCCESS;
    ASSERT_TRUE(generate(R"({"1":{"type":"uint8_t","name":"s"},"2":{"type":"uint8_t","name":"Get_s"}})"));
}

TEST_F(CSharpGeneratorUnitTest, BitfieldsPackIntoLocalUnits)
{
    ASSERT_TRUE(generate(R"({
        "1":{"type":"uint8_t","name":"a","bits":3},
        "2":{"type":"uint8_t","name":"b","bits":5},
        "3":{"type":"int16_t","name":"c","bits":9,"endian":1}})"));

    EXPECT_TRUE(has_line("            ulong unit_0 = 0;"));
    EXPECT_TRUE(has_line("            unit_0 |= (m_a & 0x7UL);"));
    EXPECT_TRUE(has_line("            unit_0 |= (m_b & 0x1fUL) << 3;"));
    EXPECT_TRUE(has_line("            buf[o] = unchecked((byte)unit_0);"));
    EXPECT_TRUE(has_line("            unit_1 |= (unchecked((ulong)m_c) & 0x1ffUL);"));
    EXPECT_TRUE(has_line("            PutLE16(buf, o + 1, unchecked((ushort)unit_1));"));

    EXPECT_TRUE(has_line("            ulong unit_0 = buf[o];"));
    EXPECT_TRUE(has_line("            m_a = unchecked((byte)((unit_0 << 61) >> 61));"));
    EXPECT_TRUE(has_line("            m_b = unchecked((byte)((unit_0 << 56) >> 59));"));
    EXPECT_TRUE(has_line("            ulong unit_1 = GetLE16(buf, o + 1);"));
    EXPECT_TRUE(has_line("            m_c = unchecked((short)(unchecked((long)(unit_1 << 55)) >> 55));"));

    EXPECT_TRUE(has_line("            return 3;"));
}

TEST_F(CSharpGeneratorUnitTest, BitfieldSettersMaskOrSignExtend)
{
    ASSERT_TRUE(generate(R"({
        "1":{"type":"uint8_t","name":"a","bits":3},
        "2":{"type":"int32_t","name":"b","bits":7},
        "3":{"type":"uint64_t","name":"c","bits":33},
        "4":{"type":"int64_t","name":"d","bits":64},
        "5":{"type":"int8_t","name":"e","bits":3}})"));

    EXPECT_TRUE(has("public byte a { get { return m_a; } set { m_a = unchecked((byte)(value & 0x7)); } }"));
    EXPECT_TRUE(has("public int b { get { return m_b; } set { m_b = (value << 25) >> 25; } }"));
    EXPECT_TRUE(has("public ulong c { get { return m_c; } set { m_c = value & 0x1ffffffffUL; } }"));
    EXPECT_TRUE(has("public long d { get { return m_d; } set { m_d = value; } }"));
    EXPECT_TRUE(has("public sbyte e { get { return m_e; } set { m_e = unchecked((sbyte)((value << 29) >> 29)); } }"));
    EXPECT_TRUE(has_line("            m_d = unchecked((long)unit_3);"));
}

