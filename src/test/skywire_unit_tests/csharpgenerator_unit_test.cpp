// Runs CSharpTestGenerator over a spec.
class CSharpTestGeneratorUnitTest : public CSharpGeneratorUnitTest
{
protected:
    std::string test;

    bool generate_test(const std::string& members)
    {
        std::string json = R"({"stringValues":{"classname":"TestClass","namespace":"testspace"},"members":)" + members + "}";
        EXPECT_TRUE(msg_spec_.read_string(json));

        CSharpTestGenerator unit(msg_spec_, lang_spec_);
        bool success = unit.generate(errorcode);
        test = unit.get_results()["unittest"];
        return success;
    }

    bool test_has(const std::string& text) const
    {
        return test.find(text) != std::string::npos;
    }
};

TEST_F(CSharpTestGeneratorUnitTest, RunAndOptionalMain)
{
    ASSERT_TRUE(generate_test(R"({"1":{"type":"uint8_t","name":"a"}})"));

    EXPECT_TRUE(test_has("\n    public static class TestClassTest\n"));
    EXPECT_TRUE(test_has("\n        public static int Run()\n"));
    EXPECT_TRUE(test_has("\n#if !SKYWIRE_NO_MAIN\n\n        public static int Main()\n"));
    EXPECT_TRUE(test_has("\n#endif\n    }\n}\n"));
    EXPECT_TRUE(test_has("RunTest(\"Wire\", TestWire);"));
    EXPECT_TRUE(test_has("RunTest(\"Offset\", TestOffset);"));
}

TEST_F(CSharpTestGeneratorUnitTest, LiteralsSuitTheType)
{
    ASSERT_TRUE(generate_test(R"({
        "1":{"type":"uint32_t","name":"a"},
        "2":{"type":"int64_t","name":"b"},
        "3":{"type":"float","name":"c"},
        "4":{"type":"string","name":"d","length":4},
        "5":{"type":"uint64_t","name":"event"}})"));

    EXPECT_TRUE(test_has("msg.a = 3000000000U;"));
    EXPECT_TRUE(test_has("msg.b = -9000000000L;"));
    EXPECT_TRUE(test_has("msg.c = 3.5f;"));
    EXPECT_TRUE(test_has("msg.Set_d(Encoding.ASCII.GetBytes(\"skywire\"));"));
    EXPECT_TRUE(test_has("msg.@event = 12000000000UL;"));
    EXPECT_TRUE(test_has("using System.Text;"));
}

TEST_F(CSharpTestGeneratorUnitTest, OutOfRangeBitfieldValueIsUnchecked)
{
    ASSERT_TRUE(generate_test(R"({"1":{"type":"int8_t","name":"a","bits":3},"2":{"type":"uint8_t","name":"b","bits":5}})"));

    EXPECT_TRUE(test_has("msg.a = unchecked((sbyte)0x"));
    EXPECT_TRUE(test_has("RunTest(\"BitfieldSetters\", TestBitfieldSetters);"));
}

TEST_F(CSharpTestGeneratorUnitTest, NestedMessageHasNoWireTest)
{
    ASSERT_TRUE(generate_test(R"({"1":{"type":"uint8_t","name":"a"},"2":{"type":"NestyInner","name":"n"}})"));

    EXPECT_FALSE(test_has("TestWire"));
    EXPECT_FALSE(test_has("msg.n ="));
}
