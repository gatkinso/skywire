TEST_F(RustGeneratorUnitTest, BitfieldsPackIntoLocalUnits)
{
    // lsb order: a takes bits 0-2, b bits 3-7 of one byte; s5/s11 share a
    // little-endian u16, written as one integer.
    ASSERT_TRUE(generate(R"({
        "1":{"type":"uint8_t","name":"a","bits":3},
        "2":{"type":"uint8_t","name":"b","bits":5},
        "3":{"type":"int16_t","name":"s5","bits":5,"endian":1},
        "4":{"type":"int16_t","name":"s11","bits":11,"endian":1},
        "5":{"type":"uint32_t","name":"whole","bits":32}})"));

    EXPECT_TRUE(has_line("    pub const SIZE: usize = 7;"));

    EXPECT_TRUE(has("\n        let mut u0 = self.a & 0x7;\n"
                    "        u0 |= (self.b & 0x1f) << 3;\n"
                    "        buf[0] = u0;\n"
                    "        let buf = &mut buf[1..];\n"
                    "        let mut u1 = (self.s5 as u16) & 0x1f;\n"
                    "        u1 |= ((self.s11 as u16) & 0x7ff) << 5;\n"
                    "        buf[..2].copy_from_slice(&u1.to_le_bytes());\n"
                    "        let buf = &mut buf[2..];\n"
                    "        let u2 = self.whole;\n"
                    "        buf[..4].copy_from_slice(&u2.to_be_bytes());\n"));

    EXPECT_TRUE(has("\n        let u0 = buf[0];\n"
                    "        self.a = (u0 << 5) >> 5;\n"
                    "        self.b = u0 >> 3;\n"
                    "        let buf = &buf[1..];\n"
                    "        let u1 = u16::from_le_bytes(buf[..2].try_into().unwrap());\n"
                    "        self.s5 = ((u1 << 11) as i16) >> 11;\n"
                    "        self.s11 = (u1 as i16) >> 5;\n"
                    "        let buf = &buf[2..];\n"
                    "        let u2 = u32::from_be_bytes(buf[..4].try_into().unwrap());\n"
                    "        self.whole = u2;\n"));

    EXPECT_TRUE(has_line("        self.a = (newval << 5) >> 5;"));
    EXPECT_TRUE(has_line("        self.s11 = (newval << 5) >> 5;"));
    // A field as wide as its type needs no masking setter.
    EXPECT_TRUE(has_line("        self.whole = newval;"));
}

