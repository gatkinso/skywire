// Sets each of members on "in" to its shared test value; a nested message
// gets the value its make_expected_<type>() builds.
void CppRelayGenerator::relay_sets(const members_t& members)
{
    for (auto& member : members)
    {
        const std::string& type = std::get<member_type>(member.second);
        const std::string& name = std::get<member_name>(member.second);

        if (is_string_type(type))
        {
            ss_ << "    in.Set_" << name << "(\"" << test_values::string_value() << "\");\n";
        }
        else if (is_user_type(type))
        {
            ss_ << "    in.Set_" << name << "(make_expected_" << type << "());\n";
        }
        else
        {
            ss_ << "    in.Set_" << name << "(" << test_literal(member.second) << ");\n";
        }
    }
}

bool CppRelayGenerator::generate(int& errorcode)
{
    errorcode = 0;
    results_.clear();

    const std::string classname = msg_spec_.get_value_string("namespace") + "::" + msg_spec_.get_value_string("classname");
    const std::string hdr_name = msg_spec_.get_value_string("outputheaderfilename");

    // The relay checks every member, inside nested messages too, against the
    // shared test values.
    std::vector<leaf_t> leaves;
    if (false == relay_leaves(leaves, errorcode))
    {
        return false;
    }

    ss_ << "// Code generated by wiregen. DO NOT EDIT.\n";
    ss_ << "// Cross-language relay: <program> <input file> <output file>\n\n";
    ss_ << "#include <cstdio>\n";
    ss_ << "#include <cstring>\n";
    ss_ << "#include <fstream>\n";
    ss_ << "#include <iterator>\n";
    ss_ << "#include <vector>\n";
    ss_ << "#include \"" << hdr_name << "\"\n\n";

    ss_ << "namespace\n";
    ss_ << "{\n\n";
    ss_ << "int failures = 0;\n\n";

    ss_ << "void fail(const char* what)\n";
    ss_ << "{\n";
    ss_ << "    std::printf(\"FAIL c++: %s\\n\", what);\n";
    ss_ << "    failures++;\n";
    ss_ << "}\n\n";

    ss_ << "void dump(const char* label, const void* p, size_t n)\n";
    ss_ << "{\n";
    ss_ << "    const unsigned char* b = static_cast<const unsigned char*>(p);\n";
    ss_ << "    std::printf(\"    %s\", label);\n";
    ss_ << "    for (size_t i = 0; i < n; i++)\n";
    ss_ << "        std::printf(\" %02x\", b[i]);\n";
    ss_ << "    std::printf(\"\\n\");\n";
    ss_ << "}\n\n";

    ss_ << "void check_bytes(const char* name, const void* got, const void* want, size_t n)\n";
    ss_ << "{\n";
    ss_ << "    if (std::memcmp(got, want, n) != 0)\n";
    ss_ << "    {\n";
    ss_ << "        std::printf(\"FAIL c++: member %s differs\\n\", name);\n";
    ss_ << "        dump(\"got \", got, n);\n";
    ss_ << "        dump(\"want\", want, n);\n";
    ss_ << "        failures++;\n";
    ss_ << "    }\n";
    ss_ << "}\n\n";

    ss_ << "template <typename T>\n";
    ss_ << "void check_member(const char* name, const T got, const T want)\n";
    ss_ << "{\n";
    ss_ << "    check_bytes(name, &got, &want, sizeof(T));\n";
    ss_ << "}\n\n";

    // Getters and setters copy a nested message, so each nested type gets a
    // function that builds its expected value, before the types that use it.
    const std::string name_space = msg_spec_.get_value_string("namespace");
    for (auto& type : nested_types_in_order())
    {
        ss_ << name_space << "::" << type << " make_expected_" << type << "()\n";
        ss_ << "{\n";
        ss_ << "    " << name_space << "::" << type << " in;\n";
        relay_sets(nested_members_[type]);
        ss_ << "    return in;\n";
        ss_ << "}\n\n";
    }

    ss_ << classname << " make_expected()\n";
    ss_ << "{\n";
    ss_ << "    " << classname << " in;\n";
    relay_sets(ordered_members_);
    ss_ << "    return in;\n";
    ss_ << "}\n\n";
    ss_ << "}\n\n";

    ss_ << "int main(int argc, char** argv)\n";
    ss_ << "{\n";
    ss_ << "    if (argc != 3)\n";
    ss_ << "    {\n";
    ss_ << "        std::fprintf(stderr, \"usage: %s <input file> <output file>\\n\", argv[0]);\n";
    ss_ << "        return 2;\n";
    ss_ << "    }\n\n";

    ss_ << "    std::ifstream file(argv[1], std::ios::binary);\n";
    ss_ << "    if (!file)\n";
    ss_ << "    {\n";
    ss_ << "        std::printf(\"FAIL c++: cannot read %s\\n\", argv[1]);\n";
    ss_ << "        return 1;\n";
    ss_ << "    }\n";
    ss_ << "    const std::vector<char> data((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());\n";
    ss_ << "    if (data.size() != " << classname << "::size())\n";
    ss_ << "    {\n";
    ss_ << "        std::printf(\"FAIL c++: input is %zu bytes, size() is %zu\\n\", data.size(), " << classname << "::size());\n";
    ss_ << "        return 1;\n";
    ss_ << "    }\n\n";

    ss_ << "    const " << classname << " want = make_expected();\n";
    ss_ << "    " << classname << " got;\n";
    ss_ << "    skyloupe::Stream in;\n";
    ss_ << "    in.write(data.data(), data.size());\n";
    ss_ << "    if (!got.deserialize(in))\n";
    ss_ << "    {\n";
    ss_ << "        fail(\"deserialize failed\");\n";
    ss_ << "        return 1;\n";
    ss_ << "    }\n";
    ss_ << "    if (in.byte_size() != 0)\n";
    ss_ << "    {\n";
    ss_ << "        fail(\"deserialize left bytes unread\");\n";
    ss_ << "    }\n\n";

    for (auto& leaf : leaves)
    {
        const std::string name = leaf.join(".");
        const std::string getters = leaf.join("", ".Get_", "()");

        if (is_string_type(std::get<member_type>(leaf.member)))
        {
            ss_ << "    check_bytes(\"" << name << "\", got" << getters << ", want" << getters << ", "
                << std::get<member_length>(leaf.member) << ");\n";
        }
        else
        {
            ss_ << "    check_member(\"" << name << "\", got" << getters << ", want" << getters << ");\n";
        }
    }
    ss_ << "    if (!(got == want))\n";
    ss_ << "    {\n";
    ss_ << "        fail(\"operator== is false\");\n";
    ss_ << "    }\n\n";

    ss_ << "    skyloupe::Stream out;\n";
    ss_ << "    if (!got.serialize(out))\n";
    ss_ << "    {\n";
    ss_ << "        fail(\"serialize failed\");\n";
    ss_ << "        return 1;\n";
    ss_ << "    }\n";
    ss_ << "    if (out.byte_size() != data.size() || std::memcmp(out.data(), data.data(), data.size()) != 0)\n";
    ss_ << "    {\n";
    ss_ << "        fail(\"re-serialized bytes differ from the input\");\n";
    ss_ << "        dump(\"got \", out.data(), out.byte_size());\n";
    ss_ << "        dump(\"want\", data.data(), data.size());\n";
    ss_ << "    }\n\n";

    ss_ << "    std::ofstream outfile(argv[2], std::ios::binary);\n";
    ss_ << "    outfile.write(out.data(), out.byte_size());\n";
    ss_ << "    outfile.close();\n";
    ss_ << "    if (!outfile)\n";
    ss_ << "    {\n";
    ss_ << "        std::printf(\"FAIL c++: cannot write %s\\n\", argv[2]);\n";
    ss_ << "        failures++;\n";
    ss_ << "    }\n\n";

    ss_ << "    if (failures == 0)\n";
    ss_ << "        std::printf(\"PASS c++: %zu bytes, " << leaves.size() << " members intact\\n\", data.size());\n";
    ss_ << "    return failures == 0 ? 0 : 1;\n";
    ss_ << "}\n";

    results_["relay"] = ss_.str();

    return true;
}

