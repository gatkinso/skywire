bool JavaScriptRelayGenerator::generate(int& errorcode)
{
    errorcode = 0;
    results_.clear();

    const std::string classname = msg_spec_.get_value_string("classname");

    // The relay checks every member, inside nested messages too, against the
    // shared test values.
    std::vector<leaf_t> leaves;
    if (false == relay_leaves(leaves, errorcode))
    {
        return false;
    }

    // The relay runs under Node, so it may use node:fs; the message module
    // does not.
    ss_ << "// Code generated by wiregen. DO NOT EDIT.\n";
    ss_ << "// Cross-language relay: node <program> <input file> <output file>\n\n";
    ss_ << "import { readFileSync, writeFileSync } from \"node:fs\";\n";
    ss_ << "import { " << classname << " } from \"" << module_name() << "\";\n\n";
    ss_ << "const MEMBERS = [\n";
    for (auto& leaf : leaves)
    {
        ss_ << "  \"" << leaf.join(".") << "\",\n";
    }
    ss_ << "];\n\n";

    // A member of a nested message is named by its path, e.g. "inner.count".
    ss_ << "function get(msg, path) {\n";
    ss_ << "  for (const name of path.split(\".\")) {\n";
    ss_ << "    msg = msg[name];\n";
    ss_ << "  }\n";
    ss_ << "  return msg;\n";
    ss_ << "}\n\n";

    // A nested message's getter returns the message itself, so its members
    // are set through it.
    ss_ << "function makeMessage() {\n";
    ss_ << "  const msg = new " << classname << "();\n";
    for (auto& leaf : leaves)
    {
        ss_ << set_line("msg" + leaf.join_parents(".", ""), leaf.member);
    }
    ss_ << "  return msg;\n";
    ss_ << "}\n\n";

    ss_ << "function hex(bytes) {\n";
    ss_ << "  return Array.from(bytes, (b) => b.toString(16).padStart(2, \"0\")).join(\" \");\n";
    ss_ << "}\n\n";

    // Same type and value: a Number never matches a BigInt, and strings
    // compare bytewise.
    ss_ << "function same(got, want) {\n";
    ss_ << "  if (want instanceof Uint8Array) {\n";
    ss_ << "    return got instanceof Uint8Array && hex(got) === hex(want);\n";
    ss_ << "  }\n";
    ss_ << "  return typeof got === typeof want && Object.is(got, want);\n";
    ss_ << "}\n\n";

    ss_ << "function main(args) {\n";
    ss_ << "  if (args.length !== 2) {\n";
    ss_ << "    console.error(\"usage: node " << msg_spec_.get_value_string("outputrelayfilename", classname + "Relay.js")
        << " <input file> <output file>\");\n";
    ss_ << "    return 2;\n";
    ss_ << "  }\n\n";

    ss_ << "  let failures = 0;\n";
    ss_ << "  const fail = (what) => {\n";
    ss_ << "    console.log(\"FAIL javascript: \" + what);\n";
    ss_ << "    failures++;\n";
    ss_ << "  };\n\n";

    ss_ << "  const data = new Uint8Array(readFileSync(args[0]));\n";
    ss_ << "  const got = new " << classname << "();\n";
    ss_ << "  if (data.length !== got.size()) {\n";
    ss_ << "    console.log(`FAIL javascript: input is ${data.length} bytes, size() is ${got.size()}`);\n";
    ss_ << "    return 1;\n";
    ss_ << "  }\n";
    ss_ << "  try {\n";
    ss_ << "    got.deserialize(data);\n";
    ss_ << "  } catch (e) {\n";
    ss_ << "    console.log(\"FAIL javascript: deserialize: \" + e.message);\n";
    ss_ << "    return 1;\n";
    ss_ << "  }\n\n";

    ss_ << "  const want = makeMessage();\n";
    ss_ << "  for (const name of MEMBERS) {\n";
    ss_ << "    const g = get(got, name);\n";
    ss_ << "    const w = get(want, name);\n";
    ss_ << "    if (!same(g, w)) {\n";
    ss_ << "      fail(`member ${name} differs\\n    got  ${g}\\n    want ${w}`);\n";
    ss_ << "    }\n";
    ss_ << "  }\n";
    ss_ << "  if (!got.equals(want)) {\n";
    ss_ << "    fail(\"equals() is false\");\n";
    ss_ << "  }\n\n";

    ss_ << "  const out = got.serialize();\n";
    ss_ << "  if (hex(out) !== hex(data)) {\n";
    ss_ << "    fail(`re-serialized bytes differ from the input\\n    got  ${hex(out)}\\n    want ${hex(data)}`);\n";
    ss_ << "  }\n";
    ss_ << "  writeFileSync(args[1], out);\n\n";

    ss_ << "  if (failures > 0) {\n";
    ss_ << "    return 1;\n";
    ss_ << "  }\n";
    ss_ << "  console.log(`PASS javascript: ${data.length} bytes, ${MEMBERS.length} members intact`);\n";
    ss_ << "  return 0;\n";
    ss_ << "}\n\n";

    ss_ << "process.exitCode = main(process.argv.slice(2));\n";

    results_["relay"] = ss_.str();

    return true;
}

