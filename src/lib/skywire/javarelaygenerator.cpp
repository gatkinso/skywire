bool JavaRelayGenerator::generate(int& errorcode)
{
    errorcode = 0;
    results_.clear();

    const std::string classname = msg_spec_.get_value_string("classname");
    const std::string package = msg_spec_.get_value_string("namespace");

    // A public Java class must be named after its file.
    std::string relayclass = msg_spec_.get_value_string("outputrelayfilename", classname + "Relay.java");
    relayclass = relayclass.substr(0, relayclass.rfind(".java"));

    // The relay checks every member, inside nested messages too, against the
    // shared test values.
    std::vector<leaf_t> leaves;
    if (false == relay_leaves(leaves, errorcode))
    {
        return false;
    }

    bool have_string = false;
    for (auto& leaf : leaves)
    {
        have_string = have_string || is_string_type(std::get<member_type>(leaf.member));
    }

    ss_ << "// Code generated by wiregen. DO NOT EDIT.\n";
    ss_ << "// Cross-language relay: <program> <input file> <output file>\n\n";
    ss_ << "package " << package << ";\n\n";
    ss_ << "import java.io.IOException;\n";
    if (have_string)
    {
        ss_ << "import java.nio.charset.StandardCharsets;\n";
    }
    ss_ << "import java.nio.file.Files;\n";
    ss_ << "import java.nio.file.Paths;\n";
    ss_ << "import java.util.Arrays;\n\n";

    ss_ << "public final class " << relayclass << " {\n";
    ss_ << "    private static int failures = 0;\n\n";

    ss_ << "    private static " << classname << " makeMessage() {\n";
    ss_ << "        " << classname << " msg = new " << classname << "();\n";
    // A nested message's getter returns the message itself, so its members are set through it.
    for (auto& leaf : leaves)
    {
        ss_ << set_line("msg" + leaf.join_parents(".Get_", "()"), leaf.member);
    }
    ss_ << "        return msg;\n";
    ss_ << "    }\n\n";

    ss_ << "    private static void fail(String what) {\n";
    ss_ << "        System.out.println(\"FAIL java: \" + what);\n";
    ss_ << "        failures++;\n";
    ss_ << "    }\n\n";

    ss_ << "    private static void checkMember(String name, boolean same, Object got, Object want) {\n";
    ss_ << "        if (!same) {\n";
    ss_ << "            fail(\"member \" + name + \" differs\\n    got  \" + got + \"\\n    want \" + want);\n";
    ss_ << "        }\n";
    ss_ << "    }\n\n";

    ss_ << "    private static String hex(byte[] bytes) {\n";
    ss_ << "        StringBuilder sb = new StringBuilder();\n";
    ss_ << "        for (byte b : bytes) {\n";
    ss_ << "            sb.append(String.format(\" %02x\", b));\n";
    ss_ << "        }\n";
    ss_ << "        return sb.toString();\n";
    ss_ << "    }\n\n";

    ss_ << "    public static void main(String[] args) throws IOException {\n";
    ss_ << "        if (args.length != 2) {\n";
    ss_ << "            System.err.println(\"usage: " << relayclass << " <input file> <output file>\");\n";
    ss_ << "            System.exit(2);\n";
    ss_ << "        }\n\n";

    ss_ << "        byte[] data = Files.readAllBytes(Paths.get(args[0]));\n";
    ss_ << "        " << classname << " got = new " << classname << "();\n";
    ss_ << "        if (data.length != got.size()) {\n";
    ss_ << "            System.out.println(\"FAIL java: input is \" + data.length + \" bytes, size() is \" + got.size());\n";
    ss_ << "            System.exit(1);\n";
    ss_ << "        }\n";
    ss_ << "        try {\n";
    ss_ << "            got.deserialize(data);\n";
    ss_ << "        } catch (IllegalArgumentException e) {\n";
    ss_ << "            System.out.println(\"FAIL java: deserialize: \" + e.getMessage());\n";
    ss_ << "            System.exit(1);\n";
    ss_ << "        }\n\n";

    ss_ << "        " << classname << " want = makeMessage();\n";
    for (auto& leaf : leaves)
    {
        const std::string name = leaf.join(".");
        const std::string g = "got" + leaf.join("", ".Get_", "()");
        const std::string w = "want" + leaf.join("", ".Get_", "()");

        if (is_string_type(std::get<member_type>(leaf.member)))
        {
            ss_ << "        checkMember(\"" << name << "\", Arrays.equals(" << g << ", " << w << "),\n";
            ss_ << "            Arrays.toString(" << g << "), Arrays.toString(" << w << "));\n";
        }
        else
        {
            ss_ << "        checkMember(\"" << name << "\", " << g << " == " << w << ", " << g << ", " << w << ");\n";
        }
    }
    ss_ << "        if (!got.equals(want)) {\n";
    ss_ << "            fail(\"equals() is false\");\n";
    ss_ << "        }\n\n";

    ss_ << "        byte[] out = got.serialize();\n";
    ss_ << "        if (!Arrays.equals(out, data)) {\n";
    ss_ << "            fail(\"re-serialized bytes differ from the input\\n    got \" + hex(out) + \"\\n    want\" + hex(data));\n";
    ss_ << "        }\n";
    ss_ << "        Files.write(Paths.get(args[1]), out);\n\n";

    ss_ << "        if (failures > 0) {\n";
    ss_ << "            System.exit(1);\n";
    ss_ << "        }\n";
    ss_ << "        System.out.println(\"PASS java: \" + data.length + \" bytes, " << leaves.size() << " members intact\");\n";
    ss_ << "    }\n";
    ss_ << "}\n";

    results_["relay"] = ss_.str();

    return true;
}

