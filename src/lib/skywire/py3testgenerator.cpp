bool Py3TestGenerator::generate(int& errorcode)
{
    errorcode = 0;

    results_.clear();

    if (false == do_test_implementation(errorcode))
    {
        errorcode |= SW_FILE_IMP;
        return false;
    }

    return true;
}

bool Py3TestGenerator::do_test_implementation(int& errorcode)
{
    std::string& test_string = results_["unittest"];

    const std::string classname = msg_spec_.get_value_string("classname");

    // The test imports the generated module by its file name.
    std::string module = msg_spec_.get_value_string("outputimplfilename", classname + ".py");
    module = module.substr(0, module.rfind(".py"));

    if (msg_spec_.get_proto().members_size() == 0)
    {
        errorcode |= SW_LANG_NOMEMBERS;
        return false;
    }

    std::vector<uint8_t> wire;
    bool have_wire = expected_wire(wire);

    ss_ << "# Code generated by wiregen. DO NOT EDIT.\n\n";
    ss_ << "import unittest\n\n";
    ss_ << "from " << module << " import " << classname << "\n\n\n";

    ss_ << "def make_message():\n";
    ss_ << "    msg = " << classname << "()\n";
    do_sets(errorcode);
    ss_ << "    return msg\n\n\n";

    ss_ << "class " << classname << "Test(unittest.TestCase):\n";
    ss_ << "    def test_round_trip(self):\n";
    ss_ << "        msg = make_message()\n";
    ss_ << "        wire = msg.serialize()\n";
    ss_ << "        self.assertEqual(len(wire), msg.size())\n";
    ss_ << "        out = " << classname << "()\n";
    ss_ << "        out.deserialize(wire)\n";
    ss_ << "        self.assertTrue(msg.equals(out), \"round-trip value mismatch\")\n";
    ss_ << "        self.assertEqual(msg, out)\n\n";

    ss_ << "    def test_short_buffer(self):\n";
    ss_ << "        wire = make_message().serialize()\n";
    ss_ << "        with self.assertRaises(ValueError):\n";
    ss_ << "            " << classname << "().deserialize(wire[:-1])\n";

    // A bitfield setter keeps only the field's bits: a value with a bit set
    // above the field reads back as the field's value.
    for (auto& member : ordered_members_)
    {
        const std::string wide = out_of_range_hex(member.second);
        if (wide.empty())
        {
            continue;
        }
        const std::string& name = std::get<member_name>(member.second);
        ss_ << "\n    def test_set_" << name << "_keeps_its_bits(self):\n";
        ss_ << "        msg = " << classname << "()\n";
        ss_ << "        msg.Set_" << name << "(" << wide << ")\n";
        ss_ << "        self.assertEqual(msg.Get_" << name << "(), " << test_literal(member.second) << ")\n";
    }

    if (have_wire)
    {
        ss_ << "\n";
        do_expected_wire(wire, errorcode);
    }

    do_text_tests(classname);
    do_bson_tests(classname);

    ss_ << "\n\nif __name__ == \"__main__\":\n";
    ss_ << "    unittest.main()\n";

    test_string.append(ss_.str());

    return true;
}

bool Py3TestGenerator::do_sets(int& errorcode)
{
    for (auto& member : ordered_members_)
    {
        ss_ << set_line("msg", member.second);
    }

    return true;
}

// The statement that sets one member of target to its shared test value, or
// nothing for a member with no test value (a nested message).
std::string Py3TestGenerator::set_line(const std::string& target, const member_desc_t& member)
{
    const std::string& type = std::get<member_type>(member);
    const std::string& name = std::get<member_name>(member);

    if (is_string_type(type))
    {
        return "    " + target + ".Set_" + name + "(b\"" + test_values::string_value() + "\")\n";
    }
    if (test_values::literal(type))
    {
        return "    " + target + ".Set_" + name + "(" + test_literal(member) + ")\n";
    }
    return "";
}

// The expected bytes come from the generator, not from the generated Python,
// so this catches wire-format bugs (byte order, padding, width) that a
// self round-trip cannot.
bool Py3TestGenerator::do_expected_wire(const std::vector<uint8_t>& wire, int& errorcode)
{
    ss_ << "    def test_wire(self):\n";
    ss_ << "        want = bytes.fromhex(\n";
    for (size_t i = 0; i < wire.size(); i += 8)
    {
        ss_ << "            \"";
        for (size_t j = i; j < std::min(i + 8, wire.size()); j++)
        {
            char hex[4];
            std::snprintf(hex, sizeof(hex), "%02x", wire[j]);
            ss_ << (j > i ? " " : "") << hex;
        }
        ss_ << (i + 8 < wire.size() ? " " : "") << "\"\n";
    }
    ss_ << "        )\n";
    ss_ << "        self.assertEqual(make_message().serialize().hex(), want.hex())\n";

    return true;
}

