// The relay is the crate root: it declares the message's module and those of
// the nested messages it uses, all in one directory.
bool RustRelayGenerator::generate(int& errorcode)
{
    errorcode = 0;
    results_.clear();

    const std::string classname = msg_spec_.get_value_string("classname");

    // The relay checks every member, inside nested messages too, against the
    // shared test values.
    std::vector<leaf_t> leaves;
    if (false == relay_leaves(leaves, errorcode))
    {
        return false;
    }

    std::vector<std::string> modules = { RustGenerator::module_name(classname) };
    for (auto& type : nested_types_in_order())
    {
        modules.push_back(RustGenerator::module_name(type));
    }
    // rustfmt sorts mod declarations.
    std::sort(modules.begin(), modules.end());

    ss_ << "// Code generated by wiregen. DO NOT EDIT.\n";
    ss_ << "// Cross-language relay: <program> <input file> <output file>\n\n";
    // The relay uses only part of each message's API.
    ss_ << "#![allow(dead_code)]\n";
    // The shared double test value, 3.14159, looks like an approximation of
    // PI to clippy.
    ss_ << "#![allow(clippy::approx_constant)]\n\n";
    for (auto& module : modules)
    {
        ss_ << "mod " << module << ";\n";
    }
    ss_ << "\n";
    // One name for the message keeps the relay's own lines the same length
    // for every message, as rustfmt lays them out.
    std::vector<std::string> uses = { "use " + RustGenerator::module_name(classname) + "::" + classname + " as Message;\n",
                                      "use std::process::exit;\n" };
    std::sort(uses.begin(), uses.end());
    ss_ << uses[0] << uses[1] << "\n";

    ss_ << "fn expected() -> Message {\n";
    ss_ << "    let mut s = Message::default();\n";
    // A nested message is set through its _mut() accessor.
    for (auto& leaf : leaves)
    {
        std::string target = "s";
        for (size_t i = 0; i + 1 < leaf.path.size(); i++)
        {
            target += "." + leaf.path[i] + "_mut()";
        }
        ss_ << set_line(target, leaf.member);
    }
    ss_ << "    s\n";
    ss_ << "}\n\n";

    ss_ << "fn hex(bytes: &[u8]) -> String {\n";
    ss_ << "    let digits: Vec<String> = bytes.iter().map(|b| format!(\"{b:02x}\")).collect();\n";
    ss_ << "    digits.join(\" \")\n";
    ss_ << "}\n\n";

    ss_ << "struct Checker {\n";
    ss_ << "    got: Message,\n";
    ss_ << "    want: Message,\n";
    ss_ << "    failures: u32,\n";
    ss_ << "}\n\n";

    ss_ << "impl Checker {\n";
    ss_ << "    fn fail(&mut self, what: &str) {\n";
    ss_ << "        println!(\"FAIL rust: {what}\");\n";
    ss_ << "        self.failures += 1;\n";
    ss_ << "    }\n\n";
    ss_ << "    fn check<T: PartialEq + std::fmt::Debug>(&mut self, name: &str, get: fn(&Message) -> T) {\n";
    ss_ << "        let (got, want) = (get(&self.got), get(&self.want));\n";
    ss_ << "        if got != want {\n";
    ss_ << "            self.fail(&format!(\n";
    ss_ << "                \"member {name} differs\\n    got  {got:?}\\n    want {want:?}\"\n";
    ss_ << "            ));\n";
    ss_ << "        }\n";
    ss_ << "    }\n";
    ss_ << "}\n\n";

    ss_ << "fn main() {\n";
    ss_ << "    let args: Vec<String> = std::env::args().collect();\n";
    ss_ << "    if args.len() != 3 {\n";
    ss_ << "        eprintln!(\"usage: {} <input file> <output file>\", args[0]);\n";
    ss_ << "        exit(2);\n";
    ss_ << "    }\n\n";

    ss_ << "    let data = match std::fs::read(&args[1]) {\n";
    ss_ << "        Ok(data) => data,\n";
    ss_ << "        Err(err) => {\n";
    ss_ << "            println!(\"FAIL rust: cannot read {}: {err}\", args[1]);\n";
    ss_ << "            exit(1);\n";
    ss_ << "        }\n";
    ss_ << "    };\n";
    ss_ << "    if data.len() != Message::SIZE {\n";
    ss_ << "        let size = Message::SIZE;\n";
    ss_ << "        println!(\"FAIL rust: input is {} bytes, SIZE is {size}\", data.len());\n";
    ss_ << "        exit(1);\n";
    ss_ << "    }\n";
    ss_ << "    let got = match Message::from_bytes(&data) {\n";
    ss_ << "        Ok(got) => got,\n";
    ss_ << "        Err(err) => {\n";
    ss_ << "            println!(\"FAIL rust: deserialize: {err}\");\n";
    ss_ << "            exit(1);\n";
    ss_ << "        }\n";
    ss_ << "    };\n\n";

    ss_ << "    let mut c = Checker {\n";
    ss_ << "        got,\n";
    ss_ << "        want: expected(),\n";
    ss_ << "        failures: 0,\n";
    ss_ << "    };\n";
    for (auto& leaf : leaves)
    {
        std::string getter = "m";
        for (auto& name : leaf.path)
        {
            getter += "." + RustGenerator::identifier(name) + "()";
        }
        // A string getter returns a reference into the message; compare the bytes.
        if (is_string_type(std::get<member_type>(leaf.member)))
        {
            getter = "*" + getter;
        }
        ss_ << call("    ", "c.check", { "\"" + leaf.join(".") + "\"", "|m| " + getter });
    }
    ss_ << "    if !c.got.equals(&c.want) {\n";
    ss_ << "        c.fail(\"equals() is false\");\n";
    ss_ << "    }\n\n";

    ss_ << "    let out = c.got.serialize();\n";
    ss_ << "    if out != data {\n";
    ss_ << "        let (got, want) = (hex(&out), hex(&data));\n";
    ss_ << "        c.fail(&format!(\n";
    ss_ << "            \"re-serialized bytes differ from the input\\n    got  {got}\\n    want {want}\"\n";
    ss_ << "        ));\n";
    ss_ << "    }\n";
    ss_ << "    if let Err(err) = std::fs::write(&args[2], &out) {\n";
    ss_ << "        c.fail(&format!(\"cannot write {}: {err}\", args[2]));\n";
    ss_ << "    }\n\n";

    ss_ << "    if c.failures > 0 {\n";
    ss_ << "        exit(1);\n";
    ss_ << "    }\n";
    ss_ << "    println!(\"PASS rust: {} bytes, " << leaves.size() << " members intact\", data.len());\n";
    ss_ << "}\n";

    results_["relay"] = ss_.str();

    return true;
}

