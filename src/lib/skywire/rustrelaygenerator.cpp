// rustfmt keeps a call on one line when its arguments fit in 60 columns and
// the line in 100; otherwise it puts each argument on its own line.
std::string call(const std::string& indent, const std::string& callee, const std::vector<std::string>& args)
{
    std::string joined;
    for (auto& arg : args)
    {
        joined += (joined.empty() ? "" : ", ") + arg;
    }

    std::string line = indent + callee + "(" + joined + ");\n";
    if (joined.size() <= 60 && line.size() - 1 <= 100)
    {
        return line;
    }

    std::string vertical = indent + callee + "(\n";
    for (auto& arg : args)
    {
        vertical += indent + "    " + arg + ",\n";
    }
    return vertical + indent + ");\n";
}

