bool JavaTestGenerator::generate(int& errorcode)
{
    errorcode = 0;

    results_.clear();

    if (false == do_test_implementation(errorcode))
    {
        errorcode |= SW_FILE_IMP;
        return false;
    }

    return true;
}

// The generated test is a plain main() (no JUnit) so it runs with only a JDK.
// It exits non-zero if any check fails.
bool JavaTestGenerator::do_test_implementation(int& errorcode)
{
    std::string& test_string = results_["unittest"];

    const std::string classname = msg_spec_.get_value_string("classname");
    const std::string package = msg_spec_.get_value_string("namespace");

    // A public Java class must be named after its file.
    std::string testclass = msg_spec_.get_value_string("outputtestfilename", classname + "Test.java");
    testclass = testclass.substr(0, testclass.rfind(".java"));

    if (msg_spec_.get_proto().members_size() == 0)
    {
        errorcode |= SW_LANG_NOMEMBERS;
        return false;
    }

    std::vector<uint8_t> wire;
    bool have_wire = true;
    bool have_string = false;
    have_wire = expected_wire(wire);
    for (auto& member : ordered_members_)
    {
        have_string = have_string || is_string_type(std::get<member_type>(member.second));
    }

    ss_ << "// Code generated by wiregen. DO NOT EDIT.\n\n";
    ss_ << "package " << package << ";\n\n";
    ss_ << "import java.nio.ByteBuffer;\n";
    ss_ << "import java.nio.ByteOrder;\n";
    if (have_string || wants_json() || wants_xml() || wants_bson())
    {
        ss_ << "import java.nio.charset.StandardCharsets;\n";
    }
    ss_ << "import java.util.Arrays;\n\n";

    ss_ << "public final class " << testclass << " {\n";
    ss_ << "    private static " << classname << " makeMessage() {\n";
    ss_ << "        " << classname << " msg = new " << classname << "();\n";
    do_sets(errorcode);
    ss_ << "        return msg;\n";
    ss_ << "    }\n\n";

    ss_ << "    private static void check(boolean cond, String message) {\n";
    ss_ << "        if (!cond) {\n";
    ss_ << "            throw new AssertionError(message);\n";
    ss_ << "        }\n";
    ss_ << "    }\n\n";

    ss_ << "    static void testRoundTrip() {\n";
    ss_ << "        " << classname << " in = makeMessage();\n";
    ss_ << "        byte[] wire = in.serialize();\n";
    ss_ << "        check(wire.length == in.size(), \"serialized \" + wire.length + \" bytes, size() is \" + in.size());\n";
    ss_ << "        " << classname << " out = new " << classname << "();\n";
    ss_ << "        out.deserialize(wire);\n";
    ss_ << "        check(in.equals(out), \"round-trip value mismatch\\n in \" + in + \"\\nout \" + out);\n";
    ss_ << "        check(in.hashCode() == out.hashCode(), \"hashCode differs after round-trip\");\n";
    ss_ << "    }\n\n";

    ss_ << "    static void testShortBuffer() {\n";
    ss_ << "        byte[] wire = makeMessage().serialize();\n";
    ss_ << "        try {\n";
    ss_ << "            new " << classname << "().deserialize(Arrays.copyOf(wire, wire.length - 1));\n";
    ss_ << "        } catch (IllegalArgumentException expected) {\n";
    ss_ << "            return;\n";
    ss_ << "        }\n";
    ss_ << "        throw new AssertionError(\"expected an IllegalArgumentException for a short buffer\");\n";
    ss_ << "    }\n\n";

    // The ByteBuffer overloads are what nested messages use: they must start
    // at the buffer's position, consume exactly size() bytes, and leave the
    // caller's byte order alone.
    ss_ << "    static void testByteBuffer() {\n";
    ss_ << "        " << classname << " in = makeMessage();\n";
    ss_ << "        ByteOrder order = ByteOrder.nativeOrder() == ByteOrder.BIG_ENDIAN ? ByteOrder.LITTLE_ENDIAN : ByteOrder.BIG_ENDIAN;\n";
    ss_ << "        ByteBuffer buf = ByteBuffer.allocate(3 + in.size()).order(order);\n";
    ss_ << "        buf.put(new byte[3]);\n";
    ss_ << "        in.serialize(buf);\n";
    ss_ << "        check(!buf.hasRemaining(), \"serialize(ByteBuffer) wrote \" + (buf.position() - 3) + \" bytes, size() is \" + in.size());\n";
    ss_ << "        check(buf.order() == order, \"serialize(ByteBuffer) changed the byte order\");\n";
    ss_ << "        check(Arrays.equals(Arrays.copyOfRange(buf.array(), 3, buf.capacity()), in.serialize()),\n";
    ss_ << "            \"serialize(ByteBuffer) differs from serialize()\");\n";
    ss_ << "        buf.position(3);\n";
    ss_ << "        " << classname << " out = new " << classname << "();\n";
    ss_ << "        out.deserialize(buf);\n";
    ss_ << "        check(!buf.hasRemaining(), \"deserialize(ByteBuffer) read \" + (buf.position() - 3) + \" bytes, size() is \" + in.size());\n";
    ss_ << "        check(buf.order() == order, \"deserialize(ByteBuffer) changed the byte order\");\n";
    ss_ << "        check(in.equals(out), \"ByteBuffer round-trip value mismatch\\n in \" + in + \"\\nout \" + out);\n";
    ss_ << "    }\n";

    // A bitfield setter keeps only the field's bits: a value with a bit set
    // above the field reads back as the field's value.
    std::string setters;
    for (auto& member : ordered_members_)
    {
        const std::string wide = out_of_range_hex(member.second);
        if (wide.empty())
        {
            continue;
        }
        const std::string& name = std::get<member_name>(member.second);
        const std::string& type = std::get<member_type>(member.second);
        setters += "        msg.Set_" + name + "(" + java_literal(type, wide) + ");\n";
        setters += "        check(msg.Get_" + name + "() == " + java_literal(type, test_literal(member.second)) +
                   ", \"" + name + ": got \" + msg.Get_" + name + "());\n";
    }
    if (false == setters.empty())
    {
        ss_ << "\n    static void testBitfieldSetters() {\n";
        ss_ << "        " << classname << " msg = new " << classname << "();\n";
        ss_ << setters;
        ss_ << "    }\n";
    }

    if (have_wire)
    {
        ss_ << "\n";
        do_expected_wire(wire, errorcode);
    }

    std::vector<std::string> text_tests;
    do_text_tests(classname, text_tests);
    do_bson_tests(classname, text_tests);

    ss_ << "\n";
    ss_ << "    private static int run(String name, Runnable test) {\n";
    ss_ << "        try {\n";
    ss_ << "            test.run();\n";
    ss_ << "        } catch (AssertionError | RuntimeException e) {\n";
    ss_ << "            System.out.println(\"FAIL " << classname << " \" + name + \": \" + e.getMessage());\n";
    ss_ << "            return 1;\n";
    ss_ << "        }\n";
    ss_ << "        System.out.println(\"PASS " << classname << " \" + name);\n";
    ss_ << "        return 0;\n";
    ss_ << "    }\n\n";

    ss_ << "    public static void main(String[] args) {\n";
    ss_ << "        int failures = 0;\n";
    ss_ << "        failures += run(\"RoundTrip\", " << testclass << "::testRoundTrip);\n";
    ss_ << "        failures += run(\"ShortBuffer\", " << testclass << "::testShortBuffer);\n";
    ss_ << "        failures += run(\"ByteBuffer\", " << testclass << "::testByteBuffer);\n";
    if (have_wire)
    {
        ss_ << "        failures += run(\"Wire\", " << testclass << "::testWire);\n";
    }
    if (false == setters.empty())
    {
        ss_ << "        failures += run(\"BitfieldSetters\", " << testclass << "::testBitfieldSetters);\n";
    }
    for (auto& test : text_tests)
    {
        ss_ << "        failures += run(\"" << test << "\", " << testclass << "::test" << test << ");\n";
    }
    ss_ << "        if (failures > 0) {\n";
    ss_ << "            System.exit(1);\n";
    ss_ << "        }\n";
    ss_ << "    }\n";
    ss_ << "}\n";

    test_string.append(ss_.str());

    return true;
}

std::string JavaTestGenerator::java_literal(const std::string& type, const std::string& literal)
{
    const std::string jtype = lang_spec_.get_value_string(type);

    if (jtype == "byte" || jtype == "short")
        return "(" + jtype + ") " + literal;
    if (jtype == "long")
        return literal + "L";
    if (jtype == "float")
        return literal + "f";
    return literal;
}

bool JavaTestGenerator::do_sets(int& errorcode)
{
    for (auto& member : ordered_members_)
    {
        ss_ << set_line("msg", member.second);
    }

    return true;
}

// The statement that sets one member of target to its shared test value, or
// nothing for a member with no test value (a nested message).
std::string JavaTestGenerator::set_line(const std::string& target, const member_desc_t& member)
{
    const std::string& type = std::get<member_type>(member);
    const std::string& name = std::get<member_name>(member);

    if (is_string_type(type))
    {
        return "        " + target + ".Set_" + name + "(\"" + test_values::string_value() + "\".getBytes(StandardCharsets.US_ASCII));\n";
    }
    if (test_values::literal(type))
    {
        return "        " + target + ".Set_" + name + "(" + java_literal(type, test_literal(member)) + ");\n";
    }
    return "";
}

// The expected bytes come from the generator, not from the generated Java,
// so this catches wire-format bugs (byte order, padding, width) that a
// self round-trip cannot.
bool JavaTestGenerator::do_expected_wire(const std::vector<uint8_t>& wire, int& errorcode)
{
    ss_ << "    static void testWire() {\n";
    ss_ << "        String want = \"\"";
    for (size_t i = 0; i < wire.size(); i += 8)
    {
        ss_ << "\n            + \"";
        for (size_t j = i; j < std::min(i + 8, wire.size()); j++)
        {
            char hex[4];
            std::snprintf(hex, sizeof(hex), "%02x", wire[j]);
            ss_ << (j > i ? " " : "") << hex;
        }
        ss_ << (i + 8 < wire.size() ? " " : "") << "\"";
    }
    ss_ << ";\n";
    ss_ << "        String got = hex(makeMessage().serialize());\n";
    ss_ << "        check(got.equals(want), \"wire mismatch\\n got \" + got + \"\\nwant \" + want);\n";
    ss_ << "    }\n\n";

    ss_ << "    private static String hex(byte[] bytes) {\n";
    ss_ << "        StringBuilder sb = new StringBuilder();\n";
    ss_ << "        for (byte b : bytes) {\n";
    ss_ << "            if (sb.length() > 0) {\n";
    ss_ << "                sb.append(' ');\n";
    ss_ << "            }\n";
    ss_ << "            sb.append(String.format(\"%02x\", b));\n";
    ss_ << "        }\n";
    ss_ << "        return sb.toString();\n";
    ss_ << "    }\n";

    return true;
}

