#include "relaygenerators.h"
#include "test_values.h"

namespace skyloupe
{

bool CRelayGenerator::generate(int& errorcode)
{
    errorcode = 0;
    results_.clear();

    const std::string classname = msg_spec_.get_value_string("classname");
    const std::string hdr_name = msg_spec_.get_value_string("outputheaderfilename");

    for (auto& member : ordered_members_)
    {
        const std::string& type = std::get<member_type>(member.second);
        if (false == is_string_type(type) && nullptr == test_values::literal(type))
        {
            // The relay can only check members that have a shared test value.
            errorcode |= SW_FILE_IMP;
            return false;
        }
    }

    ss_ << "/* Code generated by wiregen. DO NOT EDIT. */\n";
    ss_ << "/* Cross-language relay: <program> <input file> <output file> */\n\n";
    ss_ << "#include <stdio.h>\n";
    ss_ << "#include <stdlib.h>\n";
    ss_ << "#include <string.h>\n";
    ss_ << "#include \"" << hdr_name << "\"\n\n";

    ss_ << "static int failures = 0;\n\n";

    ss_ << "static void dump(const char* label, const void* p, size_t n)\n";
    ss_ << "{\n";
    ss_ << "    const unsigned char* b = (const unsigned char*)p;\n";
    ss_ << "    size_t i;\n";
    ss_ << "    printf(\"    %s\", label);\n";
    ss_ << "    for (i = 0; i < n; i++)\n";
    ss_ << "        printf(\" %02x\", b[i]);\n";
    ss_ << "    printf(\"\\n\");\n";
    ss_ << "}\n\n";

    ss_ << "static void check_member(const char* name, const void* got, const void* want, size_t n)\n";
    ss_ << "{\n";
    ss_ << "    if (memcmp(got, want, n) != 0)\n";
    ss_ << "    {\n";
    ss_ << "        printf(\"FAIL c: member %s differs\\n\", name);\n";
    ss_ << "        dump(\"got \", got, n);\n";
    ss_ << "        dump(\"want\", want, n);\n";
    ss_ << "        failures++;\n";
    ss_ << "    }\n";
    ss_ << "}\n\n";

    ss_ << "static unsigned char* read_file(const char* path, size_t* len)\n";
    ss_ << "{\n";
    ss_ << "    FILE* f = fopen(path, \"rb\");\n";
    ss_ << "    unsigned char* data = NULL;\n";
    ss_ << "    size_t cap = 0;\n";
    ss_ << "    *len = 0;\n";
    ss_ << "    if (f == NULL)\n";
    ss_ << "        return NULL;\n";
    ss_ << "    for (;;)\n";
    ss_ << "    {\n";
    ss_ << "        if (*len == cap)\n";
    ss_ << "        {\n";
    ss_ << "            unsigned char* grown = (unsigned char*)realloc(data, cap + 4096);\n";
    ss_ << "            if (grown == NULL)\n";
    ss_ << "                break;\n";
    ss_ << "            data = grown;\n";
    ss_ << "            cap += 4096;\n";
    ss_ << "        }\n";
    ss_ << "        size_t n = fread(data + *len, 1, cap - *len, f);\n";
    ss_ << "        *len += n;\n";
    ss_ << "        if (n == 0)\n";
    ss_ << "        {\n";
    ss_ << "            if (ferror(f))\n";
    ss_ << "                break;\n";
    ss_ << "            fclose(f);\n";
    ss_ << "            return data;\n";
    ss_ << "        }\n";
    ss_ << "    }\n";
    ss_ << "    fclose(f);\n";
    ss_ << "    free(data);\n";
    ss_ << "    return NULL;\n";
    ss_ << "}\n\n";

    ss_ << "static int write_file(const char* path, const void* data, size_t len)\n";
    ss_ << "{\n";
    ss_ << "    FILE* f = fopen(path, \"wb\");\n";
    ss_ << "    if (f == NULL)\n";
    ss_ << "        return -1;\n";
    ss_ << "    size_t n = fwrite(data, 1, len, f);\n";
    ss_ << "    return (fclose(f) == 0 && n == len) ? 0 : -1;\n";
    ss_ << "}\n\n";

    ss_ << "int main(int argc, char** argv)\n";
    ss_ << "{\n";
    ss_ << "    if (argc != 3)\n";
    ss_ << "    {\n";
    ss_ << "        fprintf(stderr, \"usage: %s <input file> <output file>\\n\", argv[0]);\n";
    ss_ << "        return 2;\n";
    ss_ << "    }\n\n";

    ss_ << "    size_t len;\n";
    ss_ << "    unsigned char* data = read_file(argv[1], &len);\n";
    ss_ << "    if (data == NULL)\n";
    ss_ << "    {\n";
    ss_ << "        printf(\"FAIL c: cannot read %s\\n\", argv[1]);\n";
    ss_ << "        return 1;\n";
    ss_ << "    }\n";
    ss_ << "    if (len != " << classname << "_Size())\n";
    ss_ << "    {\n";
    ss_ << "        printf(\"FAIL c: input is %zu bytes, Size() is %zu\\n\", len, " << classname << "_Size());\n";
    ss_ << "        free(data);\n";
    ss_ << "        return 1;\n";
    ss_ << "    }\n\n";

    ss_ << "    " << classname << " want;\n";
    ss_ << "    memset(&want, 0, sizeof(want));\n";
    for (auto& member : ordered_members_)
    {
        const std::string& type = std::get<member_type>(member.second);
        const std::string& name = std::get<member_name>(member.second);

        if (is_string_type(type))
        {
            ss_ << "    strncpy(want." << name << ", \"" << test_values::string_value() << "\", "
                << std::get<member_length>(member.second) << ");\n";
        }
        else
        {
            ss_ << "    want." << name << " = " << test_values::literal(type) << ";\n";
        }
    }
    ss_ << "\n";

    // A pattern, not zeros, so a member that Deserialize skips is caught.
    ss_ << "    " << classname << " got;\n";
    ss_ << "    memset(&got, 0xa5, sizeof(got));\n\n";

    ss_ << "    Cstream in;\n";
    ss_ << "    cstream_init(&in, len);\n";
    ss_ << "    cstream_write(&in, data, len, SW_NATIVE_ENDIAN_FLAG);\n";
    ss_ << "    if (" << classname << "_Deserialize(&got, &in) != 0)\n";
    ss_ << "    {\n";
    ss_ << "        printf(\"FAIL c: Deserialize failed\\n\");\n";
    ss_ << "        cstream_fini(&in);\n";
    ss_ << "        free(data);\n";
    ss_ << "        return 1;\n";
    ss_ << "    }\n";
    ss_ << "    if (cstream_available(&in) != 0)\n";
    ss_ << "    {\n";
    ss_ << "        printf(\"FAIL c: Deserialize left %zu bytes unread\\n\", cstream_available(&in));\n";
    ss_ << "        failures++;\n";
    ss_ << "    }\n";
    ss_ << "    cstream_fini(&in);\n\n";

    for (auto& member : ordered_members_)
    {
        const std::string& name = std::get<member_name>(member.second);
        ss_ << "    check_member(\"" << name << "\", &got." << name << ", &want." << name << ", sizeof(want." << name << "));\n";
    }
    ss_ << "    if (" << classname << "_Equals(&got, &want) != 1)\n";
    ss_ << "    {\n";
    ss_ << "        printf(\"FAIL c: Equals() is false\\n\");\n";
    ss_ << "        failures++;\n";
    ss_ << "    }\n\n";

    ss_ << "    Cstream out;\n";
    ss_ << "    cstream_init(&out, len);\n";
    ss_ << "    if (" << classname << "_Serialize(&got, &out) != 0)\n";
    ss_ << "    {\n";
    ss_ << "        printf(\"FAIL c: Serialize failed\\n\");\n";
    ss_ << "        failures++;\n";
    ss_ << "    }\n";
    ss_ << "    else\n";
    ss_ << "    {\n";
    ss_ << "        if (cstream_available(&out) != len || memcmp(out.head_, data, len) != 0)\n";
    ss_ << "        {\n";
    ss_ << "            printf(\"FAIL c: re-serialized bytes differ from the input\\n\");\n";
    ss_ << "            dump(\"got \", out.head_, cstream_available(&out));\n";
    ss_ << "            dump(\"want\", data, len);\n";
    ss_ << "            failures++;\n";
    ss_ << "        }\n";
    ss_ << "        if (write_file(argv[2], out.head_, cstream_available(&out)) != 0)\n";
    ss_ << "        {\n";
    ss_ << "            printf(\"FAIL c: cannot write %s\\n\", argv[2]);\n";
    ss_ << "            failures++;\n";
    ss_ << "        }\n";
    ss_ << "    }\n";
    ss_ << "    cstream_fini(&out);\n";
    ss_ << "    free(data);\n\n";

    ss_ << "    if (failures == 0)\n";
    ss_ << "        printf(\"PASS c: %zu bytes, " << ordered_members_.size() << " members intact\\n\", len);\n";
    ss_ << "    return failures == 0 ? 0 : 1;\n";
    ss_ << "}\n";

    results_["relay"] = ss_.str();

    return true;
}

}
