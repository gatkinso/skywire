bool Py3RelayGenerator::generate(int& errorcode)
{
    errorcode = 0;
    results_.clear();

    const std::string classname = msg_spec_.get_value_string("classname");

    // The relay imports the generated module by its file name.
    std::string module = msg_spec_.get_value_string("outputimplfilename", classname + ".py");
    module = module.substr(0, module.rfind(".py"));

    for (auto& member : ordered_members_)
    {
        const std::string& type = std::get<member_type>(member.second);
        if (false == is_string_type(type) && nullptr == test_values::literal(type))
        {
            // The relay can only check members that have a shared test value.
            errorcode |= SW_FILE_IMP;
            return false;
        }
    }

    ss_ << "# Code generated by wiregen. DO NOT EDIT.\n";
    ss_ << "# Cross-language relay: <program> <input file> <output file>\n\n";
    ss_ << "import sys\n\n";
    ss_ << "from " << module << " import " << classname << "\n\n";
    ss_ << "MEMBERS = (\n";
    for (auto& member : ordered_members_)
    {
        ss_ << "    \"" << std::get<member_name>(member.second) << "\",\n";
    }
    ss_ << ")\n\n\n";

    ss_ << "def make_message():\n";
    ss_ << "    msg = " << classname << "()\n";
    do_sets(errorcode);
    ss_ << "    return msg\n\n\n";

    ss_ << "def main():\n";
    ss_ << "    if len(sys.argv) != 3:\n";
    ss_ << "        print(\"usage: %s <input file> <output file>\" % sys.argv[0], file=sys.stderr)\n";
    ss_ << "        return 2\n\n";

    ss_ << "    failures = 0\n\n";
    ss_ << "    def fail(what):\n";
    ss_ << "        nonlocal failures\n";
    ss_ << "        print(\"FAIL python: \" + what)\n";
    ss_ << "        failures += 1\n\n";

    ss_ << "    with open(sys.argv[1], \"rb\") as f:\n";
    ss_ << "        data = f.read()\n";
    ss_ << "    got = " << classname << "()\n";
    ss_ << "    if len(data) != got.size():\n";
    ss_ << "        print(\"FAIL python: input is %d bytes, size() is %d\" % (len(data), got.size()))\n";
    ss_ << "        return 1\n";
    ss_ << "    try:\n";
    ss_ << "        got.deserialize(data)\n";
    ss_ << "    except ValueError as e:\n";
    ss_ << "        print(\"FAIL python: deserialize: %s\" % e)\n";
    ss_ << "        return 1\n\n";

    ss_ << "    want = make_message()\n";
    ss_ << "    for name in MEMBERS:\n";
    ss_ << "        g = getattr(got, \"Get_\" + name)()\n";
    ss_ << "        w = getattr(want, \"Get_\" + name)()\n";
    ss_ << "        if type(g) is not type(w) or g != w:\n";
    ss_ << "            fail(\"member %s differs\\n    got  %r\\n    want %r\" % (name, g, w))\n";
    ss_ << "    if not got.equals(want):\n";
    ss_ << "        fail(\"equals() is false\")\n\n";

    ss_ << "    out = bytes(got.serialize())\n";
    ss_ << "    if out != data:\n";
    ss_ << "        fail(\"re-serialized bytes differ from the input\\n    got  %s\\n    want %s\" % (out.hex(\" \"), data.hex(\" \")))\n";
    ss_ << "    with open(sys.argv[2], \"wb\") as f:\n";
    ss_ << "        f.write(out)\n\n";

    ss_ << "    if failures:\n";
    ss_ << "        return 1\n";
    ss_ << "    print(\"PASS python: %d bytes, %d members intact\" % (len(data), len(MEMBERS)))\n";
    ss_ << "    return 0\n\n\n";

    ss_ << "if __name__ == \"__main__\":\n";
    ss_ << "    sys.exit(main())\n";

    results_["relay"] = ss_.str();

    return true;
}

