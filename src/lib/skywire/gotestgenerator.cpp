bool GoTestGenerator::generate(int& errorcode)
{
    errorcode = 0;

    results_.clear();

    if (false == do_test_implementation(errorcode))
    {
        errorcode |= SW_FILE_IMP;
        return false;
    }

    return true;
}

bool GoTestGenerator::do_test_implementation(int& errorcode)
{
    std::string& test_string_out = results_["unittest"];

    const std::string classname = msg_spec_.get_value_string("classname");
    const std::string package = msg_spec_.get_value_string("namespace");

    if (msg_spec_.get_proto().members_size() == 0)
    {
        errorcode |= SW_LANG_NOMEMBERS;
        return false;
    }

    std::vector<uint8_t> wire;
    bool have_wire = expected_wire(wire);

    ss_ << "// Code generated by wiregen. DO NOT EDIT.\n\n";
    ss_ << "package " << package << "\n\n";
    ss_ << "import (\n";
    ss_ << "\t\"bytes\"\n";
    ss_ << "\t\"testing\"\n";
    ss_ << ")\n\n";

    ss_ << "func new" << classname << "() *" << classname << " {\n";
    ss_ << "\ts := &" << classname << "{}\n";
    do_sets(errorcode);
    ss_ << "\treturn s\n";
    ss_ << "}\n\n";

    ss_ << "func Test" << classname << "RoundTrip(t *testing.T) {\n";
    ss_ << "\tin := new" << classname << "()\n";
    ss_ << "\twire := in.Serialize()\n";
    ss_ << "\tif len(wire) != in.Size() {\n";
    ss_ << "\t\tt.Fatalf(\"serialized %d bytes, Size() is %d\", len(wire), in.Size())\n";
    ss_ << "\t}\n";
    ss_ << "\tout := &" << classname << "{}\n";
    ss_ << "\tif err := out.Deserialize(wire); err != nil {\n";
    ss_ << "\t\tt.Fatal(err)\n";
    ss_ << "\t}\n";
    ss_ << "\tif !in.Equals(out) {\n";
    ss_ << "\t\tt.Fatalf(\"round-trip value mismatch\\n in %+v\\nout %+v\", *in, *out)\n";
    ss_ << "\t}\n";
    ss_ << "}\n\n";

    ss_ << "func Test" << classname << "ShortBuffer(t *testing.T) {\n";
    ss_ << "\twire := new" << classname << "().Serialize()\n";
    ss_ << "\tout := &" << classname << "{}\n";
    ss_ << "\tif err := out.Deserialize(wire[:len(wire)-1]); err == nil {\n";
    ss_ << "\t\tt.Fatal(\"expected an error for a short buffer\")\n";
    ss_ << "\t}\n";
    ss_ << "}\n\n";

    // AppendTo keeps what o already holds; Put writes only the first Size
    // bytes of a longer slice and panics on a shorter one.
    ss_ << "func Test" << classname << "AppendToAndPut(t *testing.T) {\n";
    ss_ << "\tin := new" << classname << "()\n";
    ss_ << "\twire := in.Serialize()\n";
    ss_ << "\tprefix := []byte{0xde, 0xad}\n";
    ss_ << "\tgot := in.AppendTo(append([]byte{}, prefix...))\n";
    ss_ << "\tif !bytes.Equal(got[:2], prefix) || !bytes.Equal(got[2:], wire) {\n";
    ss_ << "\t\tt.Fatalf(\"AppendTo\\n got % x\\nwant % x % x\", got, prefix, wire)\n";
    ss_ << "\t}\n";
    ss_ << "\tbuf := bytes.Repeat([]byte{0xee}, " << classname << "Size+1)\n";
    ss_ << "\tin.Put(buf)\n";
    ss_ << "\tif !bytes.Equal(buf[:" << classname << "Size], wire) || buf[" << classname << "Size] != 0xee {\n";
    ss_ << "\t\tt.Fatalf(\"Put\\n got % x\\nwant % x ee\", buf, wire)\n";
    ss_ << "\t}\n";
    ss_ << "\tdefer func() {\n";
    ss_ << "\t\tif recover() == nil {\n";
    ss_ << "\t\t\tt.Fatal(\"Put did not panic on a short buffer\")\n";
    ss_ << "\t\t}\n";
    ss_ << "\t}()\n";
    ss_ << "\tin.Put(buf[:" << classname << "Size-1])\n";
    ss_ << "}\n";

    if (have_wire)
    {
        ss_ << "\n";
        do_expected_wire(errorcode);
    }

    do_bitfield_setters(errorcode);

    test_string_out.append(ss_.str());

    return true;
}

bool GoTestGenerator::do_sets(int& errorcode)
{
    for (auto& member : ordered_members_)
    {
        ss_ << set_line("s", member.second);
    }

    return true;
}

// The statement that sets one member of target to its shared test value, or
// nothing for a member with no test value (a nested message).
std::string GoTestGenerator::set_line(const std::string& target, const member_desc_t& member)
{
    const std::string& type = std::get<member_type>(member);
    const std::string& name = std::get<member_name>(member);

    if (is_string_type(type))
    {
        return "\t" + target + ".Set_" + name + "([]byte(\"" + test_values::string_value() + "\"))\n";
    }
    if (test_values::literal(type))
    {
        return "\t" + target + ".Set_" + name + "(" + test_literal(member) + ")\n";
    }
    return "";
}

// A bitfield setter keeps only the field's bits: a value with a bit set
// above the field reads back as the field's value. The wide value goes
// through a variable, as a constant conversion that overflows doesn't compile.
bool GoTestGenerator::do_bitfield_setters(int& errorcode)
{
    const std::string classname = msg_spec_.get_value_string("classname");

    std::string body;
    for (auto& member : ordered_members_)
    {
        const std::string wide = out_of_range_hex(member.second);
        if (wide.empty())
        {
            continue;
        }
        const std::string& name = std::get<member_name>(member.second);
        const std::string type = lang_spec_.get_value_string(std::get<member_type>(member.second));
        body += "\twide = " + wide + "\n";
        body += "\ts.Set_" + name + "(" + type + "(wide))\n";
        body += "\tif got := s.Get_" + name + "(); got != " + test_literal(member.second) + " {\n";
        body += "\t\tt.Fatalf(\"" + name + ": got %d\", got)\n";
        body += "\t}\n";
    }

    if (body.empty())
    {
        return true;
    }

    ss_ << "\nfunc Test" << classname << "BitfieldSetters(t *testing.T) {\n";
    ss_ << "\ts := &" << classname << "{}\n";
    ss_ << "\tvar wide uint64\n";
    ss_ << body;
    ss_ << "}\n";

    return true;
}

// The expected bytes are computed by the generator, not by the generated Go
// code, so this test catches wire-format bugs (byte order, padding, width)
// that a self round-trip cannot. Native-endian members use the byte order of
// the host running wiregen.
bool GoTestGenerator::do_expected_wire(int& errorcode)
{
    const std::string classname = msg_spec_.get_value_string("classname");

    std::vector<uint8_t> wire;
    expected_wire(wire);

    ss_ << "func Test" << classname << "Wire(t *testing.T) {\n";
    ss_ << "\twant := []byte{";
    for (size_t i = 0; i < wire.size(); i++)
    {
        if (i % 8 == 0)
        {
            ss_ << "\n\t\t";
        }
        else
        {
            ss_ << " ";
        }

        char hex[8];
        std::snprintf(hex, sizeof(hex), "0x%02x,", wire[i]);
        ss_ << hex;
    }
    ss_ << "\n\t}\n";
    ss_ << "\tgot := new" << classname << "().Serialize()\n";
    ss_ << "\tif !bytes.Equal(got, want) {\n";
    ss_ << "\t\tt.Fatalf(\"wire mismatch\\n got % x\\nwant % x\", got, want)\n";
    ss_ << "\t}\n";
    ss_ << "}\n";

    return true;
}

bool GoTestGenerator::encode_member(const member_desc_t& member, std::vector<uint8_t>& out)
{
    return test_values::encode(std::get<member_type>(member), std::get<member_endianness>(member),
                               std::get<member_length>(member), out);
}

