// The relay is a command, so the spec's namespace (the Go package) must be "main".
bool GoRelayGenerator::generate(int& errorcode)
{
    errorcode = 0;
    results_.clear();

    const std::string classname = msg_spec_.get_value_string("classname");
    const std::string package = msg_spec_.get_value_string("namespace");

    // The relay checks every member, inside nested messages too, against the
    // shared test values.
    std::vector<leaf_t> leaves;
    if (false == relay_leaves(leaves, errorcode))
    {
        return false;
    }

    ss_ << "// Code generated by wiregen. DO NOT EDIT.\n\n";
    ss_ << "// Cross-language relay: <program> <input file> <output file>\n";
    ss_ << "package " << package << "\n\n";
    ss_ << "import (\n";
    ss_ << "\t\"bytes\"\n";
    ss_ << "\t\"fmt\"\n";
    ss_ << "\t\"os\"\n";
    ss_ << ")\n\n";

    ss_ << "func relayExpected() *" << classname << " {\n";
    ss_ << "\ts := &" << classname << "{}\n";
    // The relay is in the messages' package, so it reaches nested ones by field.
    for (auto& leaf : leaves)
    {
        ss_ << set_line("s" + leaf.join_parents(".", ""), leaf.member);
    }
    ss_ << "\treturn s\n";
    ss_ << "}\n\n";

    ss_ << "func main() {\n";
    ss_ << "\tif len(os.Args) != 3 {\n";
    ss_ << "\t\tfmt.Fprintf(os.Stderr, \"usage: %s <input file> <output file>\\n\", os.Args[0])\n";
    ss_ << "\t\tos.Exit(2)\n";
    ss_ << "\t}\n\n";

    ss_ << "\tfailures := 0\n";
    ss_ << "\tfail := func(format string, args ...any) {\n";
    ss_ << "\t\tfmt.Printf(\"FAIL go: \"+format+\"\\n\", args...)\n";
    ss_ << "\t\tfailures++\n";
    ss_ << "\t}\n\n";

    ss_ << "\tdata, err := os.ReadFile(os.Args[1])\n";
    ss_ << "\tif err != nil {\n";
    ss_ << "\t\tfmt.Printf(\"FAIL go: %v\\n\", err)\n";
    ss_ << "\t\tos.Exit(1)\n";
    ss_ << "\t}\n";
    ss_ << "\tgot := &" << classname << "{}\n";
    ss_ << "\tif len(data) != got.Size() {\n";
    ss_ << "\t\tfmt.Printf(\"FAIL go: input is %d bytes, Size() is %d\\n\", len(data), got.Size())\n";
    ss_ << "\t\tos.Exit(1)\n";
    ss_ << "\t}\n";
    ss_ << "\tif err := got.Deserialize(data); err != nil {\n";
    ss_ << "\t\tfmt.Printf(\"FAIL go: Deserialize: %v\\n\", err)\n";
    ss_ << "\t\tos.Exit(1)\n";
    ss_ << "\t}\n\n";

    ss_ << "\twant := relayExpected()\n";
    for (auto& leaf : leaves)
    {
        const std::string name = leaf.join(".");
        const std::string getter = leaf.join_parents(".", "") + ".Get_" + leaf.path.back() + "()";
        ss_ << "\tif g, w := got" << getter << ", want" << getter << "; g != w {\n";
        ss_ << "\t\tfail(\"member " << name << " differs\\n    got  %v\\n    want %v\", g, w)\n";
        ss_ << "\t}\n";
    }
    ss_ << "\tif !got.Equals(want) {\n";
    ss_ << "\t\tfail(\"Equals() is false\")\n";
    ss_ << "\t}\n\n";

    ss_ << "\tout := got.Serialize()\n";
    ss_ << "\tif !bytes.Equal(out, data) {\n";
    ss_ << "\t\tfail(\"re-serialized bytes differ from the input\\n    got  % x\\n    want % x\", out, data)\n";
    ss_ << "\t}\n";
    ss_ << "\tif err := os.WriteFile(os.Args[2], out, 0o644); err != nil {\n";
    ss_ << "\t\tfail(\"%v\", err)\n";
    ss_ << "\t}\n\n";

    ss_ << "\tif failures > 0 {\n";
    ss_ << "\t\tos.Exit(1)\n";
    ss_ << "\t}\n";
    ss_ << "\tfmt.Printf(\"PASS go: %d bytes, " << leaves.size() << " members intact\\n\", len(data))\n";
    ss_ << "}\n";

    results_["relay"] = ss_.str();

    return true;
}

