#include <cstdio>
#include <vector>
#include "proto3testgenerator.h"
#include "test_values.h"

namespace skyloupe
{

bool Proto3TestGenerator::generate(int& errorcode)
{
    errorcode = 0;

    results_.clear();

    if (false == do_test_implementation(errorcode))
    {
        errorcode |= SW_FILE_IMP;
        return false;
    }

    return true;
}

bool Proto3TestGenerator::do_test_implementation(int& errorcode)
{
    std::string& test_string_out = results_["unittest"];

    if (msg_spec_.get_proto().members_size() == 0)
    {
        errorcode |= SW_LANG_NOMEMBERS;
        return false;
    }

    // The expected bytes are computed here, not by protoc, so the test catches
    // a .proto whose types don't encode the way the C++ PZ stream does.
    std::vector<uint8_t> wire;
    for (auto& member : ordered_members_)
    {
        if (false == test_values::encode_pb(std::get<member_type>(member.second), member.first,
                                            std::get<member_length>(member.second), wire))
        {
            errorcode |= SW_LANG_UNSUPPORTED_TYPE;
            return false;
        }
    }

    ss_ << "# Code generated by wiregen. DO NOT EDIT.\n";
    ss_ << "# expected: ";
    for (uint8_t byte : wire)
    {
        char hex[4];
        std::snprintf(hex, sizeof(hex), "%02x", byte);
        ss_ << hex;
    }
    ss_ << "\n";

    for (auto& member : ordered_members_)
    {
        ss_ << std::get<member_name>(member.second) << ": "
            << test_values::textproto_value(std::get<member_type>(member.second), std::get<member_length>(member.second))
            << "\n";
    }

    test_string_out.append(ss_.str());

    return true;
}

}
