bool RustTestGenerator::generate(int& errorcode)
{
    errorcode = 0;

    results_.clear();

    if (false == do_test_implementation(errorcode))
    {
        errorcode |= SW_FILE_IMP;
        return false;
    }

    return true;
}

std::string RustTestGenerator::rust_type(const std::string& type)
{
    return lang_spec_.get_value_string(type);
}

std::string RustTestGenerator::byte_string(const std::string& value)
{
    std::string literal = "b\"";
    for (unsigned char c : value)
    {
        if (c == '"' || c == '\\')
        {
            literal += '\\';
            literal += static_cast<char>(c);
        }
        else if (c < 0x20 || c > 0x7e)
        {
            char hex[8];
            std::snprintf(hex, sizeof(hex), "\\x%02x", c);
            literal += hex;
        }
        else
        {
            literal += static_cast<char>(c);
        }
    }
    return literal + "\"";
}

namespace
{

// bytes as a Rust array literal, eight to a line as in a hex dump, at the
// given indent; the statement holding it is #[rustfmt::skip].
std::string byte_array(const std::vector<uint8_t>& bytes, const std::string& indent)
{
    std::string out = "[";
    for (size_t i = 0; i < bytes.size(); i++)
    {
        out += (i % 8 == 0 ? "\n" + indent + "    " : " ");
        char hex[8];
        std::snprintf(hex, sizeof(hex), "0x%02x,", bytes[i]);
        out += hex;
    }
    return out + "\n" + indent + "]";
}

}

bool RustTestGenerator::do_test_implementation(int& errorcode)
{
    std::string& test_string_out = results_["unittest"];

    const std::string classname = msg_spec_.get_value_string("classname");

    if (msg_spec_.get_proto().members_size() == 0)
    {
        errorcode |= SW_LANG_NOMEMBERS;
        return false;
    }

    ss_ << "// Code generated by wiregen. DO NOT EDIT.\n\n";
    ss_ << "#![cfg(test)]\n";
    // The shared double test value, 3.14159, looks like an approximation of
    // PI to clippy.
    ss_ << "#![allow(clippy::approx_constant)]\n\n";
    ss_ << "use super::" << RustGenerator::module_name(classname) << "::" << classname << ";\n\n";

    do_sample(errorcode);

    ss_ << "#[test]\n";
    ss_ << "fn round_trip() {\n";
    ss_ << "    let msg = sample();\n";
    ss_ << "    let wire = msg.serialize();\n";
    ss_ << "    assert_eq!(wire.len(), msg.size());\n";
    ss_ << "    assert_eq!(wire.len(), " << classname << "::SIZE);\n";
    ss_ << "    let got = " << classname << "::from_bytes(&wire).unwrap();\n";
    ss_ << "    assert!(got.equals(&msg));\n";
    ss_ << "    assert_eq!(got, msg);\n";
    ss_ << "}\n\n";

    // A short read must fail without changing the message: start from the
    // sample, so a partial read of zeros would show.
    ss_ << "#[test]\n";
    ss_ << "fn short_buffer() {\n";
    ss_ << "    let mut got = sample();\n";
    ss_ << "    let zeros = vec![0u8; " << classname << "::SIZE - 1];\n";
    ss_ << "    let err = got.deserialize(&zeros).unwrap_err();\n";
    ss_ << "    assert_eq!(err.kind(), std::io::ErrorKind::UnexpectedEof);\n";
    ss_ << "    assert_eq!(got, sample());\n";
    ss_ << "    assert!(" << classname << "::from_bytes(&[]).is_err());\n";
    ss_ << "}\n\n";

    ss_ << "#[test]\n";
    ss_ << "fn serialize_into_appends() {\n";
    ss_ << "    let msg = sample();\n";
    ss_ << "    let mut out = vec![0xee];\n";
    ss_ << "    msg.serialize_into(&mut out);\n";
    ss_ << "    assert_eq!(out[0], 0xee);\n";
    ss_ << "    assert_eq!(out[1..], msg.serialize()[..]);\n";
    ss_ << "}\n\n";

    ss_ << "#[test]\n";
    ss_ << "fn deserialize_ignores_trailing_bytes() {\n";
    ss_ << "    let msg = sample();\n";
    ss_ << "    let mut wire = msg.serialize();\n";
    ss_ << "    wire.push(0xee);\n";
    ss_ << "    assert_eq!(" << classname << "::from_bytes(&wire).unwrap(), msg);\n";
    ss_ << "}\n";

    do_expected_wire(errorcode);
    do_bitfield_setters(errorcode);
    do_string_setters(errorcode);
    do_text_tests(classname);
    do_bson_tests(classname);

    test_string_out.append(ss_.str());

    return true;
}

bool RustTestGenerator::do_sample(int& errorcode)
{
    const std::string classname = msg_spec_.get_value_string("classname");

    std::string sets;
    for (auto& member : ordered_members_)
    {
        sets += set_line("s", member.second);
    }

    ss_ << "fn sample() -> " << classname << " {\n";
    if (sets.empty())
    {
        // Only nested messages, left at their defaults.
        ss_ << "    " << classname << "::default()\n";
    }
    else
    {
        ss_ << "    let mut s = " << classname << "::default();\n";
        ss_ << sets;
        ss_ << "    s\n";
    }
    ss_ << "}\n\n";

    return true;
}

std::string RustTestGenerator::set_line(const std::string& target, const member_desc_t& member)
{
    const std::string& type = std::get<member_type>(member);
    const std::string& name = std::get<member_name>(member);

    if (is_string_type(type))
    {
        return "    " + target + ".set_" + name + "(" + byte_string(test_values::string_value()) + ");\n";
    }
    if (test_values::literal(type))
    {
        return "    " + target + ".set_" + name + "(" + test_literal(member) + ");\n";
    }
    return "";
}

// The expected bytes are computed by the generator, not by the generated
// Rust, so this test catches wire-format bugs (byte order, padding, width)
// that a self round trip cannot. Native-endian members use the byte order of
// the host running wiregen. rustfmt would put many bytes on a line; eight
// read better against a hex dump.
bool RustTestGenerator::do_expected_wire(int& errorcode)
{
    std::vector<uint8_t> wire;
    if (false == expected_wire(wire))
    {
        return true;
    }

    ss_ << "\n#[test]\n";
    ss_ << "fn wire() {\n";
    ss_ << "    #[rustfmt::skip]\n";
    ss_ << "    let want: [u8; " << wire.size() << "] = [";
    for (size_t i = 0; i < wire.size(); i++)
    {
        ss_ << (i % 8 == 0 ? "\n        " : " ");

        char hex[8];
        std::snprintf(hex, sizeof(hex), "0x%02x,", wire[i]);
        ss_ << hex;
    }
    ss_ << "\n    ];\n";
    ss_ << "    assert_eq!(sample().serialize(), want);\n";
    ss_ << "}\n";

    return true;
}

// A bitfield setter keeps only the field's bits: a value with a bit set
// above the field reads back as the field's value. A signed type's value is
// written as its unsigned bit pattern and cast, since a hex literal above
// the type's maximum doesn't compile.
bool RustTestGenerator::do_bitfield_setters(int& errorcode)
{
    const std::string classname = msg_spec_.get_value_string("classname");

    std::string body;
    for (auto& member : ordered_members_)
    {
        const std::string wide = out_of_range_hex(member.second);
        if (wide.empty())
        {
            continue;
        }
        const std::string& name = std::get<member_name>(member.second);
        const std::string& type = std::get<member_type>(member.second);
        std::string value = wide;
        if (bitfields::is_signed(type))
        {
            value = wide + rust_type(bitfields::unsigned_type(type)) + " as " + rust_type(type);
        }
        body += "    s.set_" + name + "(" + value + ");\n";
        body += "    assert_eq!(s." + RustGenerator::identifier(name) + "(), " + test_literal(member.second) + ");\n";
    }

    if (body.empty())
    {
        return true;
    }

    ss_ << "\n#[test]\n";
    ss_ << "fn bitfield_setters() {\n";
    ss_ << "    let mut s = " << classname << "::default();\n";
    ss_ << body;
    ss_ << "}\n";

    return true;
}

// A string setter truncates a longer value and zero-pads a shorter one.
bool RustTestGenerator::do_string_setters(int& errorcode)
{
    const std::string classname = msg_spec_.get_value_string("classname");

    std::string body;
    for (auto& member : ordered_members_)
    {
        if (false == is_string_type(std::get<member_type>(member.second)))
        {
            continue;
        }
        const std::string& name = std::get<member_name>(member.second);
        const std::string getter = "s." + RustGenerator::identifier(name) + "()";
        const std::string length = std::to_string(std::get<member_length>(member.second));

        body += "    s.set_" + name + "(&[b'x'; " + length + " + 1]);\n";
        body += "    assert_eq!(" + getter + ", &[b'x'; " + length + "]);\n";
        body += "    s.set_" + name + "(b\"y\");\n";
        body += "    assert_eq!(" + getter + "[0], b'y');\n";
        body += "    assert!(" + getter + "[1..].iter().all(|&b| b == 0));\n";
    }

    if (body.empty())
    {
        return true;
    }

    ss_ << "\n#[test]\n";
    ss_ << "fn string_setters() {\n";
    ss_ << "    let mut s = " << classname << "::default();\n";
    ss_ << body;
    ss_ << "}\n";

    return true;
}

// The JSON and XML tests: the exact text (the same in every language, from
// test_values), a round trip, from bytes too, an empty object or element
// reading as the default, and malformed or out-of-range input failing.
void RustTestGenerator::do_text_tests(const std::string& classname)
{
    for (const std::string format : { "json", "xml" })
    {
        if ((format == "json" && false == wants_json()) || (format == "xml" && false == wants_xml()))
        {
            continue;
        }
        const bool json = format == "json";
        std::string expected;
        const bool have_expected = json ? expected_json(expected) : expected_xml(expected);

        ss_ << "\n#[test]\n";
        ss_ << "fn " << format << "() {\n";
        ss_ << "    let msg = sample();\n";
        ss_ << "    let text = msg.to_" << format << "();\n";
        if (have_expected)
        {
            ss_ << "    #[rustfmt::skip]\n";
            ss_ << "    let want: &[u8] = " << byte_string(expected) << ";\n";
            ss_ << "    assert_eq!(text.as_bytes(), want);\n";
        }
        ss_ << "    let got = " << classname << "::from_" << format << "(&text).unwrap();\n";
        ss_ << "    assert_eq!(got, msg);\n";
        ss_ << "    assert_eq!(got.to_" << format << "(), text);\n";
        ss_ << "    assert_eq!(" << classname << "::from_" << format << "(text.as_bytes()).unwrap(), msg);\n";
        ss_ << "}\n";

        ss_ << "\n#[test]\n";
        ss_ << "fn " << format << "_empty_is_default() {\n";
        ss_ << "    let got = " << classname << "::from_" << format << "("
            << byte_string(json ? "{}" : "<" + classname + "/>") << ").unwrap();\n";
        ss_ << "    assert_eq!(got, " << classname << "::default());\n";
        ss_ << "}\n";

        ss_ << "\n#[test]\n";
        ss_ << "fn " << format << "_rejects() {\n";
        ss_ << "    #[rustfmt::skip]\n";
        ss_ << "    let texts: &[&[u8]] = &[\n";
        for (const auto& text : json ? rejected_json() : rejected_xml())
        {
            ss_ << "        " << byte_string(text) << ",\n";
        }
        ss_ << "    ];\n";
        ss_ << "    for text in texts {\n";
        ss_ << "        let got = " << classname << "::from_" << format << "(text);\n";
        ss_ << "        let err = got.expect_err(&String::from_utf8_lossy(text));\n";
        ss_ << "        assert_eq!(err.kind(), std::io::ErrorKind::InvalidData);\n";
        ss_ << "    }\n";
        ss_ << "}\n";
    }
}

// The BSON tests: the exact bytes (from test_values), a round trip, an empty
// document reading as the default, uint64_t values above 2^63-1 as
// Decimal128, and malformed or out-of-range documents failing.
void RustTestGenerator::do_bson_tests(const std::string& classname)
{
    if (false == wants_bson())
    {
        return;
    }
    std::vector<uint8_t> expected;
    const bool have_expected = expected_bson(expected);

    ss_ << "\n#[test]\n";
    ss_ << "fn bson() {\n";
    ss_ << "    let msg = sample();\n";
    ss_ << "    let data = msg.to_bson();\n";
    if (have_expected)
    {
        ss_ << "    #[rustfmt::skip]\n";
        ss_ << "    let want: [u8; " << expected.size() << "] = " << byte_array(expected, "    ") << ";\n";
        ss_ << "    assert_eq!(data, want);\n";
    }
    ss_ << "    let got = " << classname << "::from_bson(&data).unwrap();\n";
    ss_ << "    assert_eq!(got, msg);\n";
    ss_ << "    assert_eq!(got.to_bson(), data);\n";
    ss_ << "}\n";

    ss_ << "\n#[test]\n";
    ss_ << "fn bson_empty_is_default() {\n";
    ss_ << "    let got = " << classname << "::from_bson([5, 0, 0, 0, 0]).unwrap();\n";
    ss_ << "    assert_eq!(got, " << classname << "::default());\n";
    ss_ << "}\n";

    // A uint64_t above 2^63-1 is a Decimal128, so no tool sees it negative;
    // 2^63-1 itself is still an int64.
    for (auto& member : ordered_members_)
    {
        const std::string& name = std::get<member_name>(member.second);
        if (std::get<member_type>(member.second) != "uint64_t" || is_bitfield(member.second))
            continue;
        std::vector<uint8_t> big, edge;
        test_values::bson_decimal128(name, 0, 0xFFFFFFFFFFFFFFFFull, false, big);
        test_values::bson_int64(name, 0x7FFFFFFFFFFFFFFFll, edge);
        ss_ << "\n#[test]\n";
        ss_ << "fn bson_large_uint64_" << name << "() {\n";
        ss_ << "    #[rustfmt::skip]\n";
        ss_ << "    let big: &[u8] = &" << byte_array(big, "    ") << ";\n";
        ss_ << "    #[rustfmt::skip]\n";
        ss_ << "    let edge: &[u8] = &" << byte_array(edge, "    ") << ";\n";
        ss_ << "    for (value, element) in [(u64::MAX, big), (u64::MAX >> 1, edge)] {\n";
        ss_ << "        let mut msg = " << classname << "::default();\n";
        ss_ << "        msg.set_" << name << "(value);\n";
        ss_ << "        let data = msg.to_bson();\n";
        ss_ << "        assert!(data.windows(element.len()).any(|w| w == element));\n";
        ss_ << "        assert_eq!(" << classname << "::from_bson(&data).unwrap(), msg);\n";
        ss_ << "    }\n";
        ss_ << "}\n";
    }

    ss_ << "\n#[test]\n";
    ss_ << "fn bson_rejects() {\n";
    ss_ << "    let good = " << classname << "::default().to_bson();\n";
    ss_ << "    let mut longer = good.clone();\n";
    ss_ << "    longer.push(0);\n";
    ss_ << "    let mut miscounted = good.clone();\n";
    ss_ << "    miscounted[0] += 1;\n";
    ss_ << "    let mut docs = vec![good[..good.len() - 1].to_vec(), longer, miscounted];\n";
    for (const auto& doc : rejected_bson())
    {
        ss_ << "    #[rustfmt::skip]\n";
        ss_ << "    docs.push(vec!" << byte_array(doc, "    ") << ");\n";
    }
    ss_ << "    for doc in &docs {\n";
    ss_ << "        let err = " << classname << "::from_bson(doc).expect_err(&format!(\"{doc:02x?}\"));\n";
    ss_ << "        assert_eq!(err.kind(), std::io::ErrorKind::InvalidData);\n";
    ss_ << "    }\n";
    ss_ << "}\n";
}

