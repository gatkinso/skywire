"""Write the Homebrew formula for a skywire release.

    make_formula.py 0.9.0 SHA256SUMS                  # print skywire.rb
    make_formula.py 0.9.0 SHA256SUMS -o skywire.rb
    make_formula.py 0.9.0 dist/SHA256SUMS --url-base file:///path/to/dist

VERSION is the archive's version, the tag without its v (0.10.0-rc1 for
v0.10.0-rc1). SHA256SUMS is the release's checksum file; the formula takes
the macOS arm64 archive's from it. The URL is the GitHub release's download,
or URL_BASE/<archive> with --url-base.

The formula installs the archive as it is: wiregen, the runtime headers, the
lang files, the CMake package and skywire.pc. It depends on protozero, which
generated C++ needs. It is for Apple silicon Macs only: there is no macOS
x86_64 archive, and on Linux the release tarball needs nothing installed.
"""

import argparse
import re
import sys

REPOSITORY = "https://github.com/gatkinso/skywire"

# The archive the formula installs.
OS, ARCH = "macos", "arm64"

TEMPLATE = """\
# Generated by packaging/homebrew/make_formula.py in {repository}.
class Skywire < Formula
  desc "Generates C, C++, Swift, Go and more for fixed-layout binary messages"
  homepage "{repository}"
  url "{url}"
  version "{version}"
  sha256 "{sha256}"
  license "Apache-2.0"

  depends_on arch: :arm64
  depends_on :macos
  # Every generated C++ message includes protozero.
  depends_on "protozero"

  def install
    prefix.install "bin", "include", "lib", "share"
  end

  test do
    assert_equal "wiregen #{{version.major_minor_patch}}",
                 shell_output("#{{bin}}/wiregen --version").strip

    (testpath/"Point.json").write <<~JSON
      {{
        "stringValues": {{ "classname": "Point" }},
        "members": {{
          "1": {{ "type": "uint16_t", "name": "x", "endian": 0 }},
          "2": {{ "type": "uint16_t", "name": "y", "endian": 1 }}
        }}
      }}
    JSON
    system bin/"wiregen", "--language", "c", "--write_to_file", "--silent",
           "--input_file", "Point.json", "--outdir", testpath

    (testpath/"main.c").write <<~C
      #include <string.h>
      #include "cstream.h"
      #include "Point.h"

      int main(void)
      {{
          Point p;
          Cstream s;
          unsigned char bytes[4];
          static const unsigned char expected[4] = {{0x12, 0x34, 0x78, 0x56}};
          uint16_t x = 0x1234, y = 0x5678;

          memset(&p, 0, sizeof p);
          Set_Point_x(&p, &x);
          Set_Point_y(&p, &y);
          if (cstream_init(&s, 0) != 0 || Point_Serialize(&p, &s) != 0 ||
              cstream_available(&s) != 4 ||
              cstream_read(&s, bytes, 4, SW_NATIVE_ENDIAN_FLAG) != 0)
              return 1;
          cstream_fini(&s);
          return memcmp(bytes, expected, 4) != 0;
      }}
    C
    system ENV.cc, "-std=c99", "-I#{{include}}/skywire", "-I#{{testpath}}",
           "main.c", *Dir["*.c"].reject {{ |f| f == "main.c" }}, "-o", "point"
    system "./point"
  end
end
"""


def read_sum(path, name):
    """Returns the sha256 of the archive NAME in SHA256SUMS."""
    with open(path) as f:
        for line in f:
            fields = line.split()
            if len(fields) == 2 and fields[1].lstrip("*") == name:
                return fields[0]
    sys.exit(f"{path} has no {name}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("version", help="the archive's version, e.g. 0.9.0")
    parser.add_argument("sums", help="the release's SHA256SUMS")
    parser.add_argument("--url-base",
                        help="where the archive is (default: the GitHub release)")
    parser.add_argument("-o", "--output", help="write here instead of stdout")
    args = parser.parse_args()

    if not re.fullmatch(r"\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?", args.version):
        sys.exit(f"{args.version!r} is not a version like 0.9.0 or 0.10.0-rc1")
    base = (args.url_base or f"{REPOSITORY}/releases/download/v{args.version}")
    base = base.rstrip("/")

    archive = f"skywire-{args.version}-{OS}-{ARCH}.tar.gz"
    formula = TEMPLATE.format(repository=REPOSITORY, version=args.version,
                              url=f"{base}/{archive}",
                              sha256=read_sum(args.sums, archive))

    if args.output:
        with open(args.output, "w") as f:
            f.write(formula)
    else:
        sys.stdout.write(formula)


if __name__ == "__main__":
    main()
